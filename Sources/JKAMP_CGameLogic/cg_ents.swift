                var wv: Float = 0
                var i: Int32 = 0
                // Raven's record lives to the end of his block, so the block is the closure.
                AddspriteArgStruct.scratch { fxSArgs in
                    //refEntity_t sRef;
                    //memcpy( &sRef, &ent, sizeof( sRef ) );

