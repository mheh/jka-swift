            if cent.currentState.modelGhoul2 != 0 && ent.ghoul2 == nil && ent.hModel == 0 {
                return true
            }

            // add to refresh list
            trap_R_AddRefEntityToScene(ent)

            if cent.bolt3 == 999 {
