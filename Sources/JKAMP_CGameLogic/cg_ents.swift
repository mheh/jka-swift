        }
    }
    /*
    Ghoul2 Insert End
    */
    switch cent.currentState.eType {
    case ET_FX:
        CG_FX(cent)

    case ET_INVISIBLE, ET_PUSH_TRIGGER, ET_TELEPORT_TRIGGER, ET_TERRAIN:
        break

    case ET_GENERAL:
        CG_General(cent)

    case ET_PLAYER:
        CG_Player(cent)

    case ET_ITEM:
        CG_Item(cent)

    case ET_MISSILE:
        CG_Missile(cent)

    case ET_SPECIAL:
        CG_Special(cent)

    case ET_HOLOCRON:
        CG_General(cent)

    case ET_MOVER:
        CG_Mover(cent)

    case ET_BEAM:
        CG_Beam(cent)

    case ET_PORTAL:
        CG_Portal(cent)

    case ET_SPEAKER:
        CG_Speaker(cent)

    case ET_NPC: //An entity that wants to be able to use ghoul2 humanoid (and other) anims. Like a player, but not.
        CG_G2Animated(cent)

    case ET_TEAM:
        CG_TeamBase(cent)

    case ET_BODY:
        CG_General(cent)

    default:
        CG_Error("Bad entity type: %i\n", cent.currentState.eType)
    }
}

