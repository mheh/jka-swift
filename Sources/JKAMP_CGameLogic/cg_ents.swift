                        ent.shaderRGBA[3] = 0
                    } else {
                        ent.shaderRGBA[3] = UInt8(truncatingIfNeeded: (254 - tMult))
                    }

                    if ent.shaderRGBA[3] >= 1 {
                        //add the transparent body section
                        trap_R_AddRefEntityToScene(ent)
                    }

                    ent.renderfx &= ~RF_FORCE_ENT_ALPHA
                    ent.renderfx |= RF_RGB_TINT

