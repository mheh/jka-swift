#!/usr/bin/env python3
"""rosetta.py: the C to Swift type stone a blind transcriptor reads instead of the view files.

Runs the same parse and reach as views.py and writes .claude/rosetta/<c type>.md, one per viewed struct, with one table
row per field: Raven's declaration, the Swift property and its type, and a note for a field the views table did not map.
An index at .claude/rosetta/index.md lists every viewed struct with its view and module, the scalar typedefs, and the
enums with their Swift spelling, so a transcriptor finds the Swift name of any C type in one lookup.

Usage:
  .venv/bin/python rosetta.py                   # writes every file and prints the counts
  .venv/bin/python rosetta.py --only gentity_t  # prints one stone to stdout, writes nothing
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

import clang.cindex as ci
from clang.cindex import CursorKind, TypeKind

from reexport import REPO, VIEW_OF, source_lines
from views import Generator

OUT = REPO / ".claude" / "rosetta"
NOTE = "Generated by tools/oracle-closure/rosetta.py from the C headers and the views table. Do not edit."
PROPERTY = re.compile(r"\s*public (?:var|func) (\w+)(?:\(([^)]*)\))?(?:: (.+?))? \{")


class Rosetta:
    def __init__(self) -> None:
        self.gen = Generator(None)

    # MARK: - One struct

    def field_row(self, field: ci.Cursor, target: str) -> str:
        c_decl = " ".join(field.type.spelling.split()) + " " + field.spelling
        lines = self.gen.accessor(field, target)
        if lines is None:
            return f"| `{c_decl}` | none | The views table has no row for this shape, so the field is not reachable from Swift. |"
        swift: list[str] = []
        for line in lines:
            m = PROPERTY.match(line)
            if not m:
                continue
            name, params, kind = m.group(1), m.group(2), m.group(3)
            if params is not None:
                swift.append(f"`{name}({params})`")
            else:
                swift.append(f"`{name}: {kind}`")
        if not swift:
            # A callback field has no property line, the run method lives in Callbacks.swift.
            return f"| `{c_decl}` | callback | Stored through the generated thunk of `Callbacks.swift`, run through the view's `{field.spelling}` method. |"
        note = ""
        canonical = field.type.get_canonical()
        if canonical.kind == TypeKind.CONSTANTARRAY and not self.gen.is_vec3(field.type):
            note = f"Array of {canonical.element_count}."
        elif canonical.kind == TypeKind.POINTER and swift[0].endswith("`") and "?`" in swift[0]:
            note = "Optional, nil for a NULL pointer."
        return f"| `{c_decl}` | {', '.join(swift)} | {note} |"

    def stone(self, c_name: str) -> list[str]:
        view, target = self.gen.views[c_name]
        record = self.gen.records[c_name]
        sources = source_lines(record)
        module = VIEW_OF[target]
        lines = [
            f"# {c_name}",
            "",
            NOTE,
            "",
            f"Swift view `{module}.{view}`, over one `{c_name}` in C memory. Source: {', '.join(sources) if sources else 'unknown'}.",
            "A field reads and writes through the C struct, so `ent.r.absmin` is Raven's `ent->r.absmin`.",
            "",
            "| C field | Swift | Note |",
            "|---|---|---|",
        ]
        for field in record.get_children():
            if field.kind == CursorKind.FIELD_DECL:
                lines.append(self.field_row(field, target))
        return lines

    # MARK: - The index

    def index(self) -> list[str]:
        lines = [
            "# The type stone",
            "",
            NOTE,
            "",
            "One file per viewed struct sits beside this index. The tables below give the Swift spelling of every other C type a transcriptor meets.",
            "",
            "## Viewed structs",
            "",
            "| C type | Swift view | Module | Stone |",
            "|---|---|---|---|",
        ]
        for c_name in sorted(self.gen.views):
            view, target = self.gen.views[c_name]
            lines.append(f"| `{c_name}` | `{view}` | `{VIEW_OF[target]}` | `.claude/rosetta/{c_name}.md` |")
        lines += ["", "## Scalars and typedefs", "", "| C type | Swift |", "|---|---|"]
        seen: set[str] = set()
        for cur in self.gen.tu.cursor.get_children():
            if cur.kind != CursorKind.TYPEDEF_DECL or cur.spelling in seen or cur.spelling == "qboolean":
                continue
            under = cur.underlying_typedef_type
            if under.get_canonical().get_declaration().kind in (CursorKind.STRUCT_DECL, CursorKind.UNION_DECL):
                continue
            if under.get_canonical().kind in (TypeKind.POINTER, TypeKind.FUNCTIONPROTO):
                continue
            if self.gen.is_vec3(cur.type):
                swift = "JKAShared.vec3_t, which is SIMD3<Float>"
            elif under.get_canonical().kind == TypeKind.CONSTANTARRAY:
                continue
            else:
                mapped = self.gen.scalar(cur.type, "CJKAMP_Game")
                if mapped is None:
                    continue
                swift = mapped
            seen.add(cur.spelling)
            lines.append(f"| `{cur.spelling}` | `{swift}` |")
        lines += [
            "",
            "## Enums",
            "",
            "A C enum is an `Int32` alias, and each case is a bare `Int32` constant with Raven's name, `WP_SABER`, so a body compares and stores it as written.",
            "",
            "| C enum | Swift |",
            "|---|---|",
        ]
        for name in sorted(self.gen.enums):
            if name == "qboolean":
                continue
            lines.append(f"| `{name}` | `{self.gen.qualified(name, 'CJKAMP_Game')}` |")
        lines += [
            "",
            "## Builtins",
            "",
            "| C | Swift |",
            "|---|---|",
            "| `int` | `Int32` |",
            "| `unsigned int` | `UInt32` |",
            "| `short` | `Int16` |",
            "| `float` | `Float` |",
            "| `double` | `Double` |",
            "| `char` in a string | `String` through the view, or `PooledString?` for a `char *` field |",
            "| `qboolean` | `Bool` |",
            "| `void *` | `OpaquePointer?`, only inside a view or a trap |",
        ]
        return lines

    def write(self) -> tuple[int, int]:
        OUT.mkdir(parents=True, exist_ok=True)
        for old in OUT.glob("*.md"):
            old.unlink()
        rows = 0
        for c_name in self.gen.views:
            text = self.stone(c_name)
            rows += sum(1 for line in text if line.startswith("| `"))
            (OUT / f"{c_name}.md").write_text("\n".join(text) + "\n")
        (OUT / "index.md").write_text("\n".join(self.index()) + "\n")
        return len(self.gen.views), rows


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", help="one C type name, printed to stdout, nothing written")
    args = ap.parse_args()
    stone = Rosetta()
    if args.only:
        if args.only == "index":
            print("\n".join(stone.index()))
            return
        if args.only not in stone.gen.views:
            raise SystemExit(f"rosetta.py: no view over {args.only}")
        print("\n".join(stone.stone(args.only)))
        return
    structs, rows = stone.write()
    print(f"rosetta.py: {structs} stones, {rows} field rows, and the index, {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
