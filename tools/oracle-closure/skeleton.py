def header_line(stem: str) -> str:
    """The first line of a generated stub, which names the file of a host by its own suffix."""
    return NOTE.format(stem=stem).replace(f"{stem}.c.", f"{C.file_name(stem)}.")


THUNKS_NOTE = "// Generated by tools/oracle-closure/skeleton.py from the oracle's store sites. Do not edit. Rule 3 and rule 13."


def stub_file(stem: str) -> Path:
    """The stub file of a Raven .c file under the output root. q_shared.c shares its stem with the re-export of q_shared.h in the same target,
    so its stub carries the .c."""
    name = "q_shared.c.swift" if stem == "q_shared" else f"{stem}.swift"
    return Path(target_of(stem)) / name


def stub_path(stem: str) -> Path:
    """The stub file on disk, under out/<unit>/ for a unit whose logic target is not under the output root yet."""
    return C.written(SOURCES / stub_file(stem))


def target_of(stem: str) -> str:
    # q_math.c and q_shared.c are compiled into every module, so their ports live in JKAShared, the step-002 row 1 ruling.
    if stem in ("q_math", "q_shared"):
        return SHARED
    return BG if stem.startswith("bg_") else LOGIC


class Function:
    """One Raven definition and the stub the table gives it, or the reason it has none."""

    def __init__(self, cur: ci.Cursor, stem: str) -> None:
        self.cur = cur
        self.name = cur.spelling
        # The key of the function in the table and the store, the name, with the line for a C++ overload.
        self.key = C.function_key(cur)
        self.stem = stem
        self.line = cur.location.line
        self.static = cur.storage_class == ci.StorageClass.STATIC
        self.params: list[Param] = []
        self.returns: str | None = None
        self.reason: str | None = None
        # The oracle folder of a bg function that a unit with no bg stem names, which is not the folder of the unit.
        self.folder: str | None = None

    @property
    def cite(self) -> str:
        return f"oracle/{self.folder or C.folder_of(self.stem)}/{C.file_name(self.stem)}:{self.line}"

    @property
    def raven_name(self) -> str:
        """The name Raven wrote. The SDK's fortify macro renames `memmove` to `__builtin___memmove_chk` in the parse."""
        return "memmove" if self.name == "__builtin___memmove_chk" else self.name

    @property
    def mapped(self) -> bool:
        return self.reason is None


class Variable:
    """One file-scope variable definition and the entry the stub carries for it, by rule 3 and rule 6."""

    def __init__(self, cur: ci.Cursor, stem: str) -> None:
        self.cur = cur
        self.name = cur.spelling
        self.stem = stem
        self.line = cur.location.line
        self.written = False
        self.swift: str | None = None
        self.reason: str | None = None
        self.view: str | None = None
        self.count = 0
        # The innermost array bound as Raven spelled it, for a `CharBuf`, and Raven's initializer text when a body writes the variable.
        self.bound: str | None = None
        self.data = False
        # Raven's `static` keeps the name to his file. Two files that share a name keep two variables, and the struct's field carries the stem.
        self.static = cur.storage_class == ci.StorageClass.STATIC
        self.shared = False
        # True when Raven's declaration before the initializer holds `const`, `const char *bgToggleableSurfaces[]` of bg_g2_utils.c.
        self.const = False
        # The table Raven walks the pointer over, for a file-scope walk pointer, which the port holds as the index of its slot.
        self.walk: tuple[str, str] | None = None
        # The functions that declare the local, for a local that a BYTE_STORAGE_LOCALS ruling moves to the storage class.
        self.local: tuple[str, ...] = ()
        # True for a local whose ruling names its function, because another function declares a local of the same name.
        self.suffixed = False

    @property
    def parameter(self) -> bool:
        """True for a parameter whose address Raven takes, which a BYTE_STORAGE_LOCALS ruling gives one slot on the storage class."""
        return self.cur.kind == CursorKind.PARM_DECL

    @property
    def spelled(self) -> str:
        """The Swift name of the variable: Raven's name, or the index name of a file-scope walk pointer, `pushed_pIndex`.
        The storage of a parameter takes the function name as a suffix, `key_Com_BlockChecksumKey`, because the parameter keeps Raven's name.
        So does the storage of a local that several functions declare, each with its own allocation, `regs_IsKNI`."""
        if (self.parameter or self.suffixed) and self.local:
            return f"{self.name}_{self.local[0]}"
        return self.walk[1] if self.walk is not None else self.name

    @property
    def field(self) -> str:
        """The property name on the variables struct: the Swift name, or the stem and that name when another file declares the name too."""
        return f"{self.stem}_{self.spelled}" if self.shared else self.spelled

    @property
    def access(self) -> str:
        """`private ` for a name another file declares too, the rule shared function names take, because Swift file-scope names share one module.
        `Skeleton.variable_access` adds `public ` for a global that Raven declares without `static`."""
        return "private " if self.shared else ""

    @property
    def linked(self) -> bool:
        """True for a global with Raven's external linkage, a file-scope variable he declares without `static` in one file alone."""
        return not self.local and not self.static and not self.shared

    @property
    def cite(self) -> str:
        return f"oracle/{C.folder_of(self.stem)}/{C.file_name(self.stem)}:{self.line}"

    @property
    def kind(self) -> str:
        """`storage` for a struct table in C memory, `state` for a written variable, `let` for a constant, `marker` for an unmapped type.
        A data table of records that hold a pointer to a function or to a struct is `state_data`, a hand table on the state object."""
        if self.reason == "storage":
            return "storage_data" if self.data else "storage"
        if self.reason in ("pointer_table", "byte_storage"):
            return self.reason
        if self.reason == "hand_table":
            return "state_data"
        if C.HOST and self.name in HAND_VARS and HAND_VARS[self.name] is not None:
            # An instance of a C++ class or a `std::` container of the host has no view, and the ruling gives it a hand property of the state object.
            # A module keeps the marker of such a variable, so its adopted stems hold their hand forwards as they stand.
            return "hand"
        if self.reason is not None:
            return "marker"
        if self.name in HAND_VARS:
            return "hand"
        if self.written:
            return "state_data" if self.data else "state"
        return "let"


class Macro:
    """One object-like macro Raven wrote inside a .c file, a constant of that file, written into its stub at Raven's line."""

    def __init__(self, cur: ci.Cursor, stem: str) -> None:
        self.cur = cur
        self.name = cur.spelling
        self.stem = stem
        self.line = cur.location.line
        self.shared = False

    @property
    def cite(self) -> str:
        return f"oracle/{C.folder_of(self.stem)}/{C.file_name(self.stem)}:{self.line}"

    @property
    def access(self) -> str:
        return "private " if self.shared else ""


class RustIndex:
    """Every `fn Name(` of the jka-rust crate of the unit and of the bg and qshared crates, with the line the body ends on.
    A borrowed file of the unit reads the jka-rust files of `borrowed_rust` first, where four vehicle files each define `ProcessMoveCommands`."""

    def __init__(self) -> None:
        self.spans: dict[str, tuple[Path, int, int]] = {}
        # A host names a list of crates.
        crates = C.TARGETS["rust"] if isinstance(C.TARGETS["rust"], list) else [C.TARGETS["rust"]]
        for root in [RUST / crate / "src" for crate in crates] + [RUST / "bg" / "src", RUST / "qshared" / "src"]:
            for path in sorted(root.rglob("*.rs")):
                self.index(path, self.spans)
        self.borrowed: dict[str, dict[Path, tuple[Path, int, int]]] = defaultdict(dict)
        for entry in C.TARGETS.get("borrowed_rust", []):
            root = RUST / entry
            for path in [root] if root.is_file() else sorted(root.rglob("*.rs")):
                found: dict[str, tuple[Path, int, int]] = {}
                self.index(path, found)
                for name, span in found.items():
                    self.borrowed[name][path] = span

    def index(self, path: Path, spans: dict[str, tuple[Path, int, int]]) -> None:
        lines = path.read_text(errors="replace").split("\n")
        for i, line in enumerate(lines, start=1):
            m = re.match(r"\s*(?:pub(?:\([^)]*\))?\s+)?(?:unsafe\s+)?fn\s+(\w+)\s*[(<]", line)
            if not m:
                continue
            name = m.group(1)
            end = self.body_end(lines, i - 1)
            spans.setdefault(name, (path, i, end))

    def span(self, name: str, stem: str) -> tuple[Path, int, int] | None:
        """The jka-rust function of one Raven function. A borrowed stem takes the file of its own snake name first,
        `animal_npc.rs` for AnimalNPC.c, then any file of `borrowed_rust`, then the crates of the unit."""
        if stem in C.BORROWED and name in self.borrowed:
            files = self.borrowed[name]
            snake = re.sub(r"(?<=[a-z])(?=[A-Z])", "_", stem).lower()
            own = [span for path, span in files.items() if path.stem == snake]
            return own[0] if own else next(iter(files.values()))
        return self.spans.get(name)

    @staticmethod
    def body_end(lines: list[str], start: int) -> int:
        depth = 0
        opened = False
        for j in range(start, len(lines)):
            for ch in lines[j]:
                if ch == "{":
                    depth += 1
                    opened = True
                elif ch == "}":
                    depth -= 1
            if opened and depth == 0:
                return j + 1
            if not opened and lines[j].rstrip().endswith(";"):
                return j + 1
        return start + 1


class Skeleton:
    def __init__(self, parse: C.Parse, path: Path | None = None) -> None:
        self.parse = parse
        self.tu = parse.game
        self.cgame_tu = parse.cgame
        # A test gives the path of a store in a temporary folder, and every other caller takes the working store.
        self.table = Table(parse, store=path)
        self.table.sweep()
        self.sources: dict[str, SourceFile] = {}
        self.files: dict[str, list[Function]] = defaultdict(list)
        self.by_name: dict[str, Function] = {}
        self.counts: Counter[str] = Counter()
        # The C++ definitions of a host file that have no stub, by file stem and kind, the measure of rule 17.
        self.skipped: dict[str, Counter[str]] = defaultdict(Counter)
        # The classes that own a skipped definition, one line each in the form of the cxx_only.txt that extract.py writes.
        self.cxx_classes: set[str] = set()
        self.collect()
        self.variables: dict[str, list[Variable]] = defaultdict(list)
        self.collect_variables()
        self.macros: dict[str, list[Macro]] = defaultdict(list)
        self.collect_macros()
        self.file_enums = self.collect_file_enums()
        self.stores = self.collect_stores()
        self.stored_names = {fn.name for pairs in self.stores.values() for _, fn in pairs}
        self.record_stores = self.collect_record_stores()
        self.shared_public = self.collect_shared_public()
        self.never_names = self.collect_never()
        # SpeederNPC.c defines `Update` without static, and four other files define it with. Every copy of a shared name is private.
        owners: dict[str, set[str]] = defaultdict(set)
        for stem, fns in self.files.items():
            for fn in fns:
                owners[fn.name].add(target_of(stem) + "/" + stem)
        self.shared_names = {name for name, stems in owners.items() if len(stems) > 1}

    # MARK: - Reading Raven

    def source(self, stem: str) -> SourceFile:
        if stem not in self.sources:
            self.sources[stem] = SourceFile(C.ORACLE / C.folder_of(stem) / C.file_name(stem))
        return self.sources[stem]

    def collect(self) -> None:
        game = (C.ORACLE / ORACLE_DIR).resolve()
        for cur in self.tu.cursor.get_children():
            if C.HOST and (cur.kind in CXX_KINDS or cur.kind in CXX_RECORDS):
                self.skip_cxx(cur, game)
            if cur.kind != CursorKind.FUNCTION_DECL or not cur.is_definition() or not cur.location.file:
                continue
            path = Path(cur.location.file.name).resolve()
            if not C.within(path, game) or path.name != C.file_name(path.stem) or path.name in SKIP:
                continue
            fn = Function(cur, path.stem)
            self.map(fn)
            self.files[path.stem].append(fn)
            self.by_name.setdefault(fn.name, fn)

    def skip_cxx(self, cur: ci.Cursor, game: Path) -> None:
        """Count a C++ definition of a host file that the skeleton writes no stub for, by its file and its kind.
        A class definition counts each method, constructor, and destructor its body defines, and the classes it nests."""
        if not cur.location.file:
            return
        path = Path(cur.location.file.name).resolve()
        if not C.within(path, game) or path.name != C.file_name(path.stem):
            return
        if cur.kind in CXX_RECORDS:
            if cur.is_definition():
                for child in cur.get_children():
                    self.skip_cxx(child, game)
        elif cur.kind in CXX_KINDS and cur.is_definition():
            self.skipped[path.stem][CXX_KINDS[cur.kind]] += 1
            owner = cur.semantic_parent
            if owner is not None and owner.kind in CXX_RECORDS:
                owner = owner.get_definition() or owner
                where = Path(owner.location.file.name).resolve().relative_to(C.REPO)
                self.cxx_classes.add(f"{where}:{owner.location.line} {owner.kind.name.removesuffix('_DECL').lower()} {owner.spelling}")

    def map(self, fn: Function) -> None:
        params = list(fn.cur.get_arguments())
        for i, p in enumerate(params):
            following = params[i + 1] if i + 1 < len(params) else None
            m = self.table.param(p, following, traps=False, owner=fn.name)
            if m is None:
                fn.reason = self.table.marker_reason(p, fn.name)
                return
            m.default = self.cxx_default(fn.cur, i, m.swift)
            fn.params.append(m)
        if fn.cur.type.kind == TypeKind.FUNCTIONPROTO and fn.cur.type.is_function_variadic():
            # Raven's `...` is a printf argument list, and `Format.swift` in JKAShared formats it.
            fn.params.append(Param("args", "any JKAShared.FormatArg...", "bare"))
        result = self.table.result(fn.cur)
        if result is None:
            fn.reason = f"No table row for the return `{fn.cur.result_type.spelling}`."
            return
        fn.returns = result[0]

    def file_scope_cursors(self) -> list[tuple[ci.Cursor, bool]]:
        """The top-level cursors of the game parse, then those of the cgame parse, each with whether it came from the cgame parse.
        A bg block Raven compiles only for the cgame and the ui, `#ifndef QAGAME` at `bg_panimate.c:1756`, exists only in the cgame parse."""
        cursors = [(cur, False) for cur in self.tu.cursor.get_children()]
        if self.cgame_tu is not None:
            cursors += [(cur, True) for cur in self.cgame_tu.cursor.get_children()]
        return cursors

    def method_of(self, name: str) -> tuple[ci.Cursor | None, str | None]:
        """The definition of a C++ method of a hand class and its stem, for a BYTE_STORAGE_LOCALS key of a host.
        The skeleton writes no stub for a method, and a local whose address the method takes still needs storage,
        `height` of CCMLandScape::FlattenArea at cm_terrain.cpp:1356, row X42 R5 of docket 10."""
        if not C.HOST:
            return None, None
        for cur, _ in self.file_scope_cursors():
            if cur.kind == CursorKind.CXX_METHOD and cur.spelling == name and cur.is_definition() and cur.location.file:
                stem = Path(cur.location.file.name).stem
                if stem in self.files:
                    return cur, stem
        return None, None

    def cgame_bg_function(self, cur: ci.Cursor) -> bool:
        """A function of a bg file that the cgame parse compiles and the game parse does not, so its writes count for the bg variables."""
        if not cur.location.file or cur.spelling in self.by_name:
            return False
        path = Path(cur.location.file.name).resolve()
        return path.parent == (C.ORACLE / ORACLE_DIR).resolve() and target_of(path.stem) == BG

    def collect_variables(self) -> None:
        """Every file-scope variable definition of the module, and whether any body in the module writes it."""
        game = (C.ORACLE / ORACLE_DIR).resolve()
        by_name: dict[str, list[Variable]] = defaultdict(list)
        for cur, cgame in self.file_scope_cursors():
            if cur.kind != CursorKind.VAR_DECL or not cur.location.file or cur.storage_class == ci.StorageClass.EXTERN:
                continue
            path = Path(cur.location.file.name).resolve()
            if not C.within(path, game) or path.name != C.file_name(path.stem) or path.name in SKIP:
                continue
            if cgame and (target_of(path.stem) != BG or any(v.name == cur.spelling for v in self.variables[path.stem])):
                continue
            # A file-scope variable with no initializer is C's tentative definition, which clang does not call a definition.
            # It is Raven's variable all the same, zeroed by the loader, so the sweep keeps the first one per name and file.
            previous = next((v for v in self.variables[path.stem] if v.name == cur.spelling), None)
            if previous is not None:
                if cur.is_definition() and not previous.cur.is_definition():
                    self.variables[path.stem].remove(previous)
                else:
                    continue
            var = Variable(cur, path.stem)
            text = self.declaration_text(var)
            # The map reads whether Raven wrote an initializer, so the flag is set before the map.
            var.data = "=" in text and "{" in text.split("=", 1)[1]
            var.const = re.search(r"\bconst\b", text.split("=", 1)[0]) is not None
            self.map_variable(var)
            self.variables[path.stem].append(var)
            by_name[var.name].append(var)
        # A local that a BYTE_STORAGE_LOCALS ruling moves to the storage class stands as a variable of its file, at its first declaration.
        for key, functions in BYTE_STORAGE_LOCALS.items():
            # A key of a local and its function names one local of several that share the name, and its storage takes the suffix.
            name = key[0] if isinstance(key, tuple) else key
            fn = self.by_name.get(functions[0])
            body, stem = (fn.cur, fn.stem) if fn else self.method_of(functions[0])
            local = next((c for c in body.walk_preorder() if c.kind in (CursorKind.VAR_DECL, CursorKind.PARM_DECL) and c.spelling == name),
                         None) if body is not None else None
            if local is None:
                continue
            var = Variable(local, stem)
            var.local = functions
            var.suffixed = isinstance(key, tuple)
            self.map_variable(var)
            self.variables[stem].append(var)
        owners: dict[str, set[str]] = defaultdict(set)
        for stem, variables in self.variables.items():
            for var in variables:
                owners[var.name].add(target_of(stem) + "/" + stem)
        for stem, variables in self.variables.items():
            for var in variables:
                var.shared = len(owners[var.name]) > 1

        def written(node: ci.Cursor) -> None:
            if node.kind == CursorKind.BINARY_OPERATOR or node.kind == CursorKind.COMPOUND_ASSIGNMENT_OPERATOR:
                if binop_assign_op(node):
                    self.note_write(list(node.get_children())[0], by_name)
            elif node.kind == CursorKind.UNARY_OPERATOR:
                tokens = [t.spelling for t in node.get_tokens()]
                if "++" in tokens or "--" in tokens or (tokens and tokens[0] == "&"):
                    kids = list(node.get_children())
                    if kids:
                        self.note_write(kids[0], by_name)
            elif node.kind == CursorKind.CALL_EXPR:
                arguments = list(node.get_children())[1:]
                if node.spelling in MACROS:
                    # The overlay's template says which argument one of Raven's macros writes, so the source of a `VectorCopy` is a read.
                    for i in written_arguments(node.spelling):
                        if i < len(arguments):
                            self.note_write(arguments[i], by_name, arrays_only=True)
                else:
                    # An array passed by name decays to a pointer the callee may write through.
                    for arg in arguments:
                        self.note_write(arg, by_name, arrays_only=True)
            for child in node.get_children():
                written(child)

        for cur, cgame in self.file_scope_cursors():
            if cur.kind == CursorKind.FUNCTION_DECL and cur.is_definition() and (not cgame or self.cgame_bg_function(cur)):
                written(cur)

        # Raven writes a buffer through an alias too, `marker = SaberParms + totallen` and then `*marker = 0`,
        # and the cursor sweep of the table names the buffers a write cursor points into.
        for name in self.table.alias_writes:
            for var in by_name.get(name, []):
                if not var.cur.type.is_const_qualified():
                    var.written = True

    def collect_macros(self) -> None:
        """Every object-like macro of the module's .c files, first per name and file. A name two files define is private in each."""
        game = (C.ORACLE / ORACLE_DIR).resolve()
        for cur in self.tu.cursor.get_children():
            if cur.kind != CursorKind.MACRO_DEFINITION or not cur.location.file:
                continue
            path = Path(cur.location.file.name).resolve()
            if not C.within(path, game) or path.name != C.file_name(path.stem) or path.name in SKIP:
                continue
            tokens = [t.spelling for t in cur.get_tokens()][1:]
            if reexport.is_function_like(cur) or not tokens or set(tokens) <= reexport.KEYWORD_MACROS:
                continue
            if any(m.name == cur.spelling for m in self.macros[path.stem]):
                continue
            self.macros[path.stem].append(Macro(cur, path.stem))
        owners: dict[str, set[str]] = defaultdict(set)
        for stem, macros in self.macros.items():
            for macro in macros:
                owners[macro.name].add(target_of(stem) + "/" + stem)
        for stem, macros in self.macros.items():
            # A host .cpp macro with the name of an exported constant is private, or its `let` hides the export in the whole target.
            # be_aas_entity.cpp:29 defines MASK_SOLID as CONTENTS_PLAYERCLIP, and SV_OrgVisibleBox of sv_bot.cpp reads the MASK_SOLID of bg_public.h:1171.
            exported = self.exported_of(stem) if C.HOST else {}
            for macro in macros:
                macro.shared = len(owners[macro.name]) > 1 or macro.name in exported

    def collect_file_enums(self) -> dict[str, list[tuple[int, list[str]]]]:
        """The .c enums extract.py leaves in their .c file because another .c file declares their names differently, per stem.
        extract.py writes the list into its manifest, and each one becomes private constants at the top of its stub."""
        path = Path(__file__).resolve().parent / "out" / "extract" / C.UNIT / "extract.json"
        found: dict[str, list[tuple[int, list[str]]]] = defaultdict(list)
        # Every run of extract.py that is not a check writes the file, so an absent file is a missing step and not an empty list.
        if not path.exists():
            raise SystemExit(f"skeleton.py: missing {path}. Run extract.py {C.UNIT} first.")
        rows = json.loads(path.read_text()).get("file_enums", [])
        if C.HOST:
            # A host's .cpp file has no constants header, so its enums come from the parse, as its macros do, `edgeName_t` of cm_patch.cpp.
            # An enum with a name that a macro of the module also has stays out, because the stub's `let` would declare the name twice.
            macro_names = {m.name for macros in self.macros.values() for m in macros}
            game = (C.ORACLE / ORACLE_DIR).resolve()
            for cur in self.tu.cursor.get_children():
                if cur.kind != CursorKind.ENUM_DECL or not cur.is_definition() or not cur.location.file:
                    continue
                enum_path = Path(cur.location.file.name).resolve()
                if enum_path.suffix != ".cpp" or not C.within(enum_path, game) or enum_path.name != C.file_name(enum_path.stem):
                    continue
                values = extract.enumerator_values(cur)
                if not values or any(name in macro_names for name, _ in values):
                    continue
                rows.append({"source": f"{enum_path.relative_to(C.REPO.resolve())}:{cur.location.line}", "enumerators": values})
        for row in rows:
            source, line = row["source"].rsplit(":", 1)
            source_path = Path(source)
            if source_path.parent != Path("oracle") / C.folder_of(source_path.stem) or source_path.name in SKIP:
                continue
            lines = [f"/// Source: {row['source']}"]
            # An enumerator with no initializer counts on from the one before it, and the first one counts from 0.
            base, offset = "0", -1
            for name, text in row["enumerators"]:
                if text is None:
                    offset += 1
                else:
                    base, offset = text, 0
                try:
                    value = str(int(base, 0) + offset)
                except ValueError:
                    value = base if offset == 0 else f"({base}) + {offset}"
                lines.append(f"private let {name}: Int32 = {value}")
            found[source_path.stem].append((int(line), lines))
        return found

    def macro_entry(self, macro: Macro) -> list[str]:
        """The stub's line for a .c macro: a let over its expression, or the reason a body spells it at the site."""
        text = " ".join(t.spelling for t in macro.cur.get_tokens())
        lines = [f"/// Source: {macro.cite}"]
        if macro.name in ("true", "false", "inline", "static", "register", "const"):
            # Raven aliases a keyword, `#define true qtrue`, which Swift has as a keyword already, so nothing is written.
            self.counts["macros that alias a keyword"] += 1
            lines += [f"// Raven wrote: #define {text}", "// Swift has the keyword, so a body writes it as is."]
            return lines
        if macro.name in HAND_MACROS:
            self.counts["macros by hand"] += 1
            lines += [f"// Raven wrote: #define {text}", f"// A hand value: {HAND_MACROS[macro.name].reason}."]
            return lines
        tokens = [t.spelling for t in macro.cur.get_tokens()][1:]
        if len(tokens) == 1 and re.fullmatch(r"[A-Za-z_]\w*", tokens[0]):
            alias = self.alias_entry(macro, tokens[0], text)
            if alias is not None:
                return lines + alias
        local = {m.name for m in self.macros[macro.stem]}
        expression = reexport.swift_expression(macro.cur, {}, self.exported_of(macro.stem), local=local, float_suffix=True)
        self.counts["macros"] += 1
        if expression is None:
            self.counts["macros spelled at the site"] += 1
            lines += [f"// Raven wrote: #define {text}",
                      "// The macro's text is not a constant over this file's names, so a body spells its expansion at the site."]
            return lines
        lines.append(f"{macro.access}let {macro.name} = {expression}")
        return lines

    def alias_entry(self, macro: Macro, target: str, text: str) -> list[str] | None:
        """The file-private declaration for an alias of one name: nothing for a Swift type, an accessor on the view that owns a field,
        a forwarding function for a function. None when the target is none of those."""
        doc = f"// Raven wrote: #define {text}"
        if target == "qboolean":
            self.counts["macros that alias a keyword"] += 1
            return [doc, "// Swift has `Bool`, so a body writes it."]
        owners = self.field_owners(target)
        if len(owners) == 1:
            view, swift, settable = owners[0]
            self.counts["macros that alias a field"] += 1
            setter = [f"        nonmutating set {{ self.{target} = newValue }}"] if settable else []
            return [f"extension {view} {{", f"    /// Raven's `#define {text}`, an alias of the field, file-private to this stub.",
                    f"    fileprivate var {macro.name}: {swift} {{", f"        get {{ self.{target} }}"] + setter + ["    }", "}"]
        if macro.name in self.by_name:
            # Raven's define renames a function the module declares too, and Swift takes no second declaration in the module,
            # so a body writes the target's name.
            self.counts["macros that alias a function"] += 1
            return [doc, f"// The module declares `{macro.name}` too, so a body writes `{target}` where Raven wrote `{macro.name}`."]
        fn = self.by_name.get(target)
        visible = {BG: (BG, SHARED), LOGIC: (LOGIC, BG, SHARED), SHARED: (SHARED,)}[target_of(macro.stem)]
        if fn is not None and fn.mapped and target_of(fn.stem) in visible:
            self.counts["macros that alias a function"] += 1
            params = ", ".join(f"_ {p.name}: {p.swift}" for p in fn.params)
            words = ", ".join(f"&{p.name}" if (p.swift or "").startswith("inout ") else p.name for p in fn.params)
            returns = f" -> {fn.returns}" if fn.returns else ""
            return [doc, f"private func {macro.name}({params}){returns} {{", f"    {target}({words})", "}"]
        if target in LIBC_FUNCTIONS:
            self.counts["macros that alias a function"] += 1
            ps, ret, body = LIBC_FUNCTIONS[target]
            params = ", ".join(f"_ {n}: {t}" for n, t in ps)
            return [doc, f"private func {macro.name}({params}) -> {ret} {{", f"    {body}", "}"]
        return None

    def field_owners(self, field: str) -> list[tuple[str, str, bool]]:
        """The views that declare an accessor of this name, with its Swift type and whether it has a setter, read from the view files."""
        if not hasattr(self, "_accessors"):
            self._accessors: dict[str, list[tuple[str, str, bool]]] = defaultdict(list)
            for view_dir in ("JKAShared", "JKAMP", VIEWS):
                for path in (path for root in C.READ_ROOTS for path in (root / view_dir / "Generated" / "Views").glob("*.swift")):
                    text = path.read_text()
                    view = path.stem
                    qualified = view if view_dir == VIEWS else f"{view_dir}.{view}"
                    for m in re.finditer(r"    public var (\w+): ([^{\n]+?) \{\n((?:        [^\n]*\n)*?)    \}", text):
                        self._accessors[m.group(1)].append((qualified, m.group(2).strip(), "nonmutating set" in m.group(3)))
        return self._accessors.get(field, [])

    def exported_of(self, stem: str) -> dict[str, str]:
        return self.table.views.exported_names("CJKAMP" if target_of(stem) == BG else C_TARGET)

    def note_write(self, lvalue: ci.Cursor, by_name: dict[str, list[Variable]], arrays_only: bool = False) -> None:
        """A write marks every file's copy of the name, because the unity parse binds a shared static's uses to one declaration."""
        rooted = root_var(lvalue)
        if rooted is None:
            return
        for var in by_name.get(rooted[0], []):
            if var.cur.type.is_const_qualified():
                continue
            if arrays_only and var.cur.type.get_canonical().kind != TypeKind.CONSTANTARRAY:
                continue
            var.written = True

    def map_variable(self, var: Variable) -> None:
        """The Swift type of a variable, or the reason it has none. A struct table is C storage, never a Swift type."""
        key = next((k for k in (f"{var.stem}:{var.name}", var.name) if k in TYPES), None)
        if key is not None:
            # A TYPES ruling names the variable, because Raven's declared type is not the type he stores through it.
            # A key `stem:name` names the variable of one file, where another file declares the name with another type.
            var.swift = TYPES[key]
            return
        t = var.cur.type
        canonical = t.get_canonical()
        element = canonical
        depth = 0
        if var.name in SCALAR_DATA_TABLES and var.data:
            # tables.py copies Raven's scalar table into C storage, and the view target reads it as a Slots of its scalar.
            var.reason = "storage"
            return
        if element.kind == TypeKind.INCOMPLETEARRAY and var.data:
            # The C++ parse rejects the pointer-to-int cast of Raven's `NETF` on a 64-bit target, so his table of rows keeps no bound.
            # tables.py copies the rows into C storage, where the cast is a warning, so the table is still data.
            element = element.element_type.get_canonical()
            depth += 1
        while element.kind == TypeKind.CONSTANTARRAY:
            element = element.element_type.get_canonical()
            depth += 1
        if element.kind == TypeKind.RECORD:
            # A struct or an array of structs is one zeroed allocation the state object owns, reached through its view.
            record = self.table.views.record_name(element)
            if not record or record not in self.table.views.views:
                where = element.get_declaration().location.file
                header = Path(where.name).name if where is not None and Path(where.name).suffix == ".h" else None
                var.reason = (f"No view for `{' '.join(element.spelling.split())}` of `{header}`." if header
                              else f"No view for `{' '.join(element.spelling.split())}`, a struct Raven defines inside a .c file.")
                return
            if var.data and depth and self.holds_address(element) and not (C.HOST and self.fills_no_address(var, element)):
                # C storage cannot hold the address of a Swift function or of a record the state object owns,
                # so Raven's table is a hand array on the state object, one `<View>Row` per row, with his rows in his order.
                var.reason = "hand_table"
                var.swift = f"[{self.table.views.views[record][0]}Row]"
                return
            if var.data and self.zero_initializer(var):
                # Raven's `= {qfalse, 0, 0}` is C's zero, so the record is the zeroed allocation of the storage kind, not a data table.
                var.data = False
            var.reason = "storage"
            var.view = self.table.views.qualified_view(record, C_TARGET)
            var.count = canonical.element_count if depth and canonical.kind == TypeKind.CONSTANTARRAY else 0
            # A record array of more than one dimension is one flat Slots of every record, `texMods[MAX_SHADER_STAGES][TR_MAX_TEXMODS]`
            # of tr_shader.cpp:102, and a row reads `suffix(from:)` at its first record, the form of the flat two-dimensional tables, row TR17.
            inner = canonical.element_type.get_canonical() if var.count else None
            while inner is not None and inner.kind == TypeKind.CONSTANTARRAY:
                var.count *= inner.element_count
                inner = inner.element_type.get_canonical()
            var.swift = f"Slots<{var.view}>" if depth else var.view
            return
        # The word match keeps `ivec3_t`, an `int[3]`, out, `info` of CCMLandScape::FlattenArea, row X42 R5 of docket 10.
        if self.table.views.is_vec3(t) or (depth and re.search(r"\bvec3_t\b", t.spelling)):
            if depth == 2 and var.local:
                # A BYTE_STORAGE_LOCALS ruling moves a `vec3_t` array local to the storage class, so a body hands it to a Slots parameter.
                var.reason = "byte_storage"
                var.count = canonical.element_count
                var.swift = "Slots<JKAShared.vec3_t>"
                return
            if depth and not self.table.views.is_vec3(t) and var.data and target_of(var.stem) != SHARED:
                # Raven's table of vectors is data, so it takes the shape every data table of the module takes:
                # C storage in the tree's C target with his initializer as written, read as a Slots over that array.
                # The shared module holds its own tables by hand, because the tree's C target is not its own.
                var.reason = "storage"
                var.count = canonical.element_count
                var.swift = "Slots<JKAShared.vec3_t>"
                return
            var.swift = "JKAShared.vec3_t" if not depth or self.table.views.is_vec3(t) else "[JKAShared.vec3_t]"
            return
        named = t.get_named_type() if t.kind == TypeKind.ELABORATED else t
        if named.kind == TypeKind.TYPEDEF and named.spelling == "vec4_t":
            # A scalar `vec4_t` global is one SIMD4 value, as guide line 241 spells the typedef.
            var.swift = "JKAShared.vec4_t"
            return
        # The element type as Raven spelled it, which keeps a typedef that TYPES names.
        # A typedef of an array, `ivec3_t`, has its element type on the canonical type alone.
        typed = ((t if t.kind == TypeKind.CONSTANTARRAY else t.get_canonical()).element_type.spelling if depth == 1 else t.spelling).replace("const ", "")
        if not depth and var.name in self.table.file_walks:
            # Raven walks the pointer over a file-scope table of records, so the port holds the index of the slot it points at.
            var.walk = self.table.file_walks[var.name]
            var.swift = "Int32"
            return
        if element.kind == TypeKind.POINTER:
            pointee = element.get_pointee()
            if pointee.get_canonical().kind == TypeKind.CHAR_S:
                inner = "String"
            elif pointee.get_canonical().kind == TypeKind.VOID and not depth:
                # Raven's `void *` global is an engine handle, the Ghoul2 instance of a trap, spelled as the traps spell it.
                inner = "OpaquePointer?"
            else:
                record = self.table.views.record_name(pointee)
                if not record or record not in self.table.views.views:
                    var.reason = f"No table row for `{' '.join(t.spelling.split())}`."
                    return
                inner = self.table.views.qualified_view(record, C_TARGET) + "?"
                if not depth and var.name in POINTER_SLOT_VARS:
                    # A POINTER_SLOT_VARS ruling makes the pointer one slot of storage, so a body takes its address, `&fs_searchpaths`.
                    # The hand forward reads and writes slot 0 under Raven's name.
                    var.reason = "pointer_table"
                    var.swift = f"Slots<{inner}>"
                    var.view = inner[:-1]
                    var.count = 1
                    return
                if depth == 1:
                    # A file-scope array of struct pointers is C storage the engine may read, reached through a Slots of optional views.
                    var.reason = "pointer_table"
                    var.swift = f"Slots<{inner}>"
                    var.view = inner[:-1]
                    var.count = canonical.element_count
                    return
        elif depth <= 1 and (var.local or var.name in BYTE_STORAGE_VARS) and (element.kind in INT_ELEMENTS or typed in TYPES):
            # A BYTE_STORAGE_LOCALS ruling moves an `int` array local, or an `int` parameter whose address Raven takes, to the storage class.
            # A BYTE_STORAGE_VARS ruling moves a file-scope `int` array that a body steps through a pointer, `tempDependents` of G2_bones.cpp:1219.
            # The body hands it on as bytes, `MD4Final((unsigned char *)digest, &ctx)`, through the `bytes` view of the Slots.
            # A TYPES typedef keeps its spelling, so `UINT4 x[16]` of MD4Transform is a Slots of UInt32 and not of the canonical `unsigned long`.
            var.reason = "byte_storage"
            var.swift = f"Slots<{TYPES.get(typed) or self.table.views.scalar(element, C_TARGET)}>"
            var.count = canonical.element_count if depth else 1
            return
        elif depth == 1 and element.kind in (TypeKind.CHAR_S, TypeKind.UCHAR) and (var.name in BYTE_STORAGE_VARS or var.local):
            # The engine holds the address of this buffer, so it is one zeroed byte allocation with a fixed base, by the BYTE_STORAGE_VARS ruling.
            # A `byte` buffer that a pointer field holds, `cmd_text_buf` of cmd_common.cpp, is a Slots over the allocation, so a body indexes it.
            var.reason = "byte_storage"
            var.swift = "UnsafeMutableRawPointer" if element.kind == TypeKind.CHAR_S else "Slots<JKAShared.byte>"
            var.count = canonical.element_count
            return
        elif depth and element.kind == TypeKind.CHAR_S:
            # A C character array is a `CharBuf` of Raven's bound, the shape a body's buffers take.
            var.swift = "[" * (depth - 1) + "JKAShared.CharBuf" + "]" * (depth - 1)
            var.bound = self.bound_text(var)
            return
        else:
            scalar_type = t
            for _ in range(depth):
                if scalar_type.kind != TypeKind.CONSTANTARRAY:
                    scalar_type = scalar_type.get_canonical()
                scalar_type = scalar_type.element_type
            inner = self.table.views.scalar(scalar_type, C_TARGET)
            if inner is None or not self.table.known(inner):
                var.reason = f"No table row for `{' '.join(t.spelling.split())}`."
                return
        var.swift = "[" * depth + inner + "]" * depth

    def declaration_text(self, var: Variable) -> str:
        """Raven's declaration through its `;`, read from the file. The unity parse drops the initializer of a static two files name alike,
        because one translation unit sees a redefinition, so the cursor's extent is not trusted for a variable."""
        if var.parameter:
            # A parameter ends at its comma or its parenthesis, so its own tokens are the declaration.
            return " ".join(t.spelling for t in var.cur.get_tokens())
        source = self.source(var.stem)
        text = "\n".join(source.lines)
        start_line = var.cur.extent.start.line
        start = sum(len(line) + 1 for line in source.lines[:start_line - 1]) + var.cur.extent.start.column - 1
        depth = 0
        i = start
        while i < len(text):
            ch = text[i]
            if ch in ("\"", "'"):
                # A string or character literal, with backslash escapes, is skipped whole.
                i += 1
                while i < len(text) and text[i] != ch:
                    i += 2 if text[i] == "\\" else 1
            elif ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
            elif ch == ";" and depth == 0:
                return text[start:i]
            i += 1
        return text[start:]

    def holds_address(self, record: ci.Type) -> bool:
        """True when a field of the record is a pointer to a function or to a struct, which Raven's initializer fills with an address."""
        for field in record.get_declaration().get_children():
            if field.kind != CursorKind.FIELD_DECL:
                continue
            t = field.type.get_canonical()
            if t.kind == TypeKind.POINTER and t.get_pointee().get_canonical().kind in (TypeKind.FUNCTIONPROTO, TypeKind.FUNCTIONNOPROTO, TypeKind.RECORD):
                return True
        return False

    def fills_no_address(self, var: Variable, record: ci.Type) -> bool:
        """True when the record has no function pointer field and Raven's initializer takes no address, so C storage holds the rows.
        The field tables of the botlib, `iteminfo_fields` of be_ai_goal.cpp:123, leave `substruct` NULL, row D19."""
        for field in record.get_declaration().get_children():
            if field.kind != CursorKind.FIELD_DECL:
                continue
            t = field.type.get_canonical()
            if t.kind == TypeKind.POINTER and t.get_pointee().get_canonical().kind in (TypeKind.FUNCTIONPROTO, TypeKind.FUNCTIONNOPROTO):
                return False
        # A text, a character literal, or a comment is no address, `{"&&",P_LOGIC_AND, NULL}` of l_script.cpp:79.
        literals = r'"(?:[^"\\]|\\.)*"|\'(?:[^\'\\]|\\.)*\'|//[^\n]*|/\*.*?\*/'
        initializer = re.sub(literals, "", self.declaration_text(var).split("=", 1)[-1], flags=re.S)
        return "&" not in initializer

    def zero_initializer(self, var: Variable) -> bool:
        """True when every value of Raven's initializer is C's zero, `{qfalse, 0, 0}` or `{0}`."""
        text = self.declaration_text(var)
        values = [v.strip() for v in re.split(r"[{},]", text.split("=", 1)[1]) if v.strip()]
        return bool(values) and all(re.fullmatch(r"0+|0*\.0*[fF]?|qfalse|NULL", v) for v in values)

    def exported(self, var: Variable) -> dict[str, str]:
        return self.table.views.exported_names("CJKAMP" if target_of(var.stem) == BG else C_TARGET)

    def bound_text(self, var: Variable) -> str:
        """The innermost array bound, `Int(JKAShared.MAX_QPATH)` when Raven named a macro a module exports, else the number."""
        declaration = self.declaration_text(var).split("=", 1)[0]
        bounds = re.findall(r"\[([^\]]*)\]", declaration)
        t = var.cur.type.get_canonical()
        count = 0
        while t.kind == TypeKind.CONSTANTARRAY:
            count = t.element_count
            t = t.element_type.get_canonical()
        exported = self.exported(var)
        bound = bounds[-1].strip() if bounds else ""
        return f"Int({exported[bound]}.{bound})" if bound in exported else str(count)

    def initializer(self, var: Variable) -> str | None:
        """Raven's initializer as a Swift literal: a number, `qtrue`, `qfalse`, `NULL`, a string, or a macro a module exports. None otherwise."""
        text = self.declaration_text(var)
        if "=" not in text:
            return None
        raw = " ".join(text.split("=", 1)[1].split()).rstrip(";").strip()
        swift = var.swift or ""
        if swift == "Bool":
            return {"qtrue": "true", "qfalse": "false", "1": "true", "0": "false"}.get(raw)
        if raw == "NULL" or (raw == "0" and swift.endswith("?")):
            # Raven writes a null pointer as `NULL` and as `0`, and both are nil in an optional.
            return "nil" if swift.endswith("?") else ('""' if swift == "String" else None)
        if swift == "String" and raw.startswith('"') and raw.endswith('"'):
            return raw
        if re.fullmatch(r"-?\d+", raw):
            return raw
        m = re.fullmatch(r"(-?\d*)\.(\d*)[fF]?", raw)
        if m and (m.group(1).strip("-") or m.group(2)):
            return f"{m.group(1) or '0'}.{m.group(2) or '0'}"
        exported = self.exported(var)
        if re.fullmatch(r"\w+", raw) and raw in exported:
            return f"{exported[raw]}.{raw}"
        if re.fullmatch(r"\w+", raw) and raw in self.module_lets(target_of(var.stem)):
            # A constant the module's own Swift declares, such as an enum Raven defined inside the .c file.
            return raw
        return None

    def module_lets(self, target: str) -> set[str]:
        """Every file-scope `let` name the target's hand and stub Swift declares."""
        if not hasattr(self, "_lets"):
            self._lets: dict[str, set[str]] = {}
        if target not in self._lets:
            names: set[str] = set()
            for path in C.written(SOURCES / target).rglob("*.swift"):
                names |= set(re.findall(r"^(?:public |nonisolated\(unsafe\) )*let (\w+)", path.read_text(), re.M))
            self._lets[target] = names
        return self._lets[target]

    def zero(self, var: Variable) -> str:
        """C's zero for a variable Raven left uninitialized, spelled in the variable's Swift type."""
        counts: list[int] = []
        t = var.cur.type.get_canonical()
        while t.kind == TypeKind.CONSTANTARRAY:
            counts.append(t.element_count)
            t = t.element_type.get_canonical()
        inner = var.swift or ""
        # A vec3_t is a C array of three floats and one Swift value, so only the levels the Swift type spells count.
        counts = counts[:inner.count("[")]
        for _ in counts:
            inner = inner[1:-1]
        if inner.endswith("?"):
            literal = "nil"
        elif inner == "Bool":
            literal = "false"
        elif inner == "String":
            literal = '""'
        elif inner == "JKAShared.vec3_t":
            literal = "vec3_t()"
        elif inner == "JKAShared.vec4_t":
            literal = "vec4_t()"
        elif inner == "JKAShared.CharBuf":
            literal = f"JKAShared.CharBuf({var.bound})"
        else:
            literal = "0"
        for count, depth in zip(reversed(counts), range(len(counts))):
            element = inner if depth == 0 else "[" * depth + inner + "]" * depth
            literal = f"[{element}](repeating: {literal}, count: {count})"
        return literal

    def variable_access(self, var: Variable) -> str:
        """Raven's linkage gives the access: a global he declares without `static` is public, and a `var` where he wrote no `const`.
        A file-scope `let` of a global with no `const` cannot be a `var`, because rule 6 allows no other static, so it keeps its access."""
        # A global the shell's `vmMain` reads is public by ruling E1, `g_entities` and `gSharedBuffer`.
        if not var.shared and var.name in PUBLIC_NAMES:
            return "public "
        if not var.linked or (var.kind == "let" and not var.const):
            return var.access
        # A forward whose type is internal to its target cannot be public, `theROFFSystem` of the hand class `CROFFSystem`.
        if self.names_internal(var.swift or HAND_VARS.get(var.name) or "", target_of(var.stem)):
            return var.access
        return "public "

    def names_internal(self, text: str, target: str) -> bool:
        """True when a Swift spelling names a type that the target declares without `public`."""
        if not hasattr(self, "_internal"):
            self._internal: dict[str, set[str]] = {}
        if target not in self._internal:
            self._internal[target] = self.internal_types(target)
        return bool(set(re.findall(r"\b[A-Za-z_]\w*\b", text)) & self._internal[target])

    def let_prefix(self, var: Variable) -> str:
        """A view and a CharBuf are not Sendable, so their let says so, and a shared static is private to its file."""
        swift = var.swift or ""
        unsafe = "nonisolated(unsafe) " if "?" in swift or "CharBuf" in swift else ""
        return self.variable_access(var) + unsafe

    def variable_entry(self, var: Variable, count: bool = True) -> list[str]:
        """The stub lines of one variable. The signature row reads the same lines with `count` off, so the run counts each variable once."""
        text = self.declaration_text(var)
        # A one-line definition keeps its initializer on the page. A table's initializer is Raven's data, read from the oracle.
        declaration = " ".join(text.split("=", 1)[0].split()) if "\n" in text else " ".join(text.split())
        lines = [f"/// Source: {var.cite}", f"// Raven wrote: {declaration}"]
        kind = var.kind
        initializer = "Raven's initializer" if "=" in text else "C's zero, since Raven wrote no initializer"
        if count:
            self.counts[f"variables, {kind}"] += 1
        if kind == "let" and "=" not in text:
            # Nothing writes it and Raven gave it no value, so it is C's zero for the module's life. A view is not Sendable, so its let says so.
            lines.append(f"{self.let_prefix(var)}let {var.name}: {var.swift} = {self.zero(var)}")
        elif kind == "let":
            lines.append(f"{self.let_prefix(var)}let {var.name}: {var.swift} = {{ () -> {var.swift} in portMissing(\"{var.name}\", source: \"{var.cite}\") }}()")
        elif kind in ("state", "state_data") and target_of(var.stem) == SHARED:
            lines.insert(1, f"// TODO: Port global {var.name}")
            # The home is the stub itself, as q_math holds Raven's `holdrand` in the file-scope `rng`.
            lines.append(f"// Rule 3: a file-scope variable of this stub at Raven's line, the `rng` shape of q_math, with {initializer}.")
        elif kind == "state":
            # The value lives on the generated variables struct the world owns, and the stub carries Raven's name at Raven's line.
            spelled = "bg" if target_of(var.stem) == BG else "world"
            if var.name in NEVER_NULL_VARS:
                lines = [f"/// Source: {var.cite}",
                         f"/// Raven's callers always set `{var.name}`, so a body reads it with no bind. A NULL here traps with the name.",
                         f"{self.variable_access(var)}var {var.name}: {var.swift.rstrip('?')} {{",
                         "    get {",
                         f"        guard let {var.name} = {spelled}.variables.{var.field} else {{ preconditionFailure(\"{var.name} is NULL\") }}",
                         f"        return {var.name}",
                         "    }",
                         f"    set {{ {spelled}.variables.{var.field} = newValue }}",
                         "}"]
            elif var.walk is not None:
                lines = [f"/// Source: {var.cite}",
                         f"/// Raven walks `{var.name}` over `{var.walk[0]}`, so the port holds the index of the slot it points at.",
                         f"{self.variable_access(var)}var {var.spelled}: {var.swift} {{",
                         f"    get {{ {spelled}.variables.{var.field} }}",
                         f"    set {{ {spelled}.variables.{var.field} = newValue }}",
                         "}"]
            else:
                lines = [f"/// Source: {var.cite}",
                         f"{self.variable_access(var)}var {var.name}: {var.swift} {{",
                         f"    get {{ {spelled}.variables.{var.field} }}",
                         f"    set {{ {spelled}.variables.{var.field} = newValue }}",
                         "}"]
        elif kind == "hand":
            if HAND_VARS[var.name] is None:
                lines.append("// No storage, by the HAND_VARS ruling.")
            elif HAND_VARS[var.name].startswith("["):
                # A hand table of rows on the state object, which the stub forwards under Raven's name.
                spelled = "bg" if target_of(var.stem) == BG else "world"
                home = "BgState" if target_of(var.stem) == BG else f"{STATE}World"
                lines = [f"/// Source: {var.cite}", f"/// Raven's table, a hand property of `{home}`, by the HAND_VARS ruling."]
                # KeywordHash_Add writes a row's `next` through a pointer the write sweep does not follow, so the forward always has a setter.
                lines += [f"{self.variable_access(var)}var {var.name}: {HAND_VARS[var.name]} {{",
                          f"    get {{ {spelled}.{var.name} }}",
                          f"    set {{ {spelled}.{var.name} = newValue }}",
                          "}"]
            elif HAND_VARS[var.name].rstrip("?") in CXX_CLASSES.values():
                # A file-scope instance of a C++ class is a hand property of the state object, which the stub forwards under Raven's name,
                # the form of `TheStringPackage` at stringed_ingame.swift:124. An instance by value has no setter, and a pointer has one.
                home = f"{STATE}World"
                lines = [f"/// Source: {var.cite}", f"/// Raven's instance, a hand property of `{home}`, by the HAND_VARS ruling."]
                if HAND_VARS[var.name].endswith("?"):
                    lines += [f"{self.variable_access(var)}var {var.name}: {HAND_VARS[var.name]} {{",
                              f"    get {{ world.{var.name} }}",
                              f"    set {{ world.{var.name} = newValue }}",
                              "}"]
                else:
                    lines.append(f"{self.variable_access(var)}var {var.name}: {HAND_VARS[var.name]} {{ world.{var.name} }}")
            else:
                lines.append(f"// A hand property of the state object, `{HAND_VARS[var.name]}`, by the HAND_VARS ruling.")
        elif kind == "state_data":
            # Raven's data is hand work on the state object, and the stub forwards it under Raven's name.
            home = "BgState" if target_of(var.stem) == BG else f"{STATE}World"
            spelled = "bg" if target_of(var.stem) == BG else "world"
            lines = [f"/// Source: {var.cite}", f"/// Raven's data table, a hand property of `{home}`."]
            if var.written or (var.linked and not var.const):
                # A public global with no `const` is a `var`, so its forward has a setter, `spawns` of g_spawn.c.
                lines += [f"{self.variable_access(var)}var {var.name}: {var.swift} {{",
                          f"    get {{ {spelled}.{var.field} }}",
                          f"    set {{ {spelled}.{var.field} = newValue }}",
                          "}"]
            else:
                # Raven never writes the table and declares it `static` or `const`, so the hand property is a `let` and the forward has no setter.
                lines.append(f"{self.variable_access(var)}var {var.name}: {var.swift} {{ {spelled}.{var.field} }}")
        elif kind == "storage_data":
            # tables.py serves the table from C storage, so the stub carries no marker.
            lines.append("// Raven's data table is C storage in the C target, with his initializer as written, reached as a Slots over the C array, the bg_tables.c shape that tables.py writes.")
        elif kind in ("storage", "pointer_table", "byte_storage"):
            # The allocation lives on the state object's generated storage class, and the stub carries the name at Raven's line.
            spelled = "bg" if target_of(var.stem) == BG else "world"
            lines = [f"/// Source: {var.cite}", f"{self.variable_access(var)}var {var.spelled}: {var.swift} {{ {spelled}.storage.{var.field} }}"]
            if var.local and var.parameter:
                # The ruling gives a parameter whose address Raven takes one slot on the storage class, so the forward carries the rule 24 line.
                lines.insert(1, f"// AI: Raven takes the address of the parameter `{var.name}` of {var.local[0]}. The body copies it into one zeroed slot on the storage class.")
            elif var.local and len(var.local) > 1:
                # The ruling moves Raven's stack local to the storage class, so the forward carries the rule 24 line.
                lines.insert(1, f"// AI: Raven declares `{var.name}` on the stack of {' and '.join(var.local)}. The functions share one zeroed allocation on the storage class.")
            elif var.local and var.cur.storage_class == ci.StorageClass.STATIC:
                # A static local outlives the call, `static vmSymbol_t nullSym` of VM_ValueToFunctionSymbol, so the line names the static.
                lines.insert(1, f"// AI: Raven declares `{var.name}` static in {var.local[0]}. The function uses one zeroed allocation on the storage class.")
            elif var.local:
                lines.insert(1, f"// AI: Raven declares `{var.name}` on the stack of {var.local[0]}. The function uses one zeroed allocation on the storage class.")
        else:
            lines.insert(1, f"// TODO: Port global {var.name}")
            lines.append(f"// {var.reason}")
        return lines

    def collect_stores(self) -> dict[str, list[tuple[str, Function]]]:
        """Every `ent->field = Name` in the module, by field, as (site cite, stored function).
        A store into a function-pointer local of a callback field's type, `func = NPC_Jedi_Pain` of NPC_PainFunc, counts for that field,
        because the function returns the local into the field.
        A local whose type fits more than one field names no field."""
        stores: dict[str, list[tuple[str, Function]]] = defaultdict(list)
        seen: set[tuple[str, str]] = set()
        field_of_proto: dict[str, set[str]] = defaultdict(set)
        for record in self.table.views.records.values():
            if record.spelling == "gentity_s":
                for f in record.get_children():
                    if f.kind == CursorKind.FIELD_DECL and f.spelling in FIELDS:
                        field_of_proto[f.type.get_canonical().get_pointee().get_canonical().spelling].add(f.spelling)

        def stored_field(lhs: ci.Cursor) -> str | None:
            if lhs.kind == CursorKind.MEMBER_REF_EXPR and lhs.spelling in FIELDS:
                return lhs.spelling
            ref = lhs.referenced if lhs.kind == CursorKind.DECL_REF_EXPR else None
            if ref is not None and ref.kind == CursorKind.VAR_DECL and ref.semantic_parent.kind == CursorKind.FUNCTION_DECL:
                canonical = ref.type.get_canonical()
                if canonical.kind == TypeKind.POINTER and canonical.get_pointee().kind == TypeKind.FUNCTIONPROTO:
                    fields = field_of_proto.get(canonical.get_pointee().get_canonical().spelling, set())
                    if len(fields) == 1:
                        return next(iter(fields))
            return None

        def walk(node: ci.Cursor) -> None:
            if node.kind == CursorKind.BINARY_OPERATOR and binop_assign_op(node) == "=":
                lhs, rhs = list(node.get_children())
                field = stored_field(lhs)
                if field is not None:
                    owner = lhs.type.get_canonical()
                    if owner.kind == TypeKind.POINTER and owner.get_pointee().kind == TypeKind.FUNCTIONPROTO:
                        name = rhs_function(rhs)
                        if name and name in self.by_name and (field, name) not in seen:
                            seen.add((field, name))
                            stores[field].append((name, self.by_name[name]))
                        elif name and name not in self.by_name:
                            self.counts["store of a function outside the module"] += 1
            for child in node.get_children():
                walk(child)

        for fns in self.files.values():
            for fn in fns:
                walk(fn.cur)
        return stores

    def collect_record_stores(self) -> dict[str, list[tuple[str, ci.Cursor, Function]]]:
        """Every store of a function into a callback field of a record other than gentity_t, `pVehInfo->Update = Update`, by game file.
        Each entry is the view of the record, the field, and the stored function of that file, or the function of another module.
        Five vehicle files each define a private `Update`, so the thunk of such a store stands in the file of the store."""
        stores: dict[str, list[tuple[str, ci.Cursor, Function]]] = defaultdict(list)
        for stem, fns in self.files.items():
            if target_of(stem) != LOGIC:
                continue
            seen: set[tuple[str, str]] = set()
            own = {fn.name: fn for fn in fns}
            for fn in fns:
                for node in fn.cur.walk_preorder():
                    if node.kind != CursorKind.BINARY_OPERATOR or binop_assign_op(node) != "=":
                        continue
                    lhs, rhs = list(node.get_children())
                    field = lhs.referenced
                    if lhs.kind != CursorKind.MEMBER_REF_EXPR or field is None or field.kind != CursorKind.FIELD_DECL:
                        continue
                    owner = field.type.get_canonical()
                    if owner.kind != TypeKind.POINTER or owner.get_pointee().kind != TypeKind.FUNCTIONPROTO:
                        continue
                    record = self.table.views.record_name(field.semantic_parent.type) or field.semantic_parent.spelling
                    if record == "gentity_t" or record not in self.table.views.views:
                        continue
                    # The unity parse leaves a second file's `static` of the same name unresolved, so the name is read from Raven's text.
                    name = rhs_function(rhs) or self.source(stem).slice(rhs.extent).strip()
                    stored = own.get(name) if name else None
                    # In a host, a function of another file of the same target counts when it is not `static`, as CM_StoreLeafs of cm_test.cpp in cm_trace.cpp.
                    if stored is None and name in self.by_name and (target_of(self.by_name[name].stem) != LOGIC or (C.HOST and not self.by_name[name].static)):
                        stored = self.by_name[name]
                    if stored is None and name:
                        stored = self.bg_function(rhs, name)
                    if stored is None or (field.spelling, name) in seen:
                        continue
                    seen.add((field.spelling, name))
                    stores[stem].append((self.table.views.views[record][0], field, stored))
        return stores

    def bg_function(self, rhs: ci.Cursor, name: str) -> Function | None:
        """The bg function a store names in a unit whose stems hold no bg file, or None.
        The cgame copy of a vehicle file stores `AttachRidersGeneric` of bg_vehicleLoad.c, and the cgame run collects no bg stem."""
        for node in rhs.walk_preorder():
            if node.kind != CursorKind.DECL_REF_EXPR or node.spelling != name or node.referenced is None:
                continue
            definition = node.referenced.get_definition()
            if definition is None or definition.kind != CursorKind.FUNCTION_DECL or not definition.location.file:
                return None
            path = Path(definition.location.file.name).resolve()
            if not path.stem.startswith("bg_"):
                return None
            fn = Function(definition, path.stem)
            fn.folder = str(path.parent.relative_to(C.ORACLE.resolve()))
            self.map(fn)
            return fn
        return None

    def record_thunks_name(self, view: str) -> str:
        """The private namespace of a file's thunks for one record's callback fields, `VehicleInfoThunks`."""
        return f"{view}Thunks"

    def record_thunks(self, stem: str) -> list[str]:
        """The private thunks of one game file for the callback fields of a record other than gentity_t, one static per stored function."""
        lines: list[str] = []
        by_view: dict[str, list[tuple[ci.Cursor, Function]]] = defaultdict(list)
        for view, field, fn in self.record_stores.get(stem, []):
            by_view[view].append((field, fn))
        for view in sorted(by_view):
            lines += [
                f"/// One static per function this file stores in a `{view}` callback field, so each has one address for the life of the module.",
                "/// The thunks stand in this file, because the functions they call are private to it.",
                f"private enum {self.record_thunks_name(view)} {{",
            ]
            named: set[str] = set()
            for field, fn in sorted(by_view[view], key=lambda pair: pair[1].name):
                if fn.name in named:
                    continue
                named.add(fn.name)
                alias = f"{view}{field.spelling[0].upper()}{field.spelling[1:]}"
                lines += self.thunk_lines(alias, field.type.get_canonical().get_pointee(), fn)
                lines.append("")
            lines.pop()
            lines += ["}", ""]
        return lines

    def collect_shared_public(self) -> set[str]:
        """Every function the shared module holds in public, by name, `atof` of CString.swift.
        A bg function of that name stays internal, so a game file that imports both modules reads one `atof`."""
        return {m.group(1) for path in (SOURCES / SHARED).rglob("*.swift") for m in re.finditer(r"^public func `?(\w+)", path.read_text(), re.M)}

    def collect_never(self) -> set[str]:
        """Every Raven function that never returns, by Raven's name, so its declaration returns `Never` as a Swift caller expects.
        The seed is each `-> Never` function the game and shared targets declare, `trap_Error`.
        A void function with no return statement whose last statement calls such a function joins the set, `G_Error` and then `Com_Error` of g_main.
        The shell's `bg.error` closure returns `Never`, so the game's `Com_Error` must say so."""
        never = {m.group(1) for root in C.READ_ROOTS for target in (VIEWS, SHARED) for path in (root / target).rglob("*.swift")
                 for m in re.finditer(r"^public func `?(\w+)`?\(.*\) -> Never \{$", path.read_text(), re.M)}

        def ends_in_never(fn: Function) -> bool:
            body = next((c for c in fn.cur.get_children() if c.kind == CursorKind.COMPOUND_STMT), None)
            if body is None or any(node.kind == CursorKind.RETURN_STMT for node in body.walk_preorder()):
                return False
            statements = list(body.get_children())
            last = statements[-1] if statements else None
            while last is not None and last.kind == CursorKind.UNEXPOSED_EXPR:
                last = next(last.get_children(), None)
            return last is not None and last.kind == CursorKind.CALL_EXPR and last.spelling in never

        grew = True
        while grew:
            grew = False
            for fns in self.files.values():
                for fn in fns:
                    if fn.mapped and fn.returns is None and fn.name not in never and ends_in_never(fn):
                        never.add(fn.name)
                        grew = True
        return never

    def published(self) -> list[tuple[str, str, Variable | None]]:
        """The declarations that Raven's linkage makes public in the logic and bg files of the run, as (stem, Swift name, variable).
        The variable is None for a function, and an overload of one name gives one entry."""
        out: list[tuple[str, str, Variable | None]] = []
        for stem in sorted(set(self.files) | set(self.variables)):
            if target_of(stem) == SHARED:
                continue
            names = dict.fromkeys(swift_name(fn.name) for fn in self.files.get(stem, []) if self.linkage(fn) == "public " and fn.raven_name not in NOT_PORTED)
            out += [(stem, name, None) for name in names]
            out += [(stem, var.spelled, var) for var in self.variables.get(stem, []) if var.linked or (not var.shared and var.name in PUBLIC_NAMES)]
        return out

    def internal_types(self, target: str) -> set[str]:
        """Every type name that a Swift file of the target declares without `public`, `SpawnRow` of g_local.swift before row 7."""
        pattern = re.compile(r"^\s*((?:(?:public|open|private|fileprivate|internal|final|indirect) )*)(?:struct|class|enum|protocol|typealias|actor) (\w+)", re.M)
        names: set[str] = set()
        for root in C.READ_ROOTS:
            for path in (root / target).rglob("*.swift"):
                names |= {m.group(2) for m in pattern.finditer(path.read_text()) if not re.search(r"\b(public|open)\b", m.group(1))}
        return names

    @staticmethod
    def declaration_block(lines: list[str], i: int) -> tuple[str, str]:
        """The head of the declaration at line `i` through its `{` or `=`, and the body through the brace at column 0 that closes it."""
        head: list[str] = []
        j = i
        # A function head runs to the brace of its body over the lines of its parameters, and a variable head is one line.
        function = re.match(r"(?:nonisolated\(unsafe\) )?func ", lines[i]) is not None
        while j < len(lines):
            head.append(lines[j])
            if not function or lines[j].rstrip().endswith("{"):
                break
            j += 1
        j = min(j, len(lines) - 1)
        text = " ".join(head)
        if not lines[j].rstrip().endswith("{"):
            return text, text
        k = j + 1
        while k < len(lines) and lines[k] != "}":
            k += 1
        return text, "\n".join(lines[i:k + 1])

    def kept(self, var: Variable | None, lines: list[str], i: int, internal: set[str]) -> str | None:
        """Why the declaration at line `i` keeps its access, or None when it takes `public`."""
        head, block = self.declaration_block(lines, i)
        # A parameter label is a name and not a type, so the scan drops each word before a colon.
        signature = re.sub(r"\b\w+\s*:", " ", head.split("=", 1)[0] if var is not None else head)
        types = sorted(set(re.findall(r"\b[A-Za-z_]\w*\b", signature)) & internal)
        if types:
            return f"its declaration names the internal type {', '.join(types)}"
        if var is None or var.const:
            return None
        if re.match(r"(?:nonisolated\(unsafe\) )?let ", lines[i]):
            return "Raven declares it without `const`, and a file-scope `let` cannot be a `var` under rule 6"
        # A forward over C storage or over a hand class returns a reference, so a body writes through it with no setter.
        if var.kind not in ("storage", "pointer_table", "byte_storage", "hand") and "{" in head and not re.search(r"\bset\b", block):
            return "Raven declares it without `const`, and its forward has no setter"
        return None

    def publish(self) -> tuple[int, list[str]]:
        """Raven's linkage applied to the adopted logic and bg files, which the writer leaves alone.
        Each declaration that the rule names takes `public` in front of its line, and no other text of the file changes.
        A name with no file-scope declaration line, or a declaration that cannot take the form, is reported and left as it is."""
        changed = 0
        report: list[str] = []
        by_stem: dict[str, list[tuple[str, Variable | None]]] = defaultdict(list)
        for stem, name, var in self.published():
            by_stem[stem].append((name, var))
        internal = {target: self.internal_types(target) for target in {target_of(stem) for stem in by_stem}}
        for stem, entries in sorted(by_stem.items()):
            path = stub_path(stem)
            if not path.exists() or path.read_text().split("\n", 1)[0] == header_line(stem):
                continue
            lines = path.read_text().split("\n")
            for name, var in entries:
                pattern = re.compile(rf"^((?:nonisolated\(unsafe\) )?(?:func|var|let) {re.escape(name)}(?![\w`]))")
                hits = [i for i, line in enumerate(lines) if pattern.match(line)]
                if not hits:
                    if not any(re.match(rf"^(public|private|fileprivate|internal) .*\b(func|var|let) {re.escape(name)}(?![\w`])", line) for line in lines):
                        report.append(f"{path.relative_to(REPO)}: no file-scope declaration of {name}")
                    continue
                for i in hits:
                    reason = self.kept(var, lines, i, internal[target_of(stem)])
                    if reason is not None:
                        report.append(f"{path.relative_to(REPO)}:{i + 1}: {name} keeps its access, because {reason}")
                        continue
                    lines[i] = "public " + lines[i]
                    changed += 1
            path.write_text("\n".join(lines))
        return changed, report

    # MARK: - Emission

    def access(self, fn: Function) -> str:
        """The access of a stub: the access of Raven's linkage, or internal for a signature that names an internal type."""
        access = self.linkage(fn)
        # A signature that names a type internal to its target cannot be public, so the function keeps internal access.
        if access == "public " and self.names_internal(" ".join([p.swift or "" for p in fn.params] + [fn.returns or ""]), target_of(fn.stem)):
            return ""
        return access

    def linkage(self, fn: Function) -> str:
        """Raven's linkage gives the access: a function he declares without `static` is public in its target, so a client target reaches it."""
        # Raven's static is file scope, and five vehicle files each define `Update`, so a static stub is private.
        # A static function the oracle stores in a field stays internal, because its thunk names it from another file.
        if fn.static or fn.name in self.shared_names:
            return "" if fn.name in self.stored_names else "private "
        if target_of(fn.stem) == BG and fn.name in self.shared_public:
            return ""
        return "public "

    def cxx_default(self, cur: ci.Cursor, i: int, swift: str | None) -> str | None:
        """The C++ default of a parameter, from the definition or the first declaration, in the Swift spelling of the parameter.
        `qboolean bZeroit = qfalse` of Z_Malloc is `= false`, `int iAlign = 4` is `= 4`, and a NULL into an optional is `= nil`.
        A default the parameter's spelling cannot hold, or an expression past one token, gives None.
        Swift gives an `inout` parameter no default, so `clipMap_t **clipMap = NULL` of CM_ClipHandleToModel gives None."""
        if swift is not None and swift.startswith("inout "):
            return None
        for decl in (cur, cur.canonical):
            params = list(decl.get_arguments())
            if i >= len(params):
                continue
            tokens = [t.spelling for t in params[i].get_tokens()]
            if not tokens:
                # A parameter whose type is a macro, `SE_BOOL bLoadDebug = SE_TRUE` of SE_Load at stringed_ingame.cpp:910, starts inside the macro's
                # expansion, so its extent gives no token. The default is then the one reference the parse resolved under the parameter.
                refs = [c.referenced.spelling for c in params[i].walk_preorder() if c.kind == CursorKind.DECL_REF_EXPR and c.referenced is not None]
                if len(refs) == 1:
                    tokens = ["=", refs[0]]
            if "=" not in tokens:
                continue
            value = tokens[tokens.index("=") + 1:]
            if value[:1] == ["-"] and len(value) == 2:
                value = ["-" + value[1]]
            if len(value) != 1:
                return None
            text = value[0]
            if re.fullmatch(r"[A-Za-z_]\w*", text):
                # A macro of the default expands to its name, `SE_TRUE` to `qtrue` of SE_LoadLanguage, so the default reads the name the parse resolved.
                ref = next((c.referenced for c in params[i].walk_preorder() if c.kind == CursorKind.DECL_REF_EXPR and c.referenced is not None), None)
                text = ref.spelling if ref is not None else text
            if swift == "Bool":
                return {"qfalse": "false", "false": "false", "0": "false", "qtrue": "true", "true": "true", "1": "true"}.get(text)
            if (swift or "").endswith("?"):
                return "nil" if text in ("NULL", "0", "nullptr") else None
            if re.fullmatch(r"-?\d+", text) and swift in ("Int32", "UInt32", "Int64", "UInt64", "Int16", "UInt16", "Int8", "UInt8", "CLong", "CUnsignedLong"):
                return text
            if re.fullmatch(r"-?(\d+\.\d*|\.\d+)[fF]?", text) and swift in ("Float", "Double"):
                number = text.rstrip("fF")
                return ("0" + number if number.startswith(".") else number) + ("0" if number.endswith(".") else "")
            if re.fullmatch(r"[A-Za-z_]\w*", text) and text not in ("NULL", "nullptr") and swift is not None and not swift.startswith(("inout", "Slots")):
                # An enumerator or a macro constant, which the view target re-exports under Raven's name.
                return text
            return None
        return None

    def signature(self, fn: Function) -> str:
        """The declaration line the table gives the function today, without the brace, so the manifest can carry it after adoption."""
        name = swift_name(fn.name)
        if not fn.mapped:
            return f"{self.access(fn)}func {name}() -> Never"
        # A C++ default of a parameter stays on the Swift parameter, so a caller that omits the argument reads as Raven's call.
        params = ", ".join(f"_ {p.name}: {p.swift}" + (f" = {p.default}" if p.default else "") for p in fn.params)
        returns = "Never" if fn.name in self.never_names and fn.returns is None else fn.returns
        return f"{self.access(fn)}func {name}({params})" + (f" -> {returns}" if returns else "")

    def forward_signature(self, fn: Function) -> str | None:
        """The declaration line of the forward under Raven's name, with the plain inout for each optional inout vector, or None."""
        if not fn.mapped or not any(p.kind in OPTIONAL_INOUTS for p in fn.params):
            return None
        params = ", ".join(f"_ {p.name}: {(p.swift or '')[:-1] if p.kind in OPTIONAL_INOUTS else p.swift}" for p in fn.params)
        returns = "Never" if fn.name in self.never_names and fn.returns is None else fn.returns
        return f"{self.access(fn)}func {swift_name(fn.name)}({params})" + (f" -> {returns}" if returns else "")

    def forward(self, fn: Function) -> list[str]:
        """The forward of a function with an optional inout vector, for the callers that pass a vector, or nothing.
        It wraps each vector in an optional, calls the function, and writes the vector back, so no caller that passes one changes."""
        signature = self.forward_signature(fn)
        if signature is None:
            return []
        opts = [p for p in fn.params if p.kind in OPTIONAL_INOUTS]
        named = ", ".join(f"`{p.name.strip('`')}`" for p in opts)
        lines = [f"/// A caller that passes a vector for {named} reaches `{fn.name}` through this forward, and a NULL caller passes the optional.",
                 f"/// Source: {fn.cite}",
                 f"{signature} {{"]
        words: list[str] = []
        for p in fn.params:
            local = "optional" + p.name.strip("`")[:1].upper() + p.name.strip("`")[1:]
            if p.kind in OPTIONAL_INOUTS:
                lines.append(f"    var {local}: {(p.swift or '').removeprefix('inout ')} = {p.name}")
                lines.append(f"    defer {{ {p.name} = {local}! }}")
                words.append(f"&{local}")
            elif (p.swift or "").startswith("inout "):
                words.append(f"&{p.name}")
            else:
                words.append(p.name)
        word = "return " if fn.returns or fn.name in self.never_names else ""
        lines += [f"    {word}{swift_name(fn.name)}({', '.join(words)})", "}"]
        return lines

    def stub(self, fn: Function) -> list[str]:
        source = self.source(fn.stem)
        lines = source.comment_above(fn.cur)
        lines.append(f"/// Source: {fn.cite}")
        hidden = fn.static or fn.name in self.shared_names
        if hidden and fn.name in self.stored_names:
            self.counts["static functions kept internal for a thunk"] += 1
        if not fn.static and fn.name in self.shared_names:
            self.counts["functions made private because another file defines the name"] += 1
        if fn.raven_name in NOT_PORTED:
            self.counts["not ported by ruling"] += 1
            lines += [f"// Raven wrote: {source.c_signature(fn.cur)}", f"// Not ported: {NOT_PORTED[fn.raven_name]}."]
            return lines
        if not fn.mapped and getattr(self, "_marked", {}).get(fn.stem, {}).get(self.signature(fn), fn.cite) != fn.cite:
            # A C++ overload whose parameters the table cannot shape spells the empty signature of the overload before it,
            # `G2_SetupModelPointers` of G2_API.cpp:2675 and :2773, so it is a marker with no function, the form of a NOT_PORTED stub.
            self.counts["TODO: Port signature"] += 1
            lines += [
                "// TODO: Port signature",
                f"// Raven wrote: {source.c_signature(fn.cur)}",
                f"// {fn.reason}",
                f"// TODO: Port {fn.name}",
                "// An overload before it holds the empty signature, so this marker has no function until the table shapes its parameters.",
            ]
            return lines
        if not fn.mapped:
            self.counts["TODO: Port signature"] += 1
            if not hasattr(self, "_marked"):
                self._marked: dict[str, dict[str, str]] = {}
            # The first function of a signature keeps it, and a second run of the same stub finds its own cite.
            self._marked.setdefault(fn.stem, {}).setdefault(self.signature(fn), fn.cite)
            lines += [
                "// TODO: Port signature",
                f"// Raven wrote: {source.c_signature(fn.cur)}",
                f"// {fn.reason}",
                f"{self.signature(fn)} {{",
            ]
        else:
            self.counts["stubs"] += 1
            if RETURNS.get(fn.name) == "in_place":
                lines.append("// Raven returns the argument, which the caller already holds.")
            lines.append(f"{self.signature(fn)} {{")
            if fn.raven_name in DEAD:
                lines.append(f"    // {DEAD[fn.raven_name]}, so it is dead.")
        lines += [
            f"    // TODO: Port {fn.name}",
            f'    portMissing("{fn.name}", source: "{fn.cite}")',
            "}",
        ]
        return lines

    def file(self, stem: str) -> list[str]:
        target = target_of(stem)
        # A file inside JKAShared imports nothing, because it is the module the others import.
        # Foundation holds the libc math Raven calls, `sqrt`, `sin`, `abs` for his `fabs`, so every stub imports it.
        # A game file also calls bg's functions, `BG_EvaluateTrajectory`, so it imports the bg module beside its view target.
        # A host compiles no bg file, so its stubs import no bg module.
        logic_imports = [f"import {VIEWS}"] + ([] if C.HOST else ["import JKAMP_BG"])
        imports = [] if target == SHARED else ["import Foundation", "import JKAMP", "import JKAShared"] + (logic_imports if target == LOGIC else [])
        lines = [header_line(stem), ""] + (imports + [""] if imports else [])
        # A .c enum whose names another .c file declares differently stands at the top, before the file's other constants.
        for _, enum_lines in self.file_enums.get(stem, []):
            lines += enum_lines + [""]
        entries = [(var.line, 0, var) for var in self.variables.get(stem, [])] + [(m.line, 1, m) for m in self.macros.get(stem, [])]
        for _, kind, entry in sorted(entries, key=lambda e: (e[0], e[1])):
            lines += self.variable_entry(entry) if kind == 0 else self.macro_entry(entry)
            lines.append("")
        for fn in self.files[stem]:
            lines += self.stub(fn)
            lines.append("")
            if fn.raven_name not in NOT_PORTED and self.forward(fn):
                lines += self.forward(fn)
                lines.append("")
        lines += self.record_thunks(stem)
        return lines

    def thunk(self, field: str, fn: Function) -> list[str]:
        """One static per stored function. The closure turns each handle into a view and calls the function by its module name."""
        proto = None
        for record in self.table.views.records.values():
            if record.spelling == "gentity_s":
                for f in record.get_children():
                    if f.kind == CursorKind.FIELD_DECL and f.spelling == field:
                        proto = f.type.get_canonical().get_pointee()
        assert proto is not None, field
        return self.thunk_lines(f"Entity{field[0].upper()}{field[1:]}", proto, fn)

    def thunk_lines(self, alias: str, proto: ci.Type, fn: Function) -> list[str]:
        """The static of one stored function under the callback typealias of its field.
        A view argument is the view over the handle, a qboolean is the test against 0, and a Bool return is C's 1 or 0."""
        lines = [f"    /// Source: {fn.cite}"]
        # A vector, a text, or a scalar output crosses as a C pointer with no view, and only a view target may read it under rule 11.
        # A thunk with such an argument keeps the marker, unless the function takes the pointer as it is.
        # A host thunk reads a text and a vector the function takes by value through the readers of the view target, `text(at:)` and `vector(at:)`,
        # the form of the cgame thunks of cg_main.swift, rows X1 and X2 of docket 10.
        raw = fn.mapped and any(self.raw_argument(arg, fn.params[i] if i < len(fn.params) else None) and self.host_reader(fn.params[i] if i < len(fn.params) else None) is None
                                for i, arg in enumerate(proto.argument_types()))
        if not fn.mapped or raw:
            self.counts["thunks over an unmapped signature"] += 1
            ignored = ", ".join("_" for _ in proto.argument_types()) or "_"
            lines += [
                f"    // TODO: Port signature",
                f'    static let {swift_name(fn.name)}: {alias} = {{ {ignored} in portMissing("{fn.name}", source: "{fn.cite}") }}',
            ]
            return lines
        args: list[str] = []
        for i, arg in enumerate(proto.argument_types()):
            canonical = arg.get_canonical()
            param = fn.params[i] if i < len(fn.params) else None
            if canonical.kind == TypeKind.POINTER:
                record = self.table.views.record_name(canonical.get_pointee())
                view = self.table.views.qualified_view(record, C_TARGET) if record in self.table.views.views else None
                if view and param is not None and (param.swift or "").startswith("Slots<"):
                    # The function takes the table of records with its count beside it, which no reader gives from the word alone.
                    self.counts["thunks over an unmapped signature"] += 1
                    ignored = ", ".join("_" for _ in proto.argument_types())
                    return lines + ["    // TODO: Port signature",
                                    f'    static let {swift_name(fn.name)}: {alias} = {{ {ignored} in portMissing("{fn.name}", source: "{fn.cite}") }}']
                reader = None if view else self.host_reader(fn.params[i] if i < len(fn.params) else None)
                args.append(f"{view}(handle: ${i}!)" if view else reader.replace("{}", f"${i}") if reader else f"${i}")
            elif self.table.views.scalar(arg, C_TARGET) == "Bool":
                args.append(f"${i} != 0")
            elif C.HOST and canonical.kind in (TypeKind.LONG, TypeKind.ULONG) and param is not None and param.swift in ("Int32", "UInt32"):
                # The C `long` of the stored function is the 32 bits of WinDed in the botlib function, MSVC_WIDTH_FOLDERS,
                # so the thunk keeps the low 32 bits, BotFindMatch of be_ai_chat.cpp, row X2 of docket 10.
                args.append(f"{param.swift}(truncatingIfNeeded: ${i})")
            else:
                args.append(f"${i}")
        if C.HOST and proto.is_function_variadic() and args and fn.params and fn.params[-1].swift == "String":
            # The run method of a variadic stored function hands over text it already formatted, so the filler prints it through "%s",
            # BotImport_Print of sv_bot.cpp:267, row X1a of docket 10.
            args[-1] = f'"%s", {args[-1]}'
        # A closure that names only some of its parameters names none, so every argument is positional.
        call = f"{target_of(fn.stem)}.{swift_name(fn.name)}({', '.join(args)})"
        if fn.returns == "Bool":
            call = f"{call} ? 1 : 0"
        result = proto.get_result().get_canonical()
        if C.HOST and result.kind == TypeKind.POINTER and fn.returns in ("String", "String?"):
            # A host thunk hands the C caller the text in the ring of the view target, the `va` form, BotImport_BSPEntityData of sv_bot.cpp:378, row X1.
            call = f"ringText({call})" if fn.returns == "String" else f"{call}.map(ringText)"
        elif C.HOST and result.kind == TypeKind.POINTER and fn.returns in ("UnsafeMutableRawPointer", "UnsafeMutableRawPointer?"):
            # A host thunk hands the C caller the block as the word, the form of `Z_Free(OpaquePointer(x.base))`, BotImport_GetMemory of sv_bot.cpp:438, row X1.
            call = f"OpaquePointer({call})" if fn.returns == "UnsafeMutableRawPointer" else f"{call}.map(OpaquePointer.init)"
        lines.append(f"    static let {swift_name(fn.name)}: {alias} = {{ {call} }}")
        self.counts["thunks"] += 1
        return lines

    def host_reader(self, param: Param | None) -> str | None:
        """The reader of the view target that turns a host thunk's C word into the parameter, with `{}` for the word, or None.
        A text is `text(at:)` and a vector by value is `vector(at:)`, the readers of ThunkReaders.swift, rows X1 and X2 of docket 10."""
        if not C.HOST or param is None:
            return None
        if param.swift == "String":
            return "text(at: {}!)"
        if param.swift == "String?":
            return "{}.map(text(at:))"
        if param.swift == "JKAShared.vec3_t":
            return "vector(at: {}!)"
        return None

    def raw_argument(self, arg: ci.Type, param: Param | None) -> bool:
        """Whether a thunk argument is a C pointer that no view reads and that the stored function does not take as an `OpaquePointer?`."""
        canonical = arg.get_canonical()
        if canonical.kind != TypeKind.POINTER:
            return False
        record = self.table.views.record_name(canonical.get_pointee())
        if record in self.table.views.views:
            return False
        return param is None or not (param.swift or "").startswith("OpaquePointer")

    def thunks(self) -> list[str]:
        # A host compiles no bg file, so its thunks import no bg module, as its stubs do.
        lines = [THUNKS_NOTE, "", "import JKAMP"] + ([] if C.HOST else ["import JKAMP_BG"]) + [f"import {VIEWS}", "import JKAShared", ""]
        for field in FIELDS:
            stored = sorted(self.stores.get(field, []), key=lambda pair: pair[0])
            lines += [
                f"/// One static per function the oracle stores in `{field}`, so each has one address for the life of the module.",
                f"enum {field[0].upper()}{field[1:]} {{",
            ]
            for _, fn in stored:
                lines += self.thunk(field, fn)
                lines.append("")
            if stored:
                lines.pop()
            lines += ["}", ""]
        return lines

