#!/usr/bin/env python3
"""skeleton.py: every function of the MP game module as a Swift stub, and the thunk namespaces, per porting rule 13.

Reads the mp-game unity parse and writes one Swift file per Raven .c file, Sources/JKAMP_GameLogic/g_mover.swift for
g_mover.c and Sources/JKAMP_BG/bg_pmove.swift for bg_pmove.c. g_syscalls.c is traps.py's and is skipped. Each stub keeps
Raven's order, Raven's block above it as a /** */ comment, a /// Source: line, Raven's signature by the table of
abi-stubs.md row 2, and a body of the marker pair of rule 14. Raven's static is dropped, because Swift module scope
already hides the function and the thunks below must reach it. A signature the table cannot map carries
`TODO: Port signature` with Raven's C text above a stub that takes no arguments.

The second output is Sources/JKAMP_GameLogic/Generated/Callbacks.swift: one enum per callback field of gentity_t,
one static thunk per function the oracle stores in that field, named as the function, so each function has one
address for the life of the module. A clear to 0 or NULL and a store whose value is a call are not stores of a name.

A stub file is replaced whole until its first hand edit. A file that no longer carries the generated header line
is adopted, and the generator leaves it alone and says so.

Usage:
  .venv/bin/python skeleton.py                 # writes every file and prints the counts
  .venv/bin/python skeleton.py --only g_mover  # prints one file to stdout, writes nothing
"""

from __future__ import annotations

import argparse
from collections import Counter, defaultdict
from pathlib import Path

import clang.cindex as ci
from clang.cindex import CursorKind, TypeKind

import closure as C
from fnsweep import binop_assign_op, rhs_function
from reexport import REPO, SOURCES
from table import Param, SourceFile, Table, swift_name

ORACLE_DIR = "codemp/game"
SKIP = {"g_syscalls.c"}
FIELDS = ["think", "use", "touch", "die", "pain", "reached", "blocked"]
LOGIC = "JKAMP_GameLogic"
BG = "JKAMP_BG"
NOTE = "// Generated by tools/oracle-closure/skeleton.py from the oracle's {stem}.c. Do not edit until adopted. Rule 13."
THUNKS_NOTE = "// Generated by tools/oracle-closure/skeleton.py from the oracle's store sites. Do not edit. Rule 3 and rule 13."


def target_of(stem: str) -> str:
    return BG if stem.startswith("bg_") else LOGIC


class Function:
    """One Raven definition and the stub the table gives it, or the reason it has none."""

    def __init__(self, cur: ci.Cursor, stem: str) -> None:
        self.cur = cur
        self.name = cur.spelling
        self.stem = stem
        self.line = cur.location.line
        self.static = cur.storage_class == ci.StorageClass.STATIC
        self.params: list[Param] = []
        self.returns: str | None = None
        self.reason: str | None = None

    @property
    def cite(self) -> str:
        return f"oracle/{ORACLE_DIR}/{self.stem}.c:{self.line}"

    @property
    def mapped(self) -> bool:
        return self.reason is None


class Skeleton:
    def __init__(self) -> None:
        self.table = Table()
        self.tu = C.parse_tu("mp-game", None, unity=True)
        self.sources: dict[str, SourceFile] = {}
        self.files: dict[str, list[Function]] = defaultdict(list)
        self.by_name: dict[str, Function] = {}
        self.counts: Counter[str] = Counter()
        self.collect()
        self.stores = self.collect_stores()
        self.stored_names = {fn.name for pairs in self.stores.values() for _, fn in pairs}
        # SpeederNPC.c defines `Update` without static, and four other files define it with. Every copy of a shared name is private.
        owners: dict[str, set[str]] = defaultdict(set)
        for stem, fns in self.files.items():
            for fn in fns:
                owners[fn.name].add(target_of(stem) + "/" + stem)
        self.shared_names = {name for name, stems in owners.items() if len(stems) > 1}

    # MARK: - Reading Raven

    def source(self, stem: str) -> SourceFile:
        if stem not in self.sources:
            self.sources[stem] = SourceFile(C.ORACLE / ORACLE_DIR / f"{stem}.c")
        return self.sources[stem]

    def collect(self) -> None:
        game = (C.ORACLE / ORACLE_DIR).resolve()
        for cur in self.tu.cursor.get_children():
            if cur.kind != CursorKind.FUNCTION_DECL or not cur.is_definition() or not cur.location.file:
                continue
            path = Path(cur.location.file.name).resolve()
            if path.parent != game or path.suffix != ".c" or path.name in SKIP:
                continue
            fn = Function(cur, path.stem)
            self.map(fn)
            self.files[path.stem].append(fn)
            self.by_name.setdefault(fn.name, fn)

    def map(self, fn: Function) -> None:
        params = list(fn.cur.get_arguments())
        for i, p in enumerate(params):
            following = params[i + 1] if i + 1 < len(params) else None
            m = self.table.param(p, following, traps=False)
            if m is None:
                fn.reason = f"No table row for `{' '.join(p.type.spelling.split())} {p.spelling}`."
                return
            fn.params.append(m)
        result = self.table.result(fn.cur)
        if result is None:
            fn.reason = f"No table row for the return `{fn.cur.result_type.spelling}`."
            return
        fn.returns = result[0]

    def collect_stores(self) -> dict[str, list[tuple[str, Function]]]:
        """Every `ent->field = Name` in the module, by field, as (site cite, stored function)."""
        stores: dict[str, list[tuple[str, Function]]] = defaultdict(list)
        seen: set[tuple[str, str]] = set()

        def walk(node: ci.Cursor) -> None:
            if node.kind == CursorKind.BINARY_OPERATOR and binop_assign_op(node) == "=":
                lhs, rhs = list(node.get_children())
                if lhs.kind == CursorKind.MEMBER_REF_EXPR and lhs.spelling in FIELDS:
                    owner = lhs.type.get_canonical()
                    if owner.kind == TypeKind.POINTER and owner.get_pointee().kind == TypeKind.FUNCTIONPROTO:
                        name = rhs_function(rhs)
                        if name and name in self.by_name and (lhs.spelling, name) not in seen:
                            seen.add((lhs.spelling, name))
                            stores[lhs.spelling].append((name, self.by_name[name]))
                        elif name and name not in self.by_name:
                            self.counts["store of a function outside the module"] += 1
            for child in node.get_children():
                walk(child)

        for fns in self.files.values():
            for fn in fns:
                walk(fn.cur)
        return stores

    # MARK: - Emission

    def stub(self, fn: Function) -> list[str]:
        source = self.source(fn.stem)
        lines = source.comment_above(fn.cur)
        lines.append(f"/// Source: {fn.cite}")
        name = swift_name(fn.name)
        # Raven's static is file scope, and five vehicle files each define `Update`, so a static stub is private.
        # A static function the oracle stores in a field stays internal, because its thunk names it from another file.
        hidden = fn.static or fn.name in self.shared_names
        access = "private " if hidden and fn.name not in self.stored_names else ""
        if hidden and fn.name in self.stored_names:
            self.counts["static functions kept internal for a thunk"] += 1
        if not fn.static and fn.name in self.shared_names:
            self.counts["functions made private because another file defines the name"] += 1
        if not fn.mapped:
            self.counts["TODO: Port signature"] += 1
            lines += [
                "// TODO: Port signature",
                f"// Raven wrote: {source.c_signature(fn.cur)}",
                f"// {fn.reason}",
                f"{access}func {name}() -> Never {{",
            ]
        else:
            self.counts["stubs"] += 1
            signature = ", ".join(f"_ {p.name}: {p.swift}" for p in fn.params)
            lines.append(f"{access}func {name}({signature})" + (f" -> {fn.returns}" if fn.returns else "") + " {")
        lines += [
            f"    // TODO: Port {fn.name}",
            f'    portMissing("{fn.name}", source: "{fn.cite}")',
            "}",
        ]
        return lines

    def file(self, stem: str) -> list[str]:
        target = target_of(stem)
        imports = ["import JKAMP", "import JKAShared"] + (["import JKAMP_Game"] if target == LOGIC else [])
        lines = [NOTE.format(stem=stem), ""] + imports + [""]
        for fn in self.files[stem]:
            lines += self.stub(fn)
            lines.append("")
        return lines

    def thunk(self, field: str, fn: Function) -> list[str]:
        """One static per stored function. The closure turns each handle into a view and calls the function by its module name."""
        proto = None
        for record in self.table.views.records.values():
            if record.spelling == "gentity_s":
                for f in record.get_children():
                    if f.kind == CursorKind.FIELD_DECL and f.spelling == field:
                        proto = f.type.get_canonical().get_pointee()
        assert proto is not None, field
        alias = f"Entity{field[0].upper()}{field[1:]}"
        lines = [f"    /// Source: {fn.cite}"]
        if not fn.mapped:
            self.counts["thunks over an unmapped signature"] += 1
            lines += [
                f"    // TODO: Port signature",
                f'    static let {swift_name(fn.name)}: {alias} = {{ _ in portMissing("{fn.name}", source: "{fn.cite}") }}',
            ]
            return lines
        args: list[str] = []
        for i, arg in enumerate(proto.argument_types()):
            canonical = arg.get_canonical()
            if canonical.kind == TypeKind.POINTER:
                record = self.table.views.record_name(canonical.get_pointee())
                view = self.table.views.qualified_view(record, "CJKAMP_Game") if record in self.table.views.views else None
                args.append(f"{view}(handle: ${i}!)" if view else f"${i}")
            elif self.table.views.scalar(arg, "CJKAMP_Game") == "Bool":
                args.append(f"${i} != 0")
            else:
                args.append(f"${i}")
        # A closure that names only some of its parameters names none, so every argument is positional.
        call = f"{target_of(fn.stem)}.{swift_name(fn.name)}({', '.join(args)})"
        lines.append(f"    static let {swift_name(fn.name)}: {alias} = {{ {call} }}")
        self.counts["thunks"] += 1
        return lines

    def thunks(self) -> list[str]:
        lines = [THUNKS_NOTE, "", "import JKAMP", "import JKAMP_BG", "import JKAMP_Game", "import JKAShared", ""]
        for field in FIELDS:
            stored = sorted(self.stores.get(field, []), key=lambda pair: pair[0])
            lines += [
                f"/// One static per function the oracle stores in `{field}`, so each has one address for the life of the module.",
                f"enum {field[0].upper()}{field[1:]} {{",
            ]
            for _, fn in stored:
                lines += self.thunk(field, fn)
                lines.append("")
            if stored:
                lines.pop()
            lines += ["}", ""]
        return lines

    # MARK: - Writing

    def write(self) -> tuple[int, list[str]]:
        written = 0
        adopted: list[str] = []
        for stem in sorted(self.files):
            out = SOURCES / target_of(stem) / f"{stem}.swift"
            if out.exists() and out.read_text().split("\n", 1)[0] != NOTE.format(stem=stem):
                adopted.append(str(out.relative_to(REPO)))
                continue
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text("\n".join(self.file(stem)).rstrip() + "\n")
            written += 1
        out = SOURCES / LOGIC / "Generated" / "Callbacks.swift"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text("\n".join(self.thunks()).rstrip() + "\n")
        return written, adopted


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", help="one Raven file stem, printed to stdout, nothing written")
    args = ap.parse_args()
    gen = Skeleton()
    if args.only:
        if args.only not in gen.files:
            raise SystemExit(f"skeleton.py: no Raven file named {args.only}.c")
        print("\n".join(gen.file(args.only)))
        return
    written, adopted = gen.write()
    c = gen.counts
    print(f"skeleton.py: {written} files, {c['stubs']} stubs, {c['TODO: Port signature']} TODO: Port signature markers, "
          f"{c['thunks']} thunks in {len(FIELDS)} namespaces, {c['thunks over an unmapped signature']} thunks over an unmapped signature")
    if c["functions made private because another file defines the name"]:
        print(f"  {c['functions made private because another file defines the name']} functions made private, because another file defines the name")
    if c["static functions kept internal for a thunk"]:
        print(f"  {c['static functions kept internal for a thunk']} static functions kept internal, because a thunk names them")
    if c["store of a function outside the module"]:
        print(f"  {c['store of a function outside the module']} stores of a function outside the module, skipped")
    for path in adopted:
        print(f"  adopted, left alone: {path}")
    for stem in sorted(gen.files):
        markers = sum(1 for fn in gen.files[stem] if not fn.mapped)
        if markers:
            print(f"  {stem + '.c':28} {len(gen.files[stem]):4} functions {markers:4} signature markers")


if __name__ == "__main__":
    main()
