from closure import ORACLE
from reexport import REPO, SOURCES

NOTE = "// Generated by tools/oracle-closure/tables.py from the oracle's own lines. Do not edit. Rule 6 and rule 13."


def head(target: str, header: str) -> tuple[str, ...]:
    """The tool's lines at the top of one generated file: the note, the umbrella of the target, and the hand header that declares the tables."""
    return (
        NOTE,
        "// Raven's tables as C storage, copied as written, so a view can bind over them. Rule 6 keeps them read-only at the Swift surface.",
        "// The umbrella carries no standard header, and Raven's rows say NULL.",
        "#include <stddef.h>",
        f'#include "{target}.h"',
        f'#include "{header}"',
    )

