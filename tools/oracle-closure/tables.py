@dataclass(frozen=True)
class Output:
    """One generated file: the C target it compiles in, its name, the hand header that declares its tables, and its pieces."""

    target: str
    name: str
    header: str
    pieces: tuple[Piece, ...]


OUTPUTS: tuple[Output, ...] = (
    Output("CJKAMP", "bg_tables.c", "bg_tables.h", BG_PIECES),
    Output("CJKAMP_Game", "g_tables.c", "g_tables.h", GAME_PIECES),
)


def copied(piece: Piece) -> bytes:
    """Raven's bytes for the piece's line range, as they stand in the oracle."""
    lines = (ORACLE / piece.source).read_bytes().splitlines(keepends=True)
    if piece.last > len(lines):
        raise SystemExit(f"tables.py: {piece.source} has {len(lines)} lines, and the piece asks for {piece.last}")
    return b"".join(lines[piece.first - 1:piece.last])


def cite(piece: Piece) -> str:
    span = f"{piece.first}" if piece.first == piece.last else f"{piece.first}-{piece.last}"
    return f"// Source: oracle/{piece.source}:{span}"


def emit(output: Output) -> bytes:
    out = bytearray()
    for line in head(output.target, output.header):
        out += line.encode() + b"\n"
    for piece in output.pieces:
        out += b"\n"
        for line in piece.own:
            out += line.encode() + b"\n"
        if piece.source:
            out += cite(piece).encode() + b"\n"
            out += copied(piece)
    return bytes(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--print", action="store_true", dest="show", help="print both files to stdout, write nothing")
    args = ap.parse_args()
    for output in OUTPUTS:
        text = emit(output)
        if args.show:
            sys.stdout.buffer.write(text)
            continue
        out = SOURCES / output.target / output.name
        out.write_bytes(text)
        tables = sum(1 for p in output.pieces if p.source and p.table)
        macros = sum(1 for p in output.pieces if p.source and not p.table)
        files = len({p.source for p in output.pieces if p.source})
        lines = text.count(b"\n")
        print(f"tables.py: {tables} tables and {macros} macro blocks from {files} oracle files, {lines} lines, {out.relative_to(REPO)}")


if __name__ == "__main__":
    main()
