#!/usr/bin/env python3
"""tables.py: Raven's data tables as C storage, written to Sources/CJKAMP/bg_tables.c, Sources/CJKAMP_Game/g_tables.c,
Sources/CJKAMP_CGame/cg_tables.c, and Sources/CJKAMP_Ded/ded_tables.c.

Rule 6: a table with Raven's data lives in C memory the view target binds over, read-only at the Swift surface.
Rule 13: the file is generated whole and regenerated whole, so no hand edit survives a run.

The table list below is the data. Each piece names the oracle file and the first and last line of Raven's text, and the
generator copies those bytes as they stand. Raven's files are CRLF, so a copied range is CRLF and the tool's own lines are LF.
A piece with no source carries the tool's own lines alone, which is how the offset-macro pragma and the `#undef` of the
per-file define stand beside the tables instead of inside the writer.

The bg tables go to the MP target, which every MP module compiles. The game tables go to the game target, because only the
game module defines them, and the fields table reads `gentity_t` through `FOFS`.

Usage:
  .venv/bin/python tables.py           # writes both files and prints the counts
  .venv/bin/python tables.py --print   # prints both files to stdout, writes nothing
"""

