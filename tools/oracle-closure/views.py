#!/usr/bin/env python3
"""views.py: the Swift views over Raven's structs, one file per view type, per view target.

Rule 3: ABI-crossing state lives in C memory the world owns, and Swift reaches it through pointer-backed view structs with
nonmutating setters, one view type per file. Rule 13: the accessors are generated whole and regenerated whole.

The roots are the rows of the run's unit in ROOTS of rulings.py: gentity_t, gclient_t, and level_locals_t in JKAMP_Game and
playerState_t in JKAMP for the game, and cg_t, cgs_t, and centity_t in JKAMP_CGame for the cgame. Every struct a root reaches by
value, by array, or by pointer gets a view in the target that owns its header. spelling.py maps each C field shape to one Swift
property type by the conversion table of struct-views.md row 2, with no per-field exception, and this file writes the accessor over it:

  int, float, unsigned         Int32, Float, UInt32
  scalar typedef               the re-exported typealias
  qboolean                     Bool
  C enum                       the re-exported struct
  vec3_t                       JKAShared.vec3_t, a SIMD3<Float>
  T[N]                         Slots<T>, a view over the field's address and N
  char[N]                      String, with a CharBuf accessor named nameBuffer beside it for a write target
  char *                       String?, the setter interns the text in the shared StringPool
  struct S by value            the view over the field's address
  pointer to a copied struct   the optional view
  void *                       OpaquePointer?
  function pointer             the C type, with a typealias per signature and a run method per field

A field the generator cannot map gets the rule 14 marker with Raven's declaration on the next line.

A run writes the view target of its unit whole. In JKAMP and JKAShared, which every unit's views reach, it writes the views of its
own closure and keeps the views of the other unit, so a run removes a view there only when the parse holds no struct of its name.

Usage:
  .venv/bin/python views.py                     # writes Sources/<View>/Generated/Views/ for every root's closure of the game
  .venv/bin/python views.py --unit mp-cgame     # the same for the roots of the cgame
  .venv/bin/python views.py --only gentity_t    # writes the views of one root's closure only, for a look
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

import clang.cindex as ci
from clang.cindex import CursorKind, TypeKind

import closure as C
from reexport import DEPS, SCALARS, SOURCES, VIEW_OF, source_lines
from rulings import BYTE_STORAGE_FIELDS, ENUM_TYPEDEFS, FIELD_NAMES, FIELDS, INDEXED_FIELDS, NEVER_NULL, NULLABLE, PARAMS, RETURNS, ROOTS, SLOT_BOUNDS
from spelling import Types

# Every C target the translation unit of the run's unit reaches, most specific first.
TARGETS = [C.TARGETS["c_target"], "CJKAMP", "CJKAShared"]
# The roots of the run's unit.
UNIT_ROOTS = ROOTS[C.UNIT]
NOTE = "// Generated by tools/oracle-closure/views.py from the C target's headers. Do not edit. Rule 3 and rule 13."
# The most elements of a C array field Swift's importer takes. A larger array field has no Swift member.
IMPORT_LIMIT = 4096
# The name of the second accessor of a `char name[N]` field is the field's name plus this suffix. The drafter spells it from here too.
BUFFER_SUFFIX = "Buffer"
# The part of a generated declaration line that the generator reads: the declared name, and the C signature of a callback typealias.
# The key of the table covers these parts alone, so a new value or a new comment in a re-export file keeps the facts.
DECLARATION_HEAD = re.compile(r"^public (?:let|struct|typealias) \w+(?: = @convention\(c\) .*$)?", re.M)


def arguments(proto: ci.Type) -> list[ci.Type]:
    """The parameter types of a function type, none for Raven's `()` with no prototype."""
    return list(proto.argument_types()) if proto.kind == TypeKind.FUNCTIONPROTO else []


def declaration_heads(text: str) -> str:
    """The parts of a generated Swift file that the generator reads, one per line, in file order."""
    return "\n".join(DECLARATION_HEAD.findall(text))



def row_stride(element: ci.Type, count: int, storage) -> str:
    """The byte stride of one row of a two-index array field, `count` elements of `element`, as Swift text.
    `storage` answers the Swift storage type of a C scalar. An element that is itself an array, the `vec3_t` of
    `points[MAX_GRID_SIZE][MAX_GRID_SIZE]` at cm_patch.h:115, takes its own count times the stride of its scalar, so a row is 129 * 3 floats."""
    canonical = element.get_canonical()
    if canonical.kind == TypeKind.CONSTANTARRAY:
        return f"{count} * {canonical.element_count} * MemoryLayout<{storage(canonical.element_type)}>.stride"
    return f"{count} * MemoryLayout<{storage(element)}>.stride"

class Generator:
    def __init__(self, parse: C.Parse, only: str | None, indexed_fields: set[tuple[str, str]] | None = None) -> None:
        self.parse = parse
        self.tu = parse.headers
        # The (struct, field) pairs whose bodies the subscript sweep of table.py read an index on, which get the second accessor.
        self.indexed_fields: set[tuple[str, str]] = set(indexed_fields or ())
        self.records: dict[str, ci.Cursor] = {}
        self.typedef_of: dict[str, str] = {}
        self.enums: set[str] = set()
        self.declared: dict[str, str] = self.scan_declared()
        # The one owner of the type question. Every generator reaches it through the generator it already holds.
        self.types = Types(parse, self)
        self.views: dict[str, tuple[str, str]] = {}
        # A struct or union Raven left unnamed inside a field, keyed by the place of its definition, with its record name.
        # The record name is the owner's name and the field's, `refEntity_t_data`, as jka-rust names the same record.
        self.unnamed: dict[tuple[str, int], str] = {}
        # The record name of an unnamed record -> the named struct around it and the field path from that struct, `data.sprite`.
        self.unnamed_of: dict[str, tuple[str, str]] = {}
        self.callbacks: dict[tuple[str, str], str] = {}
        self.todo = 0
        self.collect()
        roots = {only: UNIT_ROOTS[only]} if only else UNIT_ROOTS
        for c_name, (view, target) in roots.items():
            self.reach(c_name, view, target)

    def scan_declared(self) -> dict[str, str]:
        """Every public name a view target's re-exports declare, so a dependency's name can be qualified against the C import.
        It reads the targets of the run's unit alone, because a sibling unit's view target is a module this unit never imports."""
        out: dict[str, str] = {}
        for target, view in VIEW_OF.items():
            if target not in TARGETS:
                continue
            for path in (path for root in C.READ_ROOTS for path in (root / view / "Generated").glob("*.swift")):
                for m in re.finditer(r"^public (?:let|struct|typealias) (\w+)", path.read_text(), re.M):
                    out.setdefault(m.group(1), view)
        return out

    def collect(self) -> None:
        for cur in self.tu.cursor.get_children():
            if cur.kind == CursorKind.STRUCT_DECL and cur.is_definition():
                self.records[cur.spelling] = cur
            elif cur.kind == CursorKind.UNION_DECL and cur.is_definition() and cur.spelling in UNIT_ROOTS:
                # A union Raven named by its tag alone, `union cvalue` of be_ai_char.cpp:39, takes a view where a root row names the tag, row X22.
                self.records.setdefault(cur.spelling, cur)
            elif cur.kind == CursorKind.TYPEDEF_DECL:
                under = cur.underlying_typedef_type
                decl = under.get_declaration()
                if decl.kind == CursorKind.STRUCT_DECL:
                    # Raven also wrote a typedef named as its tag, and the map wants the one Raven's fields use.
                    if cur.spelling != decl.spelling:
                        self.typedef_of.setdefault(decl.spelling, cur.spelling)
                    definition = decl.get_definition()
                    if definition is not None:
                        self.records.setdefault(cur.spelling, definition)
                elif decl.kind == CursorKind.UNION_DECL and cur.spelling in UNIT_ROOTS and decl.get_definition() is not None:
                    # A named union a root row names, `qfile_gut` of files.h:71, takes a view as a struct does.
                    self.records.setdefault(cur.spelling, decl.get_definition())
                elif decl.kind == CursorKind.ENUM_DECL:
                    self.enums.add(cur.spelling)
            elif cur.kind == CursorKind.ENUM_DECL and cur.is_definition() and cur.spelling and not cur.spelling.startswith("enum ("):
                self.enums.add(cur.spelling)

    def target_of(self, cur: ci.Cursor) -> str:
        path = str(Path(cur.location.file.name).resolve())
        # A staged unit parses its C targets under out/<unit>/Sources, so a target's headers stand under that root.
        for target in TARGETS:
            if any(str(root / target / "include") in path for root in C.READ_ROOTS):
                return target
        sys.exit(f"views.py: {cur.spelling} is defined outside every target: {path}")

    def view_name(self, c_name: str) -> str:
        # A struct of JKAMP or JKAShared keeps one view name for every unit, so a root row of the other unit names it too.
        for roots in [UNIT_ROOTS, *ROOTS.values()]:
            if c_name in roots:
                return roots[c_name][0]
        if c_name in self.unnamed_of:
            # The view of an unnamed record is the view of its owner and the field name with its first letter raised.
            owner, path = self.unnamed_of[c_name]
            return self.view_name(owner) + "".join(part[0].upper() + part[1:] for part in path.split("."))
        base = c_name[:-2] if c_name.endswith("_t") else c_name
        return base[0].upper() + base[1:]

    def record_name(self, t: ci.Type) -> str | None:
        """The typedef name of a struct type, for skeleton.py, which reaches the answer through the table it holds. spelling.py owns it."""
        return self.types.record_name(t)

    def reach(self, c_name: str, view: str, target: str) -> None:
        """Adds the view of one struct and walks its fields for the structs they reach."""
        if c_name in self.views:
            return
        self.views[c_name] = (view, target)
        record = self.records.get(c_name)
        if record is None:
            sys.exit(f"views.py: {c_name} has no definition in the parse")
        for field in record.get_children():
            if field.kind != CursorKind.FIELD_DECL:
                continue
            decl = self.unnamed_decl(field.type)
            if decl is not None:
                # Raven's `union { ... } data;` has no type name, so the record takes the owner's name and the field's.
                name = f"{c_name}_{field.spelling}"
                self.unnamed[self.place(decl)] = name
                owner, path = self.unnamed_of.get(c_name, (c_name, ""))
                self.unnamed_of[name] = (owner, f"{path}.{field.spelling}" if path else field.spelling)
                self.records[name] = decl
                self.reach(name, self.view_name(name), target)
                continue
            if FIELDS.get((c_name, field.spelling)) == "opaque":
                # The field holds a handle of the C library, the `FILE *` of `qfile_gut.o`, so the walk reaches no view through it.
                continue
            self.reach_type(field.type)

    def place(self, decl: ci.Cursor) -> tuple[str, int]:
        return (str(Path(decl.location.file.name).resolve()), decl.extent.start.offset)

    def unnamed_decl(self, t: ci.Type) -> ci.Cursor | None:
        """The definition of a struct or union Raven left unnamed as the type of one field, or None for every other type."""
        canonical = t.get_canonical()
        if canonical.kind != TypeKind.RECORD:
            return None
        decl = canonical.get_declaration()
        if decl.kind not in (CursorKind.STRUCT_DECL, CursorKind.UNION_DECL):
            return None
        if decl.spelling and "(unnamed" not in decl.spelling and "(anonymous" not in decl.spelling:
            return None
        return decl

    def owner_of(self, field: ci.Cursor) -> str:
        """The record name of the struct that holds a field, the name a table row of rulings.py keys on."""
        return self.unnamed.get(self.place(field.semantic_parent)) or self.types.record_name(field.semantic_parent.type) \
            or field.semantic_parent.spelling

    def unnamed_name(self, t: ci.Type) -> str | None:
        """The record name of an unnamed record type a view covers, or None."""
        decl = self.unnamed_decl(t)
        return self.unnamed.get(self.place(decl)) if decl is not None else None

    def swift_c_type(self, c_name: str) -> str:
        """The name Swift imports a record under: the C name, or for an unnamed record the member type the importer nests in its owner,
        `refEntity_t.__Unnamed_union_data`."""
        if c_name not in self.unnamed_of:
            return c_name
        owner, path = self.unnamed_of[c_name]
        spelled = owner
        name = owner
        for part in path.split("."):
            name = f"{name}_{part}"
            kind = "union" if self.records[name].kind == CursorKind.UNION_DECL else "struct"
            spelled += f".__Unnamed_{kind}_{part}"
        return spelled

    def reach_type(self, t: ci.Type) -> None:
        canonical = t.get_canonical()
        if canonical.kind == TypeKind.POINTER:
            pointee = canonical.get_pointee()
            name = self.types.record_name(pointee)
            if name and name in self.records:
                self.reach(name, self.view_name(name), self.target_of(self.records[name]))
        elif canonical.kind == TypeKind.CONSTANTARRAY:
            self.reach_type(canonical.element_type)
        elif canonical.kind == TypeKind.RECORD:
            name = self.types.record_name(t)
            if name and name in self.records:
                self.reach(name, self.view_name(name), self.target_of(self.records[name]))

    # MARK: - Field mapping

    def qualified(self, name: str, target: str) -> str:
        """A re-exported name, qualified with its view module when that module is a dependency of the emitting target."""
        view = self.declared.get(name)
        if view and view != VIEW_OF[target]:
            return f"{view}.{name}"
        return name

    def scalar(self, t: ci.Type, target: str) -> str | None:
        """The Swift type of a scalar field, for skeleton.py and rosetta.py, which reach the answer through the generator they hold.
        spelling.py owns it."""
        return self.types.scalar(t, target)

    def element(self, t: ci.Type, target: str, address: str, field: ci.Cursor | None = None) -> tuple[str, str] | None:
        """The Swift element type and the Slots initializer call for an array field whose elements sit at `address`, a raw pointer.
        spelling.py answers the field role, and the kind of its answer picks the Slots the accessor writes.
        The field cursor, when given, lets a char array's inner bound keep the macro name Raven wrote."""
        answer = self.types.answer("field", t, target=target)
        if answer is None:
            return None
        if answer.kind == "strings":
            return answer.swift, f"Slots(strings: {address}, count: {{count}})"
        if answer.kind == "pointers":
            return answer.swift, f"Slots(pointers: {address}, count: {{count}})"
        if answer.kind == "opaque":
            return answer.swift, f"Slots(opaque: {address}, count: {{count}})"
        if answer.kind == "views":
            name = self.types.record_name(t)
            return answer.swift, f"Slots(views: {address}, count: {{count}}, stride: MemoryLayout<{name}>.stride)"
        if answer.kind == "vectors":
            return answer.swift, f"Slots(vectors: {address}, count: {{count}})"
        if answer.kind == "cstrings":
            inner_count = t.get_canonical().element_count
            capacity = self.bound(field, target, 1, inner_count) if field is not None else str(inner_count)
            return answer.swift, f"Slots(cStrings: {address}, count: {{count}}, capacity: {capacity})"
        if answer.kind == "rows":
            inner_count = t.get_canonical().element_count
            inner_c = self.element_type(t)
            inner = self.element(inner_c, target, "$0")
            if inner is None:
                return None
            inner_type, inner_call = inner
            inner_call = inner_call.replace("{count}", str(inner_count))
            stride = row_stride(inner_c, inner_count, lambda c: self.types.storage(c, target))
            return f"Slots<{inner_type}>", f"Slots(rows: {address}, count: {{count}}, stride: {stride}) {{ {inner_call} }}"
        if answer.kind == "flags":
            return answer.swift, f"Slots(flags: {address}, count: {{count}})"
        return answer.swift, f"Slots<{answer.swift}>(scalars: {address}, count: {{count}})"

    def element_type(self, t: ci.Type) -> ci.Type:
        """The element type of an array with its typedef kept, so a `vec3_t` element still reads as one."""
        named = t.get_named_type() if t.kind == TypeKind.ELABORATED else t
        return named.element_type if named.kind == TypeKind.CONSTANTARRAY else t.get_canonical().element_type

    def is_vec3(self, t: ci.Type) -> bool:
        named = t.get_named_type() if t.kind == TypeKind.ELABORATED else t
        return named.kind == TypeKind.TYPEDEF and named.spelling == "vec3_t"

    def is_vec4(self, t: ci.Type) -> bool:
        named = t.get_named_type() if t.kind == TypeKind.ELABORATED else t
        return named.kind == TypeKind.TYPEDEF and named.spelling == "vec4_t"

    def qualified_view(self, c_name: str, target: str) -> str:
        view, owner = self.views[c_name]
        return view if owner == target else f"{VIEW_OF[owner]}.{view}"

    def accessor(self, field: ci.Cursor, target: str) -> list[str] | None:
        """The property lines of one field, or None when the table has no row for its shape."""
        name = field.spelling
        t = field.type
        canonical = t.get_canonical()
        pointee = f"self.raw.pointee.{name}"
        if name in ("handle", "raw"):
            # The view's own `handle` and `raw` take these names under rule 11, so a field so named that a body reads takes the FIELD_NAMES name.
            renamed = FIELD_NAMES.get((self.owner_of(field), name))
            swift = self.types.scalar(t, target) if renamed else None
            if renamed and swift is None and canonical.kind == TypeKind.POINTER and canonical.get_pointee().get_canonical().kind == TypeKind.VOID:
                # A `void *` handle so named, the zip handle `pack->handle` of files.h:46, reads as the handle under the FIELD_NAMES name.
                return [f"    // AI: Raven names the field `{name}`. The view's own slot pointer takes that name, so the field reads as `{renamed}`."] \
                    + self.property(renamed, "OpaquePointer?", f"OpaquePointer({pointee})", f"{pointee} = UnsafeMutableRawPointer(newValue)")
            if swift is None:
                # The engine writes a field so named, and no module body reads it.
                return [f"    // Raven's `{name}` field is the engine's, and the view's own `{name}` takes the name. No module body reads it."]
            return [f"    // AI: Raven names the field `{name}`. The view's own slot pointer takes that name, so the field reads as `{renamed}`."] \
                + self.property(renamed, swift, pointee, f"{pointee} = newValue")
        if canonical.kind == TypeKind.POINTER:
            inner = canonical.get_pointee()
            # Raven's `void (*clearScene) ();` declares no prototype, and Swift imports it as a function of no arguments.
            if inner.kind in (TypeKind.FUNCTIONPROTO, TypeKind.FUNCTIONNOPROTO):
                return self.callback(field, target)
            if inner.get_canonical().kind == TypeKind.CHAR_S and FIELDS.get((self.owner_of(field), name)) == "opaque":
                # A `char *` field of kind `opaque` holds a byte buffer that a body hands on as a handle, `read_buffer` of unzip.h:66.
                return self.property(name, "OpaquePointer?", f"OpaquePointer({pointee})", f"{pointee} = UnsafeMutablePointer(newValue)")
            ruled_text = FIELDS.get((self.owner_of(field), name))
            if inner.get_canonical().kind == TypeKind.CHAR_S and isinstance(ruled_text, tuple) and ruled_text[0] == "text_buffer":
                # The field holds the text a script reads, `script->buffer` of l_script.h:161, so it reads as a Slots over its bytes and the NUL,
                # the count field beside it plus one, row N1 of the ninth batch. A store keeps the base of the assigned Slots.
                count = f"Int(self.raw.pointee.{ruled_text[1]}) + 1"
                return self.property(name, "Slots<JKAShared.byte>?", f"{pointee}.map {{ Slots(scalars: UnsafeMutableRawPointer($0), count: {count}) }}",
                                     f"{pointee} = newValue?.base.assumingMemoryBound(to: CChar.self)")
            if inner.get_canonical().kind == TypeKind.CHAR_S and isinstance(ruled_text, tuple) and ruled_text[0] == "text_offset":
                # A cursor into the buffer of its record reads as the Int32 byte offset from that buffer, the field twin of the RETURNS kind
                # `text_offset_nonnull`, row N1 of the ninth batch. The C record keeps Raven's pointer, `script->script_p` of l_script.h:162.
                if ruled_text[1] is not None:
                    base = f"self.raw.pointee.{ruled_text[1]}"
                    return self.property(name, "Int32", f"Int32({base}!.distance(to: {pointee}!))", f"{pointee} = {base}! + Int(newValue)")
                # A token holds no buffer, so its cursor keeps the offset of the script's buffer as the bits of the pointer.
                return [f"    // AI: Raven holds a pointer into the script's buffer. The token holds no buffer, so the field keeps the byte offset as the pointer's bits."] \
                    + self.property(name, "Int32", f"Int32(Int(bitPattern: {pointee}))", f"{pointee} = UnsafeMutablePointer(bitPattern: Int(newValue))")
            if inner.get_canonical().kind == TypeKind.CHAR_S:
                # A `char *` field reads as its text, and a store interns the text in the shared pool, so the engine reads a pointer that lives on.
                get = f"{pointee}.map {{ cString(at: $0) }}"
                if inner.is_const_qualified():
                    # A `const char *` field holds the same text. The view puts the const back on the way in.
                    return self.property(name, "String?", get, f"{pointee} = UnsafePointer(StringPool.shared.pointer(for: newValue))")
                return self.property(name, "String?", get, f"{pointee} = StringPool.shared.pointer(for: newValue)")
            record = self.types.record_name(inner)
            if record and record in self.views:
                view = self.qualified_view(record, target)
                if self.never_null(field):
                    get = f"{view}(handle: OpaquePointer({pointee}!))"
                    return self.trapping(name, view, get, f"{pointee} = UnsafeMutablePointer(newValue.handle)") + self.slots(field, view, self.c_name_of(inner), target)
                lines = self.property(name, f"{view}?", f"{pointee}.map {{ {view}(handle: OpaquePointer($0)) }}",
                                      f"{pointee} = UnsafeMutablePointer(newValue?.handle)") + self.slots(field, view, self.c_name_of(inner), target)
                if FIELDS.get((self.owner_of(field), name)) == "slot":
                    # Raven takes the address of the pointer field, `prev = &sym->next` of vm.cpp:302, so a second accessor reads that address
                    # as the Slots of one optional view over the field, the form of a `T **` field of kind `slot`.
                    lines += [
                        "",
                        f"    /// Raven's `&{name}`, the slot of the field as the Slots of one optional view.",
                        f"    public var {name}Slot: Slots<{view}?> {{ Slots(pointers: UnsafeMutableRawPointer(self.raw.pointer(to: \\.{name})!), count: 1) }}",
                    ]
                return lines
            ruled = FIELDS.get((self.owner_of(field), name))
            if ruled == "bytes" and inner.get_canonical().kind == TypeKind.UCHAR:
                # The field holds the base of a byte buffer a body indexes, `cmd_text.data[i]`, so it reads as a Slots over the bytes.
                # C gives the pointer no bound, so the Slots takes the widest count, and a store keeps the base of the assigned Slots.
                count, _ = self.slots_count(field, target)
                return self.property(name, "Slots<JKAShared.byte>?", f"{pointee}.map {{ Slots(scalars: UnsafeMutableRawPointer($0), count: {count}) }}",
                                     f"{pointee} = newValue?.base.assumingMemoryBound(to: UInt8.self)")
            if ruled == "bytes" and inner.get_canonical().kind == TypeKind.INT:
                # An `int *` field a body indexes, `cm->leafbrushes[i]` of cm_test.cpp and `vm->instructionPointers[value]` of vm.cpp,
                # reads as a Slots over the words by the same rule, the widest count and the base of the assigned Slots on a store.
                count, _ = self.slots_count(field, target)
                return self.property(name, "Slots<Int32>?", f"{pointee}.map {{ Slots(scalars: UnsafeMutableRawPointer($0), count: {count}) }}",
                                     f"{pointee} = newValue?.base.assumingMemoryBound(to: Int32.self)")
            if ruled == "bytes" and inner.get_canonical().kind == TypeKind.USHORT:
                # An `unsigned short *` field a body indexes, `areatraveltimes` of aas_routingupdate_t at be_aas_def.h:156, reads as a Slots
                # over the shorts by the same rule, row N5 of the ninth batch.
                count, _ = self.slots_count(field, target)
                return self.property(name, "Slots<UInt16>?", f"{pointee}.map {{ Slots(scalars: UnsafeMutableRawPointer($0), count: {count}) }}",
                                     f"{pointee} = newValue?.base.assumingMemoryBound(to: UInt16.self)")
            if ruled == "vectors" and inner.get_canonical().kind == TypeKind.CONSTANTARRAY and inner.get_canonical().element_count == 3 \
                    and inner.get_canonical().element_type.get_canonical().kind == TypeKind.FLOAT:
                # A `vec3_t *` field a body indexes, `aasworld.vertexes` of be_aas_def.h:200, reads as a Slots of vectors through `Slots(vectors:)`,
                # the form of an array field of vectors, row N4 of the ninth batch. A store keeps the base of the assigned Slots.
                count, _ = self.slots_count(field, target)
