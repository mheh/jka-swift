#!/usr/bin/env python3
"""views.py: the Swift views over Raven's structs, one file per view type, per view target.

Rule 3: ABI-crossing state lives in C memory the world owns, and Swift reaches it through pointer-backed view structs with
nonmutating setters, one view type per file. Rule 13: the accessors are generated whole and regenerated whole.

The roots are gentity_t, gclient_t, and level_locals_t in JKAMP_Game and playerState_t in JKAMP. Every struct a root reaches by
value, by array, or by pointer gets a view in the target that owns its header. spelling.py maps each C field shape to one Swift
property type by the conversion table of struct-views.md row 2, with no per-field exception, and this file writes the accessor over it:

  int, float, unsigned         Int32, Float, UInt32
  scalar typedef               the re-exported typealias
  qboolean                     Bool
  C enum                       the re-exported struct
  vec3_t                       JKAShared.vec3_t, a SIMD3<Float>
  T[N]                         Slots<T>, a view over the field's address and N
  char[N]                      String, with a CharBuf accessor named nameBuffer beside it for a write target
  char *                       String?, the setter interns the text in the shared StringPool
  struct S by value            the view over the field's address
  pointer to a copied struct   the optional view
  void *                       OpaquePointer?
  function pointer             the C type, with a typealias per signature and a run method per field

A field the generator cannot map gets the rule 14 marker with Raven's declaration on the next line.

Usage:
  .venv/bin/python views.py                     # writes Sources/<View>/Generated/Views/ for every root's closure
  .venv/bin/python views.py --only gentity_t    # writes the views of one root's closure only, for a look
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

import clang.cindex as ci
from clang.cindex import CursorKind, TypeKind

import closure as C
from reexport import DEPS, GAME_TARGET, SCALARS, SOURCES, VIEW_OF, source_lines
from rulings import NEVER_NULL, ROOTS, SLOT_BOUNDS
from spelling import Types

# Every C target the game module's translation unit reaches, most specific first.
TARGETS = [GAME_TARGET, "CJKAMP", "CJKAShared"]
NOTE = "// Generated by tools/oracle-closure/views.py from the C target's headers. Do not edit. Rule 3 and rule 13."
# The name of the second accessor of a `char name[N]` field is the field's name plus this suffix. The drafter spells it from here too.
BUFFER_SUFFIX = "Buffer"
# The part of a generated declaration line that the generator reads: the declared name, and the C signature of a callback typealias.
# The key of the table covers these parts alone, so a new value or a new comment in a re-export file keeps the facts.
DECLARATION_HEAD = re.compile(r"^public (?:let|struct|typealias) \w+(?: = @convention\(c\) .*$)?", re.M)


def declaration_heads(text: str) -> str:
    """The parts of a generated Swift file that the generator reads, one per line, in file order."""
    return "\n".join(DECLARATION_HEAD.findall(text))


class Generator:
    def __init__(self, parse: C.Parse, only: str | None, indexed_fields: set[tuple[str, str]] | None = None) -> None:
        self.parse = parse
        self.tu = parse.headers
        # The (struct, field) pairs whose bodies the subscript sweep of table.py read an index on, which get the second accessor.
        self.indexed_fields: set[tuple[str, str]] = set(indexed_fields or ())
        self.records: dict[str, ci.Cursor] = {}
        self.typedef_of: dict[str, str] = {}
        self.enums: set[str] = set()
        self.declared: dict[str, str] = self.scan_declared()
        # The one owner of the type question. Every generator reaches it through the generator it already holds.
        self.types = Types(parse, self)
        self.views: dict[str, tuple[str, str]] = {}
        self.callbacks: dict[tuple[str, str], str] = {}
        self.todo = 0
        self.collect()
        roots = {only: ROOTS[only]} if only else ROOTS
        for c_name, (view, target) in roots.items():
            self.reach(c_name, view, target)

    def scan_declared(self) -> dict[str, str]:
        """Every public name a view target's re-exports declare, so a dependency's name can be qualified against the C import."""
        out: dict[str, str] = {}
        for target, view in VIEW_OF.items():
            for path in (SOURCES / view / "Generated").glob("*.swift"):
                for m in re.finditer(r"^public (?:let|struct|typealias) (\w+)", path.read_text(), re.M):
                    out.setdefault(m.group(1), view)
        return out

    def collect(self) -> None:
        for cur in self.tu.cursor.get_children():
            if cur.kind == CursorKind.STRUCT_DECL and cur.is_definition():
                self.records[cur.spelling] = cur
            elif cur.kind == CursorKind.TYPEDEF_DECL:
                under = cur.underlying_typedef_type
                decl = under.get_declaration()
                if decl.kind == CursorKind.STRUCT_DECL:
                    # Raven also wrote a typedef named as its tag, and the map wants the one Raven's fields use.
                    if cur.spelling != decl.spelling:
                        self.typedef_of.setdefault(decl.spelling, cur.spelling)
                    definition = decl.get_definition()
                    if definition is not None:
                        self.records.setdefault(cur.spelling, definition)
                elif decl.kind == CursorKind.ENUM_DECL:
                    self.enums.add(cur.spelling)
            elif cur.kind == CursorKind.ENUM_DECL and cur.is_definition() and cur.spelling and not cur.spelling.startswith("enum ("):
                self.enums.add(cur.spelling)

    def target_of(self, cur: ci.Cursor) -> str:
        path = str(Path(cur.location.file.name).resolve())
        for target in TARGETS:
            if str(SOURCES / target / "include") in path:
                return target
        sys.exit(f"views.py: {cur.spelling} is defined outside every target: {path}")

    def view_name(self, c_name: str) -> str:
        if c_name in ROOTS:
            return ROOTS[c_name][0]
        base = c_name[:-2] if c_name.endswith("_t") else c_name
        return base[0].upper() + base[1:]

    def record_name(self, t: ci.Type) -> str | None:
        """The typedef name of a struct type, for skeleton.py, which reaches the answer through the table it holds. spelling.py owns it."""
        return self.types.record_name(t)

    def reach(self, c_name: str, view: str, target: str) -> None:
        """Adds the view of one struct and walks its fields for the structs they reach."""
        if c_name in self.views:
            return
        self.views[c_name] = (view, target)
        record = self.records.get(c_name)
        if record is None:
            sys.exit(f"views.py: {c_name} has no definition in the parse")
        for field in record.get_children():
            if field.kind != CursorKind.FIELD_DECL:
                continue
            self.reach_type(field.type)

    def reach_type(self, t: ci.Type) -> None:
        canonical = t.get_canonical()
        if canonical.kind == TypeKind.POINTER:
            pointee = canonical.get_pointee()
            name = self.types.record_name(pointee)
            if name and name in self.records:
                self.reach(name, self.view_name(name), self.target_of(self.records[name]))
        elif canonical.kind == TypeKind.CONSTANTARRAY:
            self.reach_type(canonical.element_type)
        elif canonical.kind == TypeKind.RECORD:
            name = self.types.record_name(t)
            if name and name in self.records:
                self.reach(name, self.view_name(name), self.target_of(self.records[name]))

    # MARK: - Field mapping

    def qualified(self, name: str, target: str) -> str:
        """A re-exported name, qualified with its view module when that module is a dependency of the emitting target."""
        view = self.declared.get(name)
        if view and view != VIEW_OF[target]:
            return f"{view}.{name}"
        return name

    def scalar(self, t: ci.Type, target: str) -> str | None:
        """The Swift type of a scalar field, for skeleton.py and rosetta.py, which reach the answer through the generator they hold.
        spelling.py owns it."""
        return self.types.scalar(t, target)

    def element(self, t: ci.Type, target: str, address: str, field: ci.Cursor | None = None) -> tuple[str, str] | None:
        """The Swift element type and the Slots initializer call for an array field whose elements sit at `address`, a raw pointer.
        spelling.py answers the field role, and the kind of its answer picks the Slots the accessor writes.
        The field cursor, when given, lets a char array's inner bound keep the macro name Raven wrote."""
        answer = self.types.answer("field", t, target=target)
        if answer is None:
            return None
        if answer.kind == "strings":
            return answer.swift, f"Slots(strings: {address}, count: {{count}})"
        if answer.kind == "pointers":
            return answer.swift, f"Slots(pointers: {address}, count: {{count}})"
        if answer.kind == "opaque":
            return answer.swift, f"Slots(opaque: {address}, count: {{count}})"
        if answer.kind == "views":
            name = self.types.record_name(t)
            return answer.swift, f"Slots(views: {address}, count: {{count}}, stride: MemoryLayout<{name}>.stride)"
        if answer.kind == "vectors":
            return answer.swift, f"Slots(vectors: {address}, count: {{count}})"
        if answer.kind == "cstrings":
            inner_count = t.get_canonical().element_count
            capacity = self.bound(field, target, 1, inner_count) if field is not None else str(inner_count)
            return answer.swift, f"Slots(cStrings: {address}, count: {{count}}, capacity: {capacity})"
        if answer.kind == "rows":
            inner_count = t.get_canonical().element_count
            inner_c = self.element_type(t)
            inner = self.element(inner_c, target, "$0")
            if inner is None:
                return None
            inner_type, inner_call = inner
            inner_call = inner_call.replace("{count}", str(inner_count))
            stride = f"{inner_count} * MemoryLayout<{self.types.storage(inner_c, target)}>.stride"
            return f"Slots<{inner_type}>", f"Slots(rows: {address}, count: {{count}}, stride: {stride}) {{ {inner_call} }}"
        if answer.kind == "flags":
            return answer.swift, f"Slots(flags: {address}, count: {{count}})"
        return answer.swift, f"Slots<{answer.swift}>(scalars: {address}, count: {{count}})"

    def element_type(self, t: ci.Type) -> ci.Type:
        """The element type of an array with its typedef kept, so a `vec3_t` element still reads as one."""
        named = t.get_named_type() if t.kind == TypeKind.ELABORATED else t
        return named.element_type if named.kind == TypeKind.CONSTANTARRAY else t.get_canonical().element_type

    def is_vec3(self, t: ci.Type) -> bool:
        named = t.get_named_type() if t.kind == TypeKind.ELABORATED else t
        return named.kind == TypeKind.TYPEDEF and named.spelling == "vec3_t"

    def qualified_view(self, c_name: str, target: str) -> str:
        view, owner = self.views[c_name]
        return view if owner == target else f"{VIEW_OF[owner]}.{view}"

    def accessor(self, field: ci.Cursor, target: str) -> list[str] | None:
        """The property lines of one field, or None when the table has no row for its shape."""
        name = field.spelling
        t = field.type
        canonical = t.get_canonical()
        pointee = f"self.raw.pointee.{name}"
        if name in ("handle", "raw"):
            # The view's own `handle` and `raw` take these names under rule 11. The engine writes a field so named, and no module body reads it.
            return [f"    // Raven's `{name}` field is the engine's, and the view's own `{name}` takes the name. No module body reads it."]
        if canonical.kind == TypeKind.POINTER:
            inner = canonical.get_pointee()
            if inner.kind == TypeKind.FUNCTIONPROTO:
                return self.callback(field, target)
            if inner.get_canonical().kind == TypeKind.CHAR_S:
                # A `char *` field reads as its text, and a store interns the text in the shared pool, so the engine reads a pointer that lives on.
                get = f"{pointee}.map {{ String(cString: $0) }}"
                if inner.is_const_qualified():
                    # A `const char *` field holds the same text. The view puts the const back on the way in.
                    return self.property(name, "String?", get, f"{pointee} = UnsafePointer(StringPool.shared.pointer(for: newValue))")
                return self.property(name, "String?", get, f"{pointee} = StringPool.shared.pointer(for: newValue)")
            record = self.types.record_name(inner)
            if record and record in self.views:
                view = self.qualified_view(record, target)
                if self.never_null(field):
                    get = f"{view}(handle: OpaquePointer({pointee}!))"
                    return self.trapping(name, view, get, f"{pointee} = UnsafeMutablePointer(newValue.handle)") + self.slots(field, view, self.c_name_of(inner), target)
                return self.property(name, f"{view}?", f"{pointee}.map {{ {view}(handle: OpaquePointer($0)) }}",
                                     f"{pointee} = UnsafeMutablePointer(newValue?.handle)") + self.slots(field, view, self.c_name_of(inner), target)
            back = "UnsafeMutableRawPointer" if inner.get_canonical().kind == TypeKind.VOID else "UnsafeMutablePointer"
            lines = self.property(name, "OpaquePointer?", f"OpaquePointer({pointee})", f"{pointee} = {back}(newValue)")
            if inner.get_canonical().kind == TypeKind.FLOAT:
                # Raven reads a `float *` field as the vector it points at, so the view reads and writes three floats through the pointer.
                # The pointer never leaves the view, by rule 11. A NULL pointer traps with the field's name.
                lines += [
                    "",
                    f"    /// Raven's `{name}[i]`, the vector the pointer holds. A NULL pointer traps with the field's name.",
                    f"    public var {name}Vector: JKAShared.vec3_t {{",
                    "        get {",
                    f"            precondition({pointee} != nil, \"{name} is NULL\")",
                    f"            return JKAShared.vec3_t({pointee}![0], {pointee}![1], {pointee}![2])",
                    "        }",
                    "        nonmutating set {",
                    f"            precondition({pointee} != nil, \"{name} is NULL\")",
                    f"            {pointee}![0] = newValue.x",
                    f"            {pointee}![1] = newValue.y",
                    f"            {pointee}![2] = newValue.z",
                    "        }",
                    "    }",
                ]
            return lines
        if canonical.kind == TypeKind.CONSTANTARRAY:
            count = canonical.element_count
            address = f"UnsafeMutableRawPointer(self.raw.pointer(to: \\.{name})!)"
            if canonical.element_type.get_canonical().kind == TypeKind.CHAR_S:
                capacity = self.bound(field, target, 0, count)
                return self.property(name, "String", f"cString(at: {address})", f"store(newValue, at: {address}, capacity: {capacity})") \
                    + self.buffer(name, address, capacity)
            if self.is_vec3(t):
                return self.property(name, "JKAShared.vec3_t", f"vec3(of: {pointee})", f"{pointee} = tuple(of: newValue)")
            mapped = self.element(self.element_type(t), target, address, field)
            if mapped is None:
                return None
            element_type, call = mapped
            return [f"    public var {name}: Slots<{element_type}> {{ {call.replace('{count}', str(count))} }}"]
        if canonical.kind == TypeKind.RECORD:
            record = self.types.record_name(t)
            if record and record in self.views:
                view = self.qualified_view(record, target)
                # Raven's `a.field = b` on two records is a byte copy, so the setter copies the record behind the assigned view into the slot.
                return self.property(name, view, f"{view}(handle: OpaquePointer(self.raw.pointer(to: \\.{name})!))",
                                     f"{pointee} = UnsafeMutablePointer(newValue.handle).pointee")
            return None
        swift = self.types.scalar(t, target)
        if swift is None:
            return None
        if swift == "Bool":
            return self.property(name, "Bool", f"{pointee} != qfalse", f"{pointee} = newValue ? qtrue : qfalse")
        storage = self.types.narrow(t)
        if storage is not None:
            # C widens the field to int at every read, so the getter does, and the setter truncates as C's store does.
            return self.property(name, "Int32", f"Int32({pointee})", f"{pointee} = {storage}(truncatingIfNeeded: newValue)")
        if swift in SCALARS.values():
            return self.property(name, swift, pointee, f"{pointee} = newValue")
        # A re-exported enum is an Int32 alias, and Clang imports the C field as a struct, so the property goes through its rawValue.
        base = swift.split(".")[-1]
        if base in self.enums:
            return self.property(name, swift, f"Int32(truncatingIfNeeded: {pointee}.rawValue)",
                                 f"{pointee} = .init(rawValue: .init(truncatingIfNeeded: newValue))")
        return self.property(name, swift, pointee, f"{pointee} = newValue")

    def exported_names(self, target: str) -> dict[str, str]:
        """The macro and enum names reexport.py wrote as `public let`, each with the Swift module that exports it, for the
        view's module and the modules it imports. The name is qualified in the view, because the C module exports it too."""
        if not hasattr(self, "_exported"):
            self._exported: dict[str, dict[str, str]] = {}
        if target not in self._exported:
            names: dict[str, str] = {}
            for c_target in [target] + DEPS[target]:
                for path in (SOURCES / VIEW_OF[c_target] / "Generated").glob("*.swift"):
                    for name in re.findall(r"^public let (\w+)", path.read_text(), re.M):
                        names.setdefault(name, VIEW_OF[c_target])
            self._exported[target] = names
        return self._exported[target]

    def bound(self, field: ci.Cursor, target: str, index: int, fallback: int) -> str:
        """The array bound as Raven spelled it, `Int(JKAShared.MAX_QPATH)` for a macro a module exports, or the number when it is not one."""
        tokens = [t.spelling for t in field.get_tokens()]
        brackets = []
        for i, t in enumerate(tokens):
            if t == "[" and i + 2 < len(tokens) and tokens[i + 2] == "]":
                brackets.append(tokens[i + 1])
        exported = self.exported_names(target)
        if index < len(brackets) and brackets[index] in exported:
            return f"Int({exported[brackets[index]]}.{brackets[index]})"
        return str(fallback)

    def property(self, name: str, swift: str, get: str, set_: str) -> list[str]:
        return [
            f"    public var {name}: {swift} {{",
            f"        get {{ {get} }}",
            f"        nonmutating set {{ {set_} }}",
            "    }",
        ]

    def buffer(self, name: str, address: str, capacity: str) -> list[str]:
        """The second accessor of a `char name[N]` field, the buffer a callee writes into.

        A non-const `char *` parameter takes an `inout CharBuf`, so a write target passes `&view.<name>Buffer`.
        The getter copies the field's bytes out and the setter puts them back, so the callee's write lands in C memory.
        The field keeps its `String` accessor beside this one, which is what a read of the text takes."""
        return [
            "",
            f"    /// Raven's `{name}` as the buffer a callee writes into, for a `char *` parameter the port spells `inout CharBuf`.",
            f"    public var {name}{BUFFER_SUFFIX}: JKAShared.CharBuf {{",
            f"        get {{ charBuf(at: {address}, capacity: {capacity}) }}",
            f"        nonmutating set {{ store(newValue, at: {address}, capacity: {capacity}) }}",
            "    }",
        ]

    def c_name_of(self, t: ci.Type) -> str:
        """The C spelling of a record type, the name a store through a pointer field binds the memory to."""
        return self.types.record_name(t) or t.get_canonical().spelling

    def indexed(self, field: ci.Cursor) -> bool:
        """True when the subscript sweep of table.py read a body that indexes this field, `pm->animations[anim]`."""
        owner = self.types.record_name(field.semantic_parent.type) or field.semantic_parent.spelling
        return (owner, field.spelling) in self.indexed_fields

    def slots_count(self, field: ci.Cursor, target: str) -> tuple[str, str]:
        """The count of a pointer field's Slots, and the line that states where the count comes from.

        SLOT_BOUNDS names Raven's own macro for a field a ruling has bounded, and the view spells it as its module exports it.
        A field the rule does not name takes the widest count, and Raven's own index is the one that reads."""
        owner = self.types.record_name(field.semantic_parent.type) or field.semantic_parent.spelling
        macro = SLOT_BOUNDS.get((owner, field.spelling))
        if macro is None:
            return "Int.max", "C gives the pointer no bound, so the Slots takes the widest count."
        exported = self.exported_names(target)
        spelled = f"{exported[macro]}.{macro}" if macro in exported and exported[macro] != VIEW_OF[target] else macro
        return f"Int({spelled})", f"Raven's `{macro}` bounds the records behind the pointer."

    def slots(self, field: ci.Cursor, view: str, c_name: str, target: str) -> list[str]:
        """The second accessor of a struct pointer field a body indexes, the Slots over the records the pointer holds.

        A `float *` field carries its vector accessor the same way. The pointer stays inside the view by rule 11."""
        if not self.indexed(field):
            return []
        name = field.spelling
        pointee = f"self.raw.pointee.{name}"
        count, reason = self.slots_count(field, target)
        return [
            "",
            f"    /// Raven's `{name}[i]`, the records the pointer holds. A NULL pointer traps with the field's name.",
            f"    /// {reason}",
            f"    public var {name}Slots: Slots<{view}> {{",
            "        get {",
            f"            precondition({pointee} != nil, \"{name} is NULL\")",
            f"            return Slots(views: UnsafeMutableRawPointer({pointee}!), count: {count}, stride: {view}.stride)",
            "        }",
            f"        nonmutating set {{ {pointee} = newValue.base.assumingMemoryBound(to: {c_name}.self) }}",
            "    }",
        ]

    def never_null(self, field: ci.Cursor) -> bool:
        owner = self.types.record_name(field.semantic_parent.type) or field.semantic_parent.spelling
        return (owner, field.spelling) in NEVER_NULL

    def trapping(self, name: str, swift: str, get: str, set_: str) -> list[str]:
        """A field of NEVER_NULL: the getter traps with the field's name when the pointer is NULL, so a body reads it with no bind."""
        pointee = f"self.raw.pointee.{name}"
        return [
            f"    /// Raven's callers always set `{name}`, so a body reads it with no bind. A NULL here traps with the field's name.",
            f"    public var {name}: {swift} {{",
            "        get {",
            f"            precondition({pointee} != nil, \"{name} is NULL\")",
            f"            return {get}",
            "        }",
            f"        nonmutating set {{ {set_} }}",
            "    }",
        ]

    def c_signature(self, proto: ci.Type, target: str) -> str:
        """The `@convention(c)` spelling of a function prototype, the type a stored function has in Swift."""
        c_params: list[str] = []
        for arg in proto.argument_types():
            if arg.get_canonical().kind == TypeKind.POINTER:
                c_params.append("OpaquePointer?")
            elif self.types.scalar(arg, target) == "Bool":
                c_params.append("Int32")
            else:
                c_params.append(self.types.scalar(arg, target) or "Int32")
        result = proto.get_result()
        returns = self.types.scalar(result, target) if result.get_canonical().kind != TypeKind.VOID else None
        c_result = "Int32" if returns == "Bool" else returns or "Void"
        return f"@convention(c) ({', '.join(c_params)}) -> {c_result}"

    def callback_alias(self, proto: ci.Type, target: str) -> str | None:
        """The callback typealias a view field holds for this prototype, qualified for the target, or None when no field has it.
        Every alias of one signature is the same type, so the first in name order serves."""
        signature = self.c_signature(proto, target)
        for owner in [target] + DEPS[target]:
            # The aliases are read from the Callbacks file views.py wrote, the same way exported_names reads reexport's names.
            path = SOURCES / VIEW_OF[owner] / "Generated" / "Views" / "Callbacks.swift"
            text = path.read_text() if path.exists() else ""
            aliases = sorted(alias for alias, sig in re.findall(r"^public typealias (\w+) = (@convention\(c\) .*)$", text, re.M) if sig == signature)
            if aliases:
                return aliases[0] if owner == target else f"{VIEW_OF[owner]}.{aliases[0]}"
        return None

    def callback(self, field: ci.Cursor, target: str) -> list[str]:
        """A stored function keeps the C type. The typealias per signature and the run method per field are collected for one file."""
        name = field.spelling
        proto = field.type.get_canonical().get_pointee()
        view = self.views[self.types.record_name(field.semantic_parent.type) or field.semantic_parent.spelling][0]
        alias = f"{view}{name[0].upper()}{name[1:]}"
        names = [c.spelling or f"p{i}" for i, c in enumerate(c for c in field.get_children() if c.kind == CursorKind.PARM_DECL)]
        params: list[str] = []
        args: list[str] = []
        layers: list[str] = []
        owner = self.types.record_name(field.semantic_parent.type) or field.semantic_parent.spelling
        arg_types = list(proto.argument_types())
        first_record = self.types.record_name(arg_types[0].get_canonical().get_pointee()) if arg_types and arg_types[0].get_canonical().kind == TypeKind.POINTER else None
        owner_first = first_record == owner
        for i, arg in enumerate(arg_types):
            canonical = arg.get_canonical()
            label = names[i] if i < len(names) else f"p{i}"
            if canonical.kind == TypeKind.POINTER:
                pointee = canonical.get_pointee()
                record = self.types.record_name(pointee)
                if record in self.views:
                    params.append(f"_ {label}: {self.qualified_view(record, target)}?")
                    args.append(f"{label}?.handle")
                elif pointee.get_canonical().kind == TypeKind.FLOAT:
                    # A `vec_t *` parameter is a vector, by value when const and inout when Raven writes it, rule 11.
                    if pointee.is_const_qualified():
                        params.append(f"_ {label}: JKAShared.vec3_t")
                        layers.append(f"withUnsafePointer(to: {label}) {{ {label} in")
                    else:
                        params.append(f"_ {label}: inout JKAShared.vec3_t")
                        layers.append(f"withUnsafeMutablePointer(to: &{label}) {{ {label} in")
                    args.append(f"OpaquePointer({label})")
                else:
                    params.append(f"_ {label}: OpaquePointer?")
                    args.append(label)
            elif self.types.scalar(arg, target) == "Bool":
                # Rule 7: qboolean is Bool at the surface, and its C shape is a four-byte enum, so Int32 in the thunk's signature.
                params.append(f"_ {label}: Bool")
                args.append(f"{label} ? 1 : 0")
            else:
                swift = self.types.scalar(arg, target) or "Int32"
                params.append(f"_ {label}: {swift}")
                args.append(label)
        result = proto.get_result()
        returns = self.types.scalar(result, target) if result.get_canonical().kind != TypeKind.VOID else None
        self.callbacks[(target, alias)] = self.c_signature(proto, target)
        # When Raven's first parameter is the owner, the run method passes this slot and takes the rest.
        # Otherwise every parameter is the caller's, as `pm->trace(&trace, start, ...)` is.
        if owner_first:
            rest = params[1:]
            args = ["self.handle"] + args[1:]
            doc = f"    /// Calls the stored `{name}` function through the C pointer, with this slot first, as Raven's `ent->{name}(ent, ...)` did."
        else:
            rest = params
            doc = f"    /// Calls the stored `{name}` function through the C pointer, with the caller's arguments, as Raven's `pm->{name}(...)` did."
        pointee = f"self.raw.pointee.{name}"
        always = self.never_null(field)
        if always:
            lines = self.trapping(name, alias, f"unsafeBitCast({pointee}, to: {alias}.self)",
                                  f"{pointee} = unsafeBitCast(newValue, to: Swift.type(of: {pointee}))")
            call = f"self.{name}({', '.join(args)})"
            if returns == "Bool":
                call = f"{call} != 0"
        else:
            lines = self.property(name, f"{alias}?", f"unsafeBitCast({pointee}, to: {alias}?.self)",
                                  f"{pointee} = unsafeBitCast(newValue, to: Swift.type(of: {pointee}))")
            # Raven calls through the pointer with no NULL test, so the run method traps with the field's name where C would crash.
            # A site where Raven tests the pointer first keeps his test on the field itself.
            call = f"self.{name}!({', '.join(args)})"
            if returns == "Bool":
                call = f"{call} != 0"
            doc += f"\n    /// A NULL `{name}` traps with the field's name, as Raven's call through the pointer would crash."
        body: list[str] = []
        if not always:
            body.append(f"        precondition({pointee} != nil, \"{name} is NULL\")")
        head = "return " if returns and not always else ""
        if layers:
            body.append("        " + head + layers[0])
            for depth, layer in enumerate(layers[1:], start=3):
                body.append("    " * depth + layer)
            body.append("    " * (len(layers) + 2) + call)
            for depth in range(len(layers) + 1, 1, -1):
                body.append("    " * depth + "}")
        else:
            body.append(f"        {head}{call}")
        # A callback's return is `@discardableResult`, because Raven drops it at most sites and C never warned.
        if returns:
            doc += "\n    @discardableResult"
        lines += [
            "",
            doc,
            f"    public func run{name[0].upper()}{name[1:]}({', '.join(rest)}){f' -> {returns}' if returns else ''} {{",
            *body,
            "    }",
        ]
        return lines

    # MARK: - Emission

    def emit(self) -> dict[tuple[str, str], list[str]]:
        """The Swift files, keyed by (view target, file stem)."""
        files: dict[tuple[str, str], list[str]] = {}
        for c_name, (view, target) in self.views.items():
            record = self.records[c_name]
            sources = source_lines(record)
            base_line = int(sources[0].rsplit(":", 1)[1]) if sources else 0
            source_path = sources[0].rsplit(":", 1)[0] if sources else "unknown"
            lines = [f"/// Source: {s}" for s in sources]
            local = c_name[:-2] if c_name.endswith("_t") else c_name
            lines += [
                f"/// A view over one `{c_name}` in C memory.",
                "/// A copy of a view is a copy of the pointer, and two views of one slot compare equal.",
                f"public struct {view}: Hashable, HandleView {{",
                f"    let raw: UnsafeMutablePointer<{c_name}>",
                "",
                "    init(raw: UnsafeMutablePointer<" + c_name + ">) { self.raw = raw }",
                "",
                "    /// The slot behind a handle a generated thunk received. Rule 11 confines the handle to generated code.",
                "    public init(handle: OpaquePointer) { self.raw = UnsafeMutablePointer(handle) }",
                "",
                f"    /// Raven's cast from a raw pointer, `({c_name} *)p`. A body writes this where and only where Raven wrote the cast.",
                f"    public init(_ raw: UnsafeMutableRawPointer) {{ self.raw = raw.assumingMemoryBound(to: {c_name}.self) }}",
                "",
                f"    /// Raven's cast from another struct's pointer over the same memory, `({c_name} *)other`.",
                "    public init(_ other: some HandleView) { self.raw = UnsafeMutablePointer(other.handle) }",
                "",
                "    /// The slot as a handle, for a stored function call and for a view in another module.",
                "    public var handle: OpaquePointer { OpaquePointer(self.raw) }",
                "",
                "    /// The size of one slot in bytes, for a module that allocates its own slot and cannot see the C type.",
                f"    public static let byteCount = MemoryLayout<{c_name}>.size",
                "",
                "    /// The distance between two slots of a C array of this type, for a Slots over one.",
                f"    public static let stride = MemoryLayout<{c_name}>.stride",
                "",
                f"    /// Raven's `{c_name} {local};` on the stack. The slot is zero at entry, lives for the closure, and the closure's value is the result.",
                f"    public static func scratch<Result>(_ body: ({view}) throws -> Result) rethrows -> Result {{",
                f"        var slot = {c_name}()",
                f"        return try withUnsafeMutablePointer(to: &slot) {{ try body({view}(raw: $0)) }}",
                "    }",
                "",
                f"    /// Raven's `{c_name} {local}[N];` on the stack, a local array of records.",
                "    /// The slots are zero at entry, live for the closure, and the closure's value is the result.",
                f"    public static func scratch<Result>(count: Int, _ body: (Slots<{view}>) throws -> Result) rethrows -> Result {{",
                f"        let base = UnsafeMutableRawPointer.allocate(byteCount: count * {view}.stride, alignment: MemoryLayout<{c_name}>.alignment)",
                "        defer { base.deallocate() }",
                f"        base.initializeMemory(as: UInt8.self, repeating: 0, count: count * {view}.stride)",
                f"        return try body(Slots(views: base, count: count, stride: {view}.stride))",
                "    }",
                "",
                f"    /// Raven's `{c_name} {local} = *other;`, a copy of another slot on the stack.",
                f"    public static func scratch<Result>(copying other: {view}, _ body: ({view}) throws -> Result) rethrows -> Result {{",
                "        var slot = other.raw.pointee",
                f"        return try withUnsafeMutablePointer(to: &slot) {{ try body({view}(raw: $0)) }}",
                "    }",
                "",
                f"    /// Raven's `memset(&{local}, 0, sizeof({local}))`, every byte of the slot to zero.",
                "    public func clear() {",
                f"        self.raw.pointee = {c_name}()",
                "    }",
                "",
                f"    /// Raven's `{local} = *other;` or his `memcpy`, every byte of the other slot into this one.",
                f"    public func copy(from other: {view}) {{",
                "        self.raw.pointee = other.raw.pointee",
                "    }",
            ]
            if c_name == "pmove_t":
                # Raven's `(bgEntity_t *)((byte *)pm->baseEnt + pm->entSize*(num))` in PM_BGEntForNum: bg code runs in three modules
                # with three entity sizes, so the pmove record carries the first entity and the stride, and the walk stays in the view.
                lines += [
                    "",
                    "    /// Raven's `(byte *)baseEnt + entSize * num`, the entity at an index by the stride the host module set.",
                    "    /// A NULL `baseEnt` or a zero `entSize` traps, as Raven's asserts do.",
                    "    public func entity(at num: Int32) -> BgEntity {",
                    "        precondition(self.raw.pointee.baseEnt != nil, \"baseEnt is NULL\")",
                    "        precondition(self.raw.pointee.entSize != 0, \"entSize is 0\")",
                    "        let bytes = UnsafeMutableRawPointer(self.raw.pointee.baseEnt!) + Int(self.raw.pointee.entSize) * Int(num)",
                    "        return BgEntity(handle: OpaquePointer(bytes))",
                    "    }",
                ]
            for field in record.get_children():
                if field.kind != CursorKind.FIELD_DECL:
                    continue
                delta = field.location.line - record.location.line
                lines.append("")
                lines.append(f"    /// Source: {source_path}:{base_line + delta}")
                body = self.accessor(field, target)
                if body is None:
                    self.todo += 1
                    text = " ".join(t.spelling for t in field.get_tokens())
                    lines += [f"    // TODO: Port {c_name}.{field.spelling}", f"    // Raven wrote: {text}"]
                else:
                    lines += body
            lines.append("}")
            files[(VIEW_OF[target], view)] = lines
        by_target: dict[str, list[tuple[str, str]]] = defaultdict(list)
        for (target, alias), signature in sorted(self.callbacks.items()):
            by_target[target].append((alias, signature))
        for target, aliases in by_target.items():
            lines = ["/// The C types of the stored functions, one per signature, and the address compare Raven's `==` did."]
            for alias, signature in aliases:
                lines += [f"public typealias {alias} = {signature}", ""]
            # A typealias is not a new type, so one == serves every alias of a signature, and a dependency's == already covers its own.
            covered = {sig for (dep, _), sig in self.callbacks.items() if dep in DEPS[target]}
            for alias, signature in aliases:
                if signature in covered:
                    continue
                covered.add(signature)
                # The pointer is read from a box, not passed to a generic, so no reabstraction thunk can change the word.
                # NIOSSL's `ClosureBits` in `TLSConfiguration.swift` is the precedent.
                lines += [
                    f"private struct {alias}Bits {{ var function: {alias}? }}",
                    "",
                    f"public func == (lhs: {alias}?, rhs: {alias}?) -> Bool {{",
                    f"    precondition(MemoryLayout<{alias}Bits>.size == MemoryLayout<UInt>.size)",
                    f"    return withUnsafeBytes(of: {alias}Bits(function: lhs)) {{ $0.load(as: UInt.self) }}",
                    f"        == withUnsafeBytes(of: {alias}Bits(function: rhs)) {{ $0.load(as: UInt.self) }}",
                    "}",
                    "",
                ]
            files[(VIEW_OF[target], "Callbacks")] = lines
        return files


def write(files: dict[tuple[str, str], list[str]], only: bool) -> int:
    by_view: dict[str, dict[str, list[str]]] = defaultdict(dict)
    for (view, stem), lines in files.items():
        by_view[view][stem] = lines
    target_of_view = {v: k for k, v in VIEW_OF.items()}
    count = 0
    for view, stems in by_view.items():
        out = SOURCES / view / "Generated" / "Views"
        if out.exists() and not only:
            for old in out.glob("*.swift"):
                old.unlink()
        out.mkdir(parents=True, exist_ok=True)
        target = target_of_view[view]
        imports = [f"internal import {target}"] + [f"import {VIEW_OF[d]}" for d in DEPS[target]]
        for stem, lines in sorted(stems.items()):
            text = [NOTE, ""] + imports + [""] + lines
            (out / f"{stem}.swift").write_text("\n".join(text).rstrip() + "\n")
            count += 1
    return count


def indexed_fields(gen: Generator) -> set[tuple[str, str]]:
    """The struct pointer fields a body indexes, which table.py computes in its subscript sweep.

    A fact about the C belongs to one place, so views.py reads the sweep instead of walking the bodies again.
    table.py imports this file for the view names, so the import of it happens here, inside the one function that needs it."""
    from table import Table

    table = Table(gen.parse, views=gen)
    table.sweep()
    return table.indexed_fields


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rebuild", action="store_true", help="sweep every fact of the table again and write the store anew")
    ap.add_argument("--only", help="one root struct, for a look at its closure alone")
    args = ap.parse_args()
    import table

    table.REBUILD = args.rebuild
    gen = Generator(C.Parse(), args.only)
    gen.indexed_fields = indexed_fields(gen)
    files = gen.emit()
    written = write(files, bool(args.only))
    per_target: dict[str, int] = defaultdict(int)
    for view, _ in files:
        per_target[view] += 1
    print(f"views.py: {written} files, {len(gen.views)} views, {len(gen.callbacks)} callback types, {gen.todo} TODO: Port markers")
    for view, n in sorted(per_target.items()):
        print(f"  {view:12} {n} files")


if __name__ == "__main__":
    main()
