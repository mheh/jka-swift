#!/usr/bin/env python3
"""channel.py: the bg channel of rule 23, the closures a consumer installs so a bg body reaches the engine and the game.

Reads the mp-game unity parse, and the mp-cgame unity parse for the cgame arms of the bg files, and writes three files:

  Sources/JKAMP_BG/Generated/bg_strap.swift         one `strap_` function per declaration of bg_strap.h, forwarding to a
                                                    closure on `bg.straps`, and the `BgStraps` struct that holds them
  Sources/JKAMP_BG/Generated/bg_callbacks.swift     one bare function per game function a bg body calls directly, forwarding
                                                    to a closure on `bg.callbacks`, and the `BgCallbacks` struct
  Sources/JKAMP_GameLogic/Generated/BgChannel.swift `installBgChannel()`, which points every closure at the game's function
                                                    of the same name and turns a `BgEntity` into an `Entity` by its handle

A signature the table cannot map is a `TODO: Port signature` marker with Raven's C text, and the struct has no closure for
it. A bg body spells `strap_G2API_SetBoneAngles(...)` and `G_NewString(...)` as Raven wrote them. The `Entity` view lives
in the game target, which bg cannot import, so the bg side of the channel names `JKAMP.BgEntity` over the same memory.

Usage:
  .venv/bin/python channel.py            # writes the three files and prints the counts
  .venv/bin/python channel.py --only bg  # prints the two bg files to stdout, writes nothing
"""

from __future__ import annotations

import argparse
import re
from collections import Counter
from pathlib import Path

import clang.cindex as ci
from clang.cindex import CursorKind

import closure as C
from reexport import REPO, SOURCES
from rulings import EXTRA_HOOKS, OWN_HOOKS, SHARED_STEMS
from overlay import OVERLAY
from table import Param, SourceFile, Table

ORACLE_DIR = "codemp/game"
CGAME_DIR = "codemp/cgame"
STRAP_HEADER = "bg_strap.h"
NOTE = "// Generated by tools/oracle-closure/channel.py from the oracle's {source}. Do not edit. Rule 23."
ENTITY = re.compile(r"\bEntity\b")


class Hook:
    """One function of the channel: Raven's declaration, the table's signature, and the reason when it has none."""

    def __init__(self, cur: ci.Cursor | None, name: str, cite: str | None = None, foreign: bool = False) -> None:
        self.cur = cur
        self.name = name
        self.params: list[Param] = []
        self.returns: str | None = None
        self.reason: str | None = None
        # A foreign hook is one another consumer defines, so the game's install skips it.
        # An EXTRA_HOOKS entry takes its shape from a game function and its cite from the consumer that defines it.
        # A hook the cgame parse found takes its shape and its cite from the cgame definition.
        self.foreign = foreign or cite is not None
        self._cite = cite
        # A read hook carries the game's expression for its install closure, and no function stands behind it.
        self.install: str | None = None
        # A trap hook takes the trap's own shape, the one traps.py wrote in g_syscalls.swift, so a filled buffer is a returned String.
        self.trap = name.startswith("trap_")

    @property
    def cite(self) -> str:
        if self._cite is not None:
            return self._cite
        path = Path(self.cur.location.file.name).resolve().relative_to(C.ORACLE.resolve())
        return f"oracle/{path}:{self.cur.location.line}"

    @property
    def mapped(self) -> bool:
        return self.reason is None

    @property
    def crossing(self) -> list[Param]:
        """The parameters the Swift signature carries. A trap's filled buffer crosses as the return instead."""
        return [p for p in self.params if p.swift is not None]

    def bg_types(self) -> list[str]:
        return [ENTITY.sub("JKAMP.BgEntity", p.swift or "") for p in self.crossing]

    def bg_returns(self) -> str | None:
        # A trap that fills a buffer returns the text, beside its word when Raven returned one, the shape traps.py writes.
        outs = [p for p in self.params if p.kind == "out_string"]
        returns = self.returns
        if outs and returns:
            returns = f"({returns}, String)"
        elif outs:
            returns = "String"
        return ENTITY.sub("JKAMP.BgEntity", returns) if returns else None

    def signature(self) -> str:
        return ", ".join(f"_ {p.name}: {t}" for p, t in zip(self.crossing, self.bg_types()))

    def closure_type(self) -> str:
        return f"({', '.join(self.bg_types())}) -> {self.bg_returns() or 'Void'}"

    def words(self) -> str:
        """The arguments a bare function forwards, `&` for an inout."""
        return ", ".join(f"&{p.name}" if (p.swift or "").startswith("inout ") else p.name for p in self.crossing)


class Channel:
    def __init__(self) -> None:
        self.table = Table()
        # Both parses take the overlay bodies.py drafts against, so a read inside Raven's vector macros has its own nodes.
        self.tu = C.parse_tu("mp-game", None, unity=True, overlay=OVERLAY)
        self.game = (C.ORACLE / ORACLE_DIR).resolve()
        # The cgame parse compiles the bg files under CGAME, so the calls on Raven's `#else` arms exist in it.
        self.cgame_tu = C.parse_tu("mp-cgame", None, unity=True, overlay=OVERLAY)
        self.cgame = (C.ORACLE / CGAME_DIR).resolve()
        self.table.sweep(self.tu, self.game, other=self.cgame_tu, other_folder=self.cgame)
        self.sources: dict[Path, SourceFile] = {}
        self.counts: Counter[str] = Counter()
        self.straps = self.collect_straps()
        self.callbacks = self.collect_callbacks() + self.collect_reads()

    def source(self, path: Path) -> SourceFile:
        if path not in self.sources:
            self.sources[path] = SourceFile(path)
        return self.sources[path]

    def map(self, hook: Hook) -> None:
        params = list(hook.cur.get_arguments())
        for i, p in enumerate(params):
            following = params[i + 1] if i + 1 < len(params) else None
            m = self.table.param(p, following, traps=hook.trap, owner=hook.name)
            if m is None or (m.swift is None and m.kind != "out_string"):
                hook.reason = self.table.marker_reason(p, hook.name)
                return
            hook.params.append(m)
        result = self.table.result(hook.cur)
        if result is None:
            hook.reason = f"No table row for the return `{hook.cur.result_type.spelling}`."
            return
        hook.returns = result[0]

    # MARK: - Collecting

    def definitions(self) -> dict[str, tuple[str, ci.Cursor]]:
        """Every function definition of the game's .c files, by name, with its file stem."""
        if not hasattr(self, "_definitions"):
            self._definitions = self.definitions_of(self.tu, self.game)
        return self._definitions

    def cgame_definitions(self) -> dict[str, tuple[str, ci.Cursor]]:
        """Every function definition of the cgame's .c files, by name, with its file stem."""
        if not hasattr(self, "_cgame_definitions"):
            self._cgame_definitions = self.definitions_of(self.cgame_tu, self.cgame)
        return self._cgame_definitions

    @staticmethod
    def definitions_of(tu: ci.TranslationUnit, folder: Path) -> dict[str, tuple[str, ci.Cursor]]:
        definitions: dict[str, tuple[str, ci.Cursor]] = {}
        for cur in tu.cursor.get_children():
            if cur.kind == CursorKind.FUNCTION_DECL and cur.is_definition() and cur.location.file:
                path = Path(cur.location.file.name).resolve()
                if path.parent == folder and path.suffix == ".c":
                    definitions[cur.spelling] = (path.stem, cur)
        return definitions

    def called_from_bg(self) -> list[str]:
        """Every function name a bg body calls on either consumer's arms, in name order, resolved or not."""
        if not hasattr(self, "_called"):
            called: set[str] = set()

            def walk(node: ci.Cursor) -> None:
                if node.kind == CursorKind.CALL_EXPR and node.referenced is not None and node.referenced.kind == CursorKind.FUNCTION_DECL:
                    called.add(node.referenced.spelling)
                for child in node.get_children():
                    walk(child)

            for tu in (self.tu, self.cgame_tu):
                for cur in tu.cursor.get_children():
                    if cur.kind == CursorKind.FUNCTION_DECL and cur.is_definition() and cur.location.file:
                        path = Path(cur.location.file.name).resolve()
                        if path.parent == self.game and path.stem.startswith("bg_"):
                            walk(cur)
            self._called = sorted(called)
        return self._called

    def collect_straps(self) -> list[Hook]:
        """Every declaration of bg_strap.h, once, in Raven's order, then every trap a bg body calls by name.
        A trap the game's g_syscalls.c defines takes that shape. A trap only the cgame's cg_syscalls.c defines takes that shape as a foreign hook,
        which the game's install skips. A trap neither defines keeps a marker by name."""
        hooks: dict[str, Hook] = {}
        for cur in self.tu.cursor.get_children():
            if cur.kind != CursorKind.FUNCTION_DECL or cur.is_definition() or not cur.location.file:
                continue
            if Path(cur.location.file.name).name != STRAP_HEADER or cur.spelling in hooks:
                continue
            hook = Hook(cur, cur.spelling)
            self.map(hook)
            hooks[cur.spelling] = hook
        definitions = self.definitions()
        cgame = self.cgame_definitions()
        for name in self.called_from_bg():
            if not name.startswith("trap_") or name in hooks:
                continue
            found = definitions.get(name)
            in_cgame = cgame.get(name)
            if found and found[0] == "g_syscalls":
                hook = Hook(found[1], name)
                self.map(hook)
            elif in_cgame and in_cgame[0] == "cg_syscalls":
                hook = Hook(in_cgame[1], name, foreign=True)
                self.map(hook)
            else:
                hook = Hook(None, name, "oracle/codemp/cgame/cg_syscalls.c")
                hook.reason = "No consumer's syscalls define this trap."
            hooks[name] = hook
        return list(hooks.values())

    def collect_callbacks(self) -> list[Hook]:
        """Every game function a bg body calls by name, by the definitions the unity parse compiled,
        then every cgame function a bg body calls on a cgame arm, as a foreign hook shaped from the cgame definition."""
        definitions = self.definitions()
        cgame = self.cgame_definitions()
        called: dict[str, ci.Cursor] = {}
        foreign: set[str] = set()
        for name in self.called_from_bg():
            found = definitions.get(name)
            if found and not found[0].startswith("bg_") and found[0] not in SHARED_STEMS and name not in OWN_HOOKS:
                called.setdefault(name, found[1])
        for name, (shape, cite) in EXTRA_HOOKS.items():
            called.setdefault(name, definitions[shape][1])
        for name in self.called_from_bg():
            in_cgame = cgame.get(name)
            if name in called or name in definitions or name.startswith("trap_") or not in_cgame or in_cgame[0] == "cg_syscalls":
                continue
            called[name] = in_cgame[1]
            foreign.add(name)
        hooks = []
        for name in sorted(called):
            hook = Hook(called[name], name, EXTRA_HOOKS[name][1] if name in EXTRA_HOOKS else None, foreign=name in foreign)
            self.map(hook)
            hooks.append(hook)
        return hooks

    def collect_reads(self) -> list[Hook]:
        """One callback per game field a bg body reaches, from the table's read sweep, by the hole walk's row 1.
        The game's install reads or writes the field through its own views, so the bg module keeps no view of the game."""
        hooks = []
        for read in self.table.sweep_reads(self.tu, self.game):
            hook = Hook(None, read.name, cite=read.cite)
            hook.foreign = False
            hook.install = read.install
            if read.entity:
                hook.params.append(Param("ent", "JKAMP.BgEntity", "view"))
            if read.write:
                hook.params.append(Param("value", read.swift, "bare"))
            else:
                hook.returns = read.swift
            hooks.append(hook)
        return hooks

    # MARK: - The bg side

    def bg_file(self, hooks: list[Hook], struct: str, store: str, source: str, doc: str) -> list[str]:
        lines = [NOTE.format(source=source), "", "import JKAMP", "import JKAShared", "", f"/// {doc}",
                 "/// A default traps as a marker, so a consumer that installs nothing fails at the first call and names it.",
                 f"public struct {struct} {{"]
        for hook in hooks:
            if not hook.mapped:
                continue
            blanks = ", ".join("_" for _ in hook.crossing)
            default = f"{{ {blanks} in portMissing(\"{hook.name}\", source: \"{hook.cite}\") }}" if hook.crossing else \
                f"{{ portMissing(\"{hook.name}\", source: \"{hook.cite}\") }}"
            lines += [f"    /// Source: {hook.cite}", f"    public var {hook.name}: {hook.closure_type()} = {default}", ""]
        lines += ["    public init() {}", "}", ""]
        for hook in hooks:
            lines.append(f"/// Source: {hook.cite}")
            if not hook.mapped:
                self.counts["markers"] += 1
                if hook.cur is None:
                    wrote = "a trap of the cgame module"
                else:
                    source_file = self.source(Path(hook.cur.location.file.name))
                    wrote = source_file.c_signature(hook.cur) if hook.cur.is_definition() else ' '.join(source_file.slice(hook.cur.extent).split())
                lines += [
                    "// TODO: Port signature",
                    f"// Raven wrote: {wrote}",
                    f"// {hook.reason}",
                    f"func {hook.name}() -> Never {{",
                    f"    portMissing(\"{hook.name}\", source: \"{hook.cite}\")",
                    "}",
                    "",
                ]
                continue
            self.counts["hooks"] += 1
            returns = f" -> {hook.bg_returns()}" if hook.bg_returns() else ""
            # A returning hook is discardable like the trap behind it, so a body reads Raven's line without `_ =`.
            lines += (["@discardableResult"] if returns else []) + [
                f"func {hook.name}({hook.signature()}){returns} {{",
                f"    bg.{store}.{hook.name}({hook.words()})",
                "}",
                "",
            ]
            lines += self.buffer_overload(hook, store)
        return lines

    def buffer_overload(self, hook: Hook, store: str) -> list[str]:
        """The second overload of docket row 7, for a `void *` parameter Raven's own callers fill with a `char buf[N]`.

        The buffer hands the engine its base inside one unsafe scope here, so a bg body passes the buffer bare and no `Unsafe`
        type reaches a logic target. The first overload stays for a caller that holds a raw allocation."""
        fills = [p for p in hook.crossing if p.swift == "OpaquePointer?" and self.table.fills_buffer(hook.name, p.name)]
        if len(fills) != 1:
            return []
        buffer = fills[0]
        signature = ", ".join(f"_ {p.name}: " + ("inout JKAShared.CharBuf" if p is buffer else t)
                              for p, t in zip(hook.crossing, hook.bg_types()))
        words = []
        for p, t in zip(hook.crossing, hook.bg_types()):
            if p is buffer:
                words.append("OpaquePointer(base)")
            elif t.startswith("inout "):
                words.append(f"&{p.name}")
            else:
                words.append(p.name)
        returns = f" -> {hook.bg_returns()}" if hook.bg_returns() else ""
        self.counts["buffer overloads"] += 1
        return [
            f"/// Source: {hook.cite}",
            f"/// Raven's `{buffer.name}` takes a `char buf[N]` at his own call sites, and this overload hands the engine that buffer's base.",
        ] + (["@discardableResult"] if returns else []) + [
            f"func {hook.name}({signature}){returns} {{",
            f"    {'return ' if returns else ''}{buffer.name}.withUnsafeMutableRawPointer {{ base in",
            f"        bg.{store}.{hook.name}({', '.join(words)})",
            "    }",
            "}",
            "",
        ]

    # MARK: - The game side

    def install_file(self) -> list[str]:
        lines = [NOTE.format(source="bg_strap.h and the bg call sites"), "", "import JKAMP", "import JKAMP_BG", "import JKAMP_Game", "",
                 "/// The game module points every closure of the bg channel at its own function of the same name.",
                 "/// `dllEntry` calls this once. A `BgEntity` bg holds becomes the `Entity` the game function takes, by its handle, under rule 11.",
                 "public func installBgChannel() {"]
        for store, hooks in (("straps", self.straps), ("callbacks", self.callbacks)):
            for hook in hooks:
                if not hook.mapped or hook.foreign:
                    continue
                names = ", ".join(p.name for p in hook.crossing) or ""
                if hook.install is not None:
                    head = f"    bg.{store}.{hook.name} = {{ {names} in" if names else f"    bg.{store}.{hook.name} = {{"
                    lines += [head, f"        {hook.install}", "    }"]
                    continue
                args = []
                for p, t in zip(hook.crossing, hook.bg_types()):
                    if t == "JKAMP.BgEntity":
                        args.append(f"Entity(handle: {p.name}.handle)")
                    elif t == "JKAMP.BgEntity?":
                        args.append(f"{p.name}.map {{ Entity(handle: $0.handle) }}")
                    elif t.startswith("inout "):
                        args.append(f"&{p.name}")
                    else:
                        args.append(p.name)
                call = f"{hook.name}({', '.join(args)})"
                returns = hook.returns or ""
                if returns == "Entity?":
                    call = f"{call}.map {{ JKAMP.BgEntity(handle: $0.handle) }}"
                elif returns == "Entity":
                    call = f"JKAMP.BgEntity(handle: {call}.handle)"
                head = f"    bg.{store}.{hook.name} = {{ {names} in" if names else f"    bg.{store}.{hook.name} = {{"
                lines += [head, f"        {call}", "    }"]
        lines += ["}"]
        return lines

    def write(self) -> None:
        bg_dir = SOURCES / "JKAMP_BG" / "Generated"
        bg_dir.mkdir(parents=True, exist_ok=True)
        (bg_dir / "bg_strap.swift").write_text("\n".join(self.strap_file()).rstrip() + "\n")
        (bg_dir / "bg_callbacks.swift").write_text("\n".join(self.callback_file()).rstrip() + "\n")
        out = SOURCES / "JKAMP_GameLogic" / "Generated" / "BgChannel.swift"
        out.write_text("\n".join(self.install_file()).rstrip() + "\n")

    def strap_file(self) -> list[str]:
        return self.bg_file(self.straps, "BgStraps", "straps", STRAP_HEADER,
                            "The strap functions of `bg_strap.h`, which the consumer installs over its own traps at its entry point, rule 23.")

    def callback_file(self) -> list[str]:
        return self.bg_file(self.callbacks, "BgCallbacks", "callbacks", "bg call sites",
                            "The game functions a bg body calls by name, which the game installs at its entry point, rule 23.")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", choices=["bg", "game"], help="print to stdout, write nothing")
    args = ap.parse_args()
    channel = Channel()
    if args.only == "bg":
        print("\n".join(channel.strap_file()))
        print("\n".join(channel.callback_file()))
        return
    if args.only == "game":
        print("\n".join(channel.install_file()))
        return
    channel.write()
    c = channel.counts
    print(f"channel.py: {len(channel.straps)} straps and {len(channel.callbacks)} callbacks, {c['hooks']} hooks, {c['markers']} TODO: Port signature markers")


if __name__ == "__main__":
    main()
