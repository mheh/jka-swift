"""The unit of a run: each fact of the `[targets]` row that a generator reads keeps the game value when the command line names no `--unit`."""

from __future__ import annotations

import sys
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HERE))

REPO = HERE.parents[1]


class DefaultUnit(unittest.TestCase):
    def test_a_command_line_with_no_unit_reads_the_game(self) -> None:
        import closure as C

        # given a command line with no --unit, and two with one
        # then the first reads the game, and the others read the unit they name
        self.assertEqual(C.unit_of(["--game"]), "mp-game")
        self.assertEqual(C.unit_of(["--unit", "mp-cgame", "--game"]), "mp-cgame")
        self.assertEqual(C.unit_of(["--unit=mp-cgame"]), "mp-cgame")
        self.assertEqual(C.UNIT, "mp-game")

    def test_the_other_unit_and_both_folders_are_the_game_values(self) -> None:
        import closure as C

        self.assertEqual(C.OTHER_UNIT, "mp-cgame")
        self.assertEqual(C.GAME_DIR, "codemp/game")
        self.assertEqual(C.CGAME_DIR, "codemp/cgame")

    def test_the_game_writes_into_the_repository(self) -> None:
        import closure as C

        # given the game, whose logic target is under Sources
        path = REPO / "Sources" / "JKAMP_GameLogic" / "g_main.swift"

        # then the run writes each path where it stands
        self.assertFalse(C.STAGED)
        self.assertEqual(C.written(path), path)

    def test_the_trap_file_is_g_syscalls(self) -> None:
        import skeleton
        import traps

        self.assertEqual(skeleton.SKIP, {"g_syscalls.c"})
        self.assertEqual(traps.SOURCE, "codemp/game/g_syscalls.c")
        self.assertEqual(traps.NOTE, "// Generated by tools/oracle-closure/traps.py from the oracle's g_syscalls.c. Do not edit. Rule 11 and rule 13.")

    def test_the_logic_target_is_the_game_logic(self) -> None:
        import skeleton

        self.assertEqual(skeleton.LOGIC, "JKAMP_GameLogic")
        self.assertEqual(skeleton.stub_path("g_main"), REPO / "Sources" / "JKAMP_GameLogic" / "g_main.swift")
        self.assertEqual(skeleton.stub_path("bg_pmove"), REPO / "Sources" / "JKAMP_BG" / "bg_pmove.swift")

    def test_the_view_target_is_the_game_views(self) -> None:
        import draft_expressions
        import skeleton
        import traps

        self.assertEqual(skeleton.VIEWS, "JKAMP_Game")
        self.assertEqual(traps.VIEW, "JKAMP_Game")
        self.assertEqual(draft_expressions.GAME_SIDE, {"JKAMP_GameLogic", "JKAMP_Game"})

    def test_the_c_target_is_the_game_target(self) -> None:
        import reexport
        import skeleton
        import spelling
        import table
        import traps
        import views

        # given the game, the C target of every generator is the game's
        self.assertEqual(traps.IMPORT, "CJKAMP_Game")
        for target in (skeleton.C_TARGET, spelling.TARGET, table.TARGET, traps.TARGET, views.TARGETS[0]):
            self.assertEqual(target, "CJKAMP_Game")

        # and the re-exports name every unit's target, the game's first
        self.assertEqual(reexport.VIEW_OF, {"CJKAShared": "JKAShared", "CJKAMP": "JKAMP", "CJKAMP_Game": "JKAMP_Game", "CJKAMP_CGame": "JKAMP_CGame"})
        self.assertEqual(reexport.DEPS, {"CJKAShared": [], "CJKAMP": ["CJKAShared"], "CJKAMP_Game": ["CJKAMP", "CJKAShared"],
                                         "CJKAMP_CGame": ["CJKAMP", "CJKAShared"]})

    def test_the_roots_are_the_game_roots(self) -> None:
        import views
        from rulings import ROOTS

        self.assertIs(views.UNIT_ROOTS, ROOTS["mp-game"])
        self.assertEqual(views.UNIT_ROOTS["gentity_t"], ("Entity", "CJKAMP_Game"))

    def test_the_state_names_are_the_game_names(self) -> None:
        import skeleton

        self.assertEqual(skeleton.STATE, "Game")

    def test_the_rust_crate_is_the_game_crate(self) -> None:
        import closure as C

        self.assertEqual(C.TARGETS["rust"], "game")

    def test_the_store_is_the_game_store(self) -> None:
        import lookup
        import table

        self.assertEqual(table.STORE, REPO / "tools" / "oracle-closure" / "table.sqlite")
        self.assertEqual(lookup.STORE, REPO / "tools" / "oracle-closure" / "table.sqlite")

    def test_the_stub_folders_and_the_declarations_are_the_game_lists(self) -> None:
        import closure as C

        # given the folders and the globs the table key reads for the game
        folders = C.PROJECT["output"]["stubs"] + [C.TARGETS["logic"]]
        patterns = [pattern.format(views=C.TARGETS["views"]) for pattern in C.PROJECT["output"]["declarations"]]

        # then they are the lists the project file held before the unit table
        self.assertEqual(sorted(folders), ["JKAMP_BG", "JKAMP_GameLogic", "JKAShared"])
        self.assertEqual(patterns, [
            "JKAShared/Generated/*.swift",
            "JKAMP/Generated/*.swift",
            "JKAMP_Game/Generated/*.swift",
            "JKAShared/Generated/Views/Callbacks.swift",
            "JKAMP/Generated/Views/Callbacks.swift",
            "JKAMP_Game/Generated/Views/Callbacks.swift",
        ])

    def test_the_cgame_row_names_the_game_as_its_other_unit(self) -> None:
        import closure as C

        # given the two rows of the unit table
        game, cgame = C.PROJECT["targets"]["mp-game"], C.PROJECT["targets"]["mp-cgame"]

        # then each names the other, and each fact of the cgame row differs from the game's
        self.assertEqual((game["other"], cgame["other"]), ("mp-cgame", "mp-game"))
        for key in ("folder", "traps", "logic", "views", "c_target", "state", "rust", "store"):
            self.assertNotEqual(game[key], cgame[key], key)


if __name__ == "__main__":
    unittest.main()
