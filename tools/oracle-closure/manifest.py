#!/usr/bin/env python3
"""manifest.py: one transcription manifest per Raven .c file of the MP game module.

Reads the same unity parse as skeleton.py and writes .claude/manifest/<stem>.md, one table row per function definition:
Raven's name, the oracle path with the first and last line of the definition, the line of the Swift stub or body,
whether it still carries a marker, the jka-rust function with its first and last line when one exists, and the
signature the table gives the function today. An adopted file no longer regenerates, so the signature column is where a
second pass reads the stub line a new view or table row changed.
A transcriptor reads one slice by line range from the manifest, and the reviewer has both references on the same row.

Usage:
  .venv/bin/python manifest.py                 # writes every manifest and prints the counts
  .venv/bin/python manifest.py --only g_combat # prints one manifest to stdout, writes nothing
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from reexport import REPO, SOURCES
from skeleton import ORACLE_DIR, Function, Skeleton, Variable, stub_path, target_of

RUST = Path("/Users/milohehmsoth/Developer/Milo/jka-rust/crates/mp")
OUT = REPO / ".claude" / "manifest"
NOTE = "Generated by tools/oracle-closure/manifest.py from the oracle's {stem}.c. Do not edit."


class RustIndex:
    """Every `fn Name(` of the jka-rust game and bg crates, with the line the body ends on."""

    def __init__(self) -> None:
        self.spans: dict[str, tuple[Path, int, int]] = {}
        for root in (RUST / "game" / "src", RUST / "bg" / "src", RUST / "qshared" / "src"):
            for path in sorted(root.rglob("*.rs")):
                self.index(path)

    def index(self, path: Path) -> None:
        lines = path.read_text(errors="replace").split("\n")
        for i, line in enumerate(lines, start=1):
            m = re.match(r"\s*(?:pub(?:\([^)]*\))?\s+)?(?:unsafe\s+)?fn\s+(\w+)\s*[(<]", line)
            if not m:
                continue
            name = m.group(1)
            end = self.body_end(lines, i - 1)
            self.spans.setdefault(name, (path, i, end))

    @staticmethod
    def body_end(lines: list[str], start: int) -> int:
        depth = 0
        opened = False
        for j in range(start, len(lines)):
            for ch in lines[j]:
                if ch == "{":
                    depth += 1
                    opened = True
                elif ch == "}":
                    depth -= 1
            if opened and depth == 0:
                return j + 1
            if not opened and lines[j].rstrip().endswith(";"):
                return j + 1
        return start + 1


class Manifest:
    def __init__(self) -> None:
        self.skeleton = Skeleton()
        self.rust = RustIndex()

    def swift_line(self, fn: Function) -> tuple[int | None, bool]:
        """The line of the Swift declaration and whether a marker still sits under it."""
        path = stub_path(fn.stem)
        if not path.exists():
            return None, True
        lines = path.read_text().split("\n")
        pattern = re.compile(rf"\bfunc {re.escape(fn.name)}\s*[(<]")
        for i, line in enumerate(lines, start=1):
            if pattern.search(line):
                window = "\n".join(lines[i : i + 3])
                return i, "TODO: Port" in window or "portMissing(" in window
        return None, True

    def row(self, fn: Function) -> str:
        first = fn.cur.extent.start.line
        last = fn.cur.extent.end.line
        swift, marker = self.swift_line(fn)
        swift_cell = f"`{stub_path(fn.stem).relative_to(SOURCES)}:{swift}`" if swift else "missing"
        state = "marker" if marker else "ported"
        span = self.rust.spans.get(fn.name)
        if span:
            path, a, b = span
            rust_cell = f"`{path.relative_to(RUST.parent.parent)}:{a}-{b}`"
        else:
            rust_cell = "none"
        static = " static" if fn.static else ""
        signature = f"`{self.skeleton.signature(fn)}`"
        if not fn.mapped:
            signature += f" TODO: Port signature. {fn.reason}"
        return f"| `{fn.name}`{static} | `oracle/{ORACLE_DIR}/{fn.stem}.c:{first}-{last}` | {swift_cell} | {state} | {rust_cell} | {signature} |"

    def file(self, stem: str) -> list[str]:
        fns = self.skeleton.files.get(stem, [])
        markers = sum(1 for fn in fns if self.swift_line(fn)[1])
        matched = sum(1 for fn in fns if fn.name in self.rust.spans)
        lines = [
            f"# {stem}.c",
            "",
            NOTE.format(stem=stem),
            "",
            f"{len(fns)} functions, {markers} with a marker, {matched} with a jka-rust match.",
            "The oracle range is the whole definition, from the return type to the closing brace.",
            "",
            "| Function | Oracle | Swift | State | jka-rust | Signature |",
            "|---|---|---|---|---|---|",
        ]
        lines += [self.row(fn) for fn in fns]
        variables = self.skeleton.variables.get(stem, [])
        if variables:
            lines += [
                "",
                f"{len(variables)} file-scope variables. The entry is the stub's line for the variable, by rule 3 and rule 6.",
                "",
                "| Variable | Oracle | Kind | Entry |",
                "|---|---|---|---|",
            ]
            lines += [self.variable_row(var) for var in variables]
        return lines

    def variable_row(self, var: Variable) -> str:
        entry = self.skeleton.variable_entry(var)
        # The last line is the `let`, the rule 3 line, the storage line, or the reason.
        return f"| `{var.name}` | `oracle/{ORACLE_DIR}/{var.stem}.c:{var.line}` | {var.kind} | `{entry[-1]}` |"

    def write(self) -> tuple[int, int, int]:
        OUT.mkdir(parents=True, exist_ok=True)
        files = 0
        total = 0
        matched = 0
        for stem in sorted(set(self.skeleton.files) | set(self.skeleton.variables)):
            (OUT / f"{stem}.md").write_text("\n".join(self.file(stem)) + "\n")
            files += 1
            total += len(self.skeleton.files.get(stem, []))
            matched += sum(1 for fn in self.skeleton.files.get(stem, []) if fn.name in self.rust.spans)
        return files, total, matched


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", help="one stem, printed to stdout, nothing written")
    args = ap.parse_args()
    manifest = Manifest()
    if args.only:
        if args.only not in manifest.skeleton.files and args.only not in manifest.skeleton.variables:
            raise SystemExit(f"manifest.py: no file named {args.only}.c")
        print("\n".join(manifest.file(args.only)))
        return
    files, total, matched = manifest.write()
    print(f"manifest.py: {files} manifests, {total} functions, {matched} with a jka-rust match, {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
