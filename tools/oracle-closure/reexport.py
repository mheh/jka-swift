#!/usr/bin/env python3
"""reexport.py: the Swift re-exports of Raven's constants, enums, and scalar typedefs, one file per Raven header, per view target.

Rule 8: a logic target never imports a C module, so the view target re-exports each constant and enum as a generated public Swift
declaration. The C declaration stays the single source of truth, so each Swift value reads the imported C value.

The shapes:
  a macro Clang imports          public let STEPSIZE = CJKAMP.STEPSIZE
  a macro Clang cannot import    a TODO: Port marker with the C text, rule 14
  an anonymous enum's enumerator public let WP_NONE: Int32
  a named enum                   public typealias team_t = Int32 and one public let per enumerator, typed team_t
  a typedef of a scalar          public typealias weapon_t = Int32

qboolean is skipped, because rule 7 makes it Bool at every Swift surface and the view converts it.

Usage:
  .venv/bin/python reexport.py                    # writes Sources/<View>/Generated/ for every view target, then builds, marks the macros Swift could not import, and writes again
  .venv/bin/python reexport.py --no-probe         # writes once with every macro as an import, which builds only when the importer takes them all
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tomllib
from collections import defaultdict
from pathlib import Path

import clang.cindex as ci
from clang.cindex import CursorKind, TypeKind

from rulings import NOT_PORTED_MACROS

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
SOURCES = REPO / "Sources"

# The C target and the view target of each unit, from the rows of `[targets]` in project.toml, in the order of the rows.
# A generator reads the C target of its run's unit from closure.py, and this file re-exports every target whose view target exists.
with (HERE / "project.toml").open("rb") as _f:
    _units = tomllib.load(_f)["targets"].values()
# C target -> Swift view target, and the C targets each view target's umbrella reaches.
VIEW_OF = {"CJKAShared": "JKAShared", "CJKAMP": "JKAMP"} | {unit["c_target"]: unit["views"] for unit in _units}
DEPS = {"CJKAShared": [], "CJKAMP": ["CJKAShared"]} | {unit["c_target"]: ["CJKAMP", "CJKAShared"] for unit in _units}
SKIP = {"qboolean"}
# Macro bodies that are a keyword or a keyword macro, not a value.
KEYWORD_MACROS = {"inline", "static", "__inline", "ID_INLINE", "QDECL", "MAC_STATIC"}

SCALARS = {
    TypeKind.INT: "Int32", TypeKind.UINT: "UInt32", TypeKind.SHORT: "Int16", TypeKind.USHORT: "UInt16",
    TypeKind.CHAR_S: "CChar", TypeKind.SCHAR: "Int8", TypeKind.UCHAR: "UInt8", TypeKind.LONG: "CLong", TypeKind.ULONG: "CUnsignedLong",
    TypeKind.LONGLONG: "Int64", TypeKind.ULONGLONG: "UInt64", TypeKind.FLOAT: "Float", TypeKind.DOUBLE: "Double",
}

# A C integer narrower than int, which C widens to int at every read. A view's scalar field, a parameter, and a return of one of
# these is Int32 in Swift, and the view's setter stores the truncation C performs. The storage type stays what Raven wrote.
NARROW = {TypeKind.SHORT, TypeKind.USHORT, TypeKind.SCHAR, TypeKind.UCHAR}

ANSI = re.compile(r"\x1b\[[0-9;]*m")

OPERATORS = {"(", "+", "-", "*", "/", "%", "|", "&", "^", "~", "<<", ">>", "!", "?", ":", "<", ">", "<=", ">=", "==", "!="}
CLOSE = {")"}

NOTE = "// Generated by tools/oracle-closure/reexport.py from the C target's headers. Do not edit. Rule 8 and rule 13."


def parse(target: str) -> ci.TranslationUnit:
    umbrella = SOURCES / target / "include" / f"{target}.h"
    args = ["-x", "c", "-std=gnu11", "-Wno-everything", "-ferror-limit=0"]
    args += [f"-I{SOURCES / t / 'include'}" for t in [target] + DEPS[target]]
    tu = ci.Index.create().parse(str(umbrella), args=args, options=ci.TranslationUnit.PARSE_DETAILED_PROCESSING_RECORD)
    errors = [d for d in tu.diagnostics if d.severity >= ci.Diagnostic.Error]
    if errors:
        sys.exit(f"reexport.py: {target} does not parse: {errors[0].location.file}:{errors[0].location.line} {errors[0].spelling}")
    return tu


def in_target(cur: ci.Cursor, target: str) -> bool:
    f = cur.location.file
    return f is not None and str(SOURCES / target / "include") in str(Path(f.name).resolve())


def source_lines(cur: ci.Cursor) -> list[str]:
    """The // Source: lines above a declaration, in file order, read back over Raven's comment block when one sits between."""
    lines = Path(cur.location.file.name).read_text().splitlines()
    i = cur.extent.start.line - 2
    out: list[str] = []
    in_block = False
    while i >= 0:
        line = lines[i].strip()
        if in_block:
            if "/*" in line:
                in_block = False
        elif line.endswith("*/"):
            in_block = "/*" not in line
        elif re.match(r"#\s*(else|elif)\b", line):
            # A macro in the second arm of a platform conditional takes the Source line above the opening `#if`.
            # The walk skips the first arm to that `#if`, and it counts nested conditionals on the way.
            depth = 0
            i -= 1
            while i >= 0:
                directive = lines[i].strip()
                if re.match(r"#\s*endif\b", directive):
                    depth += 1
                elif re.match(r"#\s*if", directive):
                    if depth == 0:
                        break
                    depth -= 1
                i -= 1
        elif re.match(r"#\s*if", line):
            # The opening `#if` of a conditional sits between a macro of the first arm and its Source line.
            pass
        elif line.startswith("//"):
            m = re.match(r"// Source: (.*)$", line)
            if m:
                out.append(m.group(1).strip())
        elif line:
            break
        i -= 1
    return list(reversed(out))


def swift_expression(cur: ci.Cursor, enum_of: dict[str, str], declared: dict[str, str], narrow: bool = False,
                     local: set[str] | None = None, float_suffix: bool = False) -> str | None:
    """Raven's macro body as a Swift expression, or None when a token has no Swift spelling, such as a cast or sizeof.
    `local` names the macros of the same .c file, which a stub spells bare, and any other unqualified name is a miss.
    `float_suffix` types a literal Raven wrote with `f` as Float, the C type, for a stub's let."""
    tokens = [t.spelling for t in cur.get_tokens()][1:]
    out: list[str] = []
    literal_only = True
    has_float = False
    has_float_suffix = False
    has_string = False
    for tok in tokens:
        if re.fullmatch(r"0[xX][0-9a-fA-F]+[uUlL]*", tok):
            out.append(re.sub(r"[uUlL]+$", "", tok))
        elif re.fullmatch(r"0[0-7]+[uUlL]*", tok):
            out.append("0o" + re.sub(r"[uUlL]+$", "", tok)[1:])
        elif re.fullmatch(r"\d+[uUlL]*", tok):
            out.append(re.sub(r"[uUlL]+$", "", tok))
        elif re.fullmatch(r"(\d+\.\d*|\.\d+|\d+)([eE][+-]?\d+)?[fFlL]?", tok):
            # Swift takes no bare point on either side of a literal, so Raven's `.55` reads `0.55` and his `1.` reads `1.0`.
            out.append(("0" if tok.startswith(".") else "") + re.sub(r"[fFlL]$", "", tok) + ("0" if tok.rstrip("fFlL").endswith(".") else ""))
            has_float = True
            has_float_suffix = has_float_suffix or tok[-1] in "fF"
        elif tok.startswith('"') and tok.endswith('"') and len(tok) >= 2:
            # A string literal macro, `#define DEFAULT_SABER "Kyle"`, is a String constant. C's hex and octal escapes take Swift's `\u{}` form.
            spelled = re.sub(r"\\x([0-9a-fA-F]{1,2})", lambda m: "\\u{" + m.group(1) + "}", tok)
            spelled = re.sub(r"\\([0-7]{1,3})", lambda m: "\\u{" + format(int(m.group(1), 8), "x") + "}", spelled)
            out.append(spelled)
            has_string = True
        elif tok in ("qtrue", "qfalse"):
            out.append("true" if tok == "qtrue" else "false")
            literal_only = False
        elif re.fullmatch(r"'(\\?.)'", tok):
            out.append(f'Int32(UInt8(ascii: "{tok[1:-1]}"))')
            literal_only = False
        elif tok in OPERATORS or tok in CLOSE:
            # A minus or tilde after an operator or an open paren is unary, and Swift wants it against its operand.
            unary = tok in ("-", "~") and (not out or out[-1].rstrip("\0") in OPERATORS)
            out.append(tok + "\0" if unary else tok)
        elif re.fullmatch(r"[A-Za-z_]\w*", tok):
            if tok in ("sizeof", "int", "float", "unsigned", "long", "short", "char", "double", "void"):
                return None
            # A name from a dependency view is qualified, because the same name also reaches this file as a C macro through the
            # umbrella's export, and Swift calls the two ambiguous. A name of this target shadows the import and stays bare.
            # An enumerator is a bare constant of its enum's module, so it qualifies the same way as its enum.
            module = declared.get(enum_of.get(tok, ""), declared.get(tok))
            if local is not None and module is None and tok not in local:
                return None
            spelled = f"{module}.{tok}" if module else tok
            # Raven mixes constants Clang imported as Int32 and UInt32 in one mask, and Swift's checker gives up on the mix.
            out.append(f"Int32(truncatingIfNeeded: {spelled})" if narrow else spelled)
            literal_only = False
        else:
            return None
    if not out:
        return None
    text = " ".join(out).replace("\0 ", "").replace("( ", "(").replace(" )", ")")
    if literal_only and has_string:
        return text if len(out) == 1 else None
    if literal_only:
        return f"{text} as {('Float' if float_suffix and has_float_suffix else 'Double') if has_float else 'Int32'}"
    return f"{text} as Int32" if narrow else text


def cast_literal(cur: ci.Cursor, typealiases: set[str], declared: dict[str, str]) -> tuple[str, str] | None:
    """The Swift type and the literal of a macro body `( ( <scalar typedef> ) <literal> )`, `NULL_HANDLE ((qhandle_t) 0)`, or None for any other body.
    The typedef is one of the scalar typealiases a view target declares, qualified as `swift_expression` qualifies a name of a dependency."""
    tokens = [t.spelling for t in cur.get_tokens()][1:]
    if len(tokens) != 6 or tokens[:2] != ["(", "("] or tokens[3] != ")" or tokens[5] != ")" or tokens[2] not in typealiases:
        return None
    literal = tokens[4]
    if re.fullmatch(r"0[xX][0-9a-fA-F]+[uUlL]*", literal) or re.fullmatch(r"\d+[uUlL]*", literal) and not re.fullmatch(r"0[0-7]+[uUlL]*", literal):
        value = re.sub(r"[uUlL]+$", "", literal)
    elif re.fullmatch(r"0[0-7]+[uUlL]*", literal):
        value = "0o" + re.sub(r"[uUlL]+$", "", literal)[1:]
    elif re.fullmatch(r"(\d+\.\d*|\.\d+)([eE][+-]?\d+)?[fFlL]?", literal):
        value = ("0" if literal.startswith(".") else "") + re.sub(r"[fFlL]$", "", literal) + ("0" if literal.rstrip("fFlL").endswith(".") else "")
    else:
        return None
    module = declared.get(tokens[2])
    return (f"{module}.{tokens[2]}" if module else tokens[2], value)


def header_stem(source: str) -> str:
    return Path(source.rsplit(":", 1)[0]).stem


def is_function_like(cur: ci.Cursor) -> bool:
    tokens = list(cur.get_tokens())
    return len(tokens) > 1 and tokens[1].spelling == "(" and tokens[1].extent.start.offset == tokens[0].extent.end.offset


def macro_text(cur: ci.Cursor) -> str:
    return " ".join(t.spelling for t in cur.get_tokens())


def doc(sources: list[str]) -> list[str]:
    return [f"/// Source: {s}" for s in sources]


def emit(target: str, unimportable: set[str], narrowed: set[str], typed: set[str], unexpressible: set[str],
         declared: dict[str, str]) -> dict[str, list[str]]:
    """The Swift files for one C target, keyed by Raven header stem."""
    tu = parse(target)
    # The scalar typedefs this target writes as a typealias, or reads from a dependency's view, which a cast body may name.
    typealiases = {
        cur.spelling for cur in tu.cursor.get_children()
        if cur.kind == CursorKind.TYPEDEF_DECL and cur.spelling not in SKIP and SCALARS.get(cur.underlying_typedef_type.get_canonical().kind)
        and (in_target(cur, target) or cur.spelling in declared)
    }
    files: dict[str, list[str]] = defaultdict(list)
    seen: set[str] = set()
    enum_of: dict[str, str] = {}
    for cur in tu.cursor.get_children():
        if cur.kind == CursorKind.ENUM_DECL and cur.is_definition() and enum_name(cur) and enum_name(cur) not in SKIP:
            for e in cur.get_children():
                if e.kind == CursorKind.ENUM_CONSTANT_DECL:
                    enum_of.setdefault(e.spelling, enum_name(cur))
    for cur in tu.cursor.get_children():
        if not in_target(cur, target):
            continue
        if cur.kind == CursorKind.MACRO_DEFINITION:
            name = cur.spelling
            # A .c file's macros are constants of that file, and skeleton.py writes them into its stub at Raven's line.
            # extract.py copied them into a per-stem header, so the oracle cite says where Raven wrote them.
            origins = source_lines(cur)
            if origins and origins[0].rsplit(":", 1)[0].endswith(".c"):
                continue
            # An include guard and QDECL have no body, GAME_INLINE is a keyword, and nothing reads those from Swift.
            tokens = [t.spelling for t in cur.get_tokens()][1:]
            if is_function_like(cur) or name in seen or name in SKIP or not tokens or set(tokens) <= KEYWORD_MACROS:
                continue
            # A macro that repeats the name of an enumerator of the target yields to the enumerator, which the enum emits.
            # menudef.h spells CT_LTBLUE1 and three more colors of q_shared.h's ct_table_t as three numbers for the menu scripts.
            # That text is not a C value.
            if name in enum_of:
                continue
            seen.add(name)
            sources = source_lines(cur)
            block = doc(sources)
            expression = swift_expression(cur, enum_of, declared, narrow=name in narrowed) if name in unimportable else None
            if name in NOT_PORTED_MACROS:
                block += [f"// Raven wrote: #define {macro_text(cur)}", f"// Not ported: {NOT_PORTED_MACROS[name]}."]
            elif name in typed and name not in unexpressible and cast_literal(cur, typealiases, declared) is not None:
                # Swift takes no C cast, so a cast of a literal to a scalar typedef is the literal with the typedef as its type.
                swift, value = cast_literal(cur, typealiases, declared)
                block.append(f"public let {name}: {swift} = {value}")
            elif name in unexpressible or name in typed or (name in unimportable and expression is None):
                # Rule 14: a placeholder constant carries the marker alone, and the C text says what it must become.
                block += [f"// TODO: Port {name}", f"// Raven wrote: #define {macro_text(cur)}"]
            elif name in unimportable:
                # Swift's importer does not take this macro, so its body is spelled as a Swift expression over the same names.
                block.append(f"public let {name} = {expression}")
            else:
                block.append(f"public let {name} = {target}.{name}")
            files[header_stem(sources[0]) if sources else "unknown"] += block + [""]
        elif cur.kind == CursorKind.ENUM_DECL and cur.is_definition():
            sources = source_lines(cur)
            stem = header_stem(sources[0]) if sources else "unknown"
            name = enum_name(cur)
            enumerators = [c for c in cur.get_children() if c.kind == CursorKind.ENUM_CONSTANT_DECL]
            if name is None or name in SKIP:
                if name in SKIP:
                    continue
                # Raven wrote typedef enum { ... }; with no name, so the enumerators are plain constants, as Clang imports them.
                for e in enumerators:
                    if e.spelling in seen:
                        continue
                    seen.add(e.spelling)
                    files[stem] += doc(sources) + [f"public let {e.spelling}: Int32 = Int32(truncatingIfNeeded: {target}.{e.spelling})", ""]
                continue
            if name in seen:
                continue
            seen.add(name)
            # A C enum is an int, ruling of 2026-09-09. The type is an Int32 alias and each enumerator is a bare constant of it.
            block = doc(sources)
            block.append(f"public typealias {name} = Int32")
            for e in enumerators:
                if e.spelling in seen:
                    continue
                seen.add(e.spelling)
                block.append(f"public let {e.spelling}: {name} = Int32(truncatingIfNeeded: {target}.{e.spelling}.rawValue)")
            files[stem] += block + [""]
        elif cur.kind == CursorKind.TYPEDEF_DECL:
            name = cur.spelling
            if name in seen or name in SKIP:
                continue
            under = cur.underlying_typedef_type.get_canonical()
            swift = SCALARS.get(under.kind)
            if swift is None:
                continue
            seen.add(name)
            sources = source_lines(cur)
            files[header_stem(sources[0]) if sources else "unknown"] += doc(sources) + [f"public typealias {name} = {swift}", ""]
    return files


def enum_name(cur: ci.Cursor) -> str | None:
    """The typedef name or the tag of an enum definition, or None when Raven gave it neither."""
    if cur.spelling and not cur.is_anonymous() and not cur.spelling.startswith("enum (unnamed"):
        return cur.spelling
    return None


def write(target: str, files: dict[str, list[str]]) -> int:
    view = VIEW_OF[target]
    out = SOURCES / view / "Generated"
    if out.exists():
        # Other generators write into this directory too, such as traps.py, so only a file that opens with this script's note goes.
        for old in out.glob("*.swift"):
            with old.open() as f:
                first = f.readline().rstrip("\n")
            if first == NOTE:
                old.unlink()
    out.mkdir(parents=True, exist_ok=True)
    count = 0
    for stem, lines in sorted(files.items()):
        imports = [f"internal import {target}"] + [f"import {VIEW_OF[d]}" for d in DEPS[target]]
        text = [NOTE, ""] + imports + [""] + lines
        (out / f"{stem}.swift").write_text("\n".join(text).rstrip() + "\n")
        count += sum(1 for l in lines if l.startswith("public ") or l.startswith("// TODO: Port"))
    return count


def probe() -> set[tuple[str, str]]:
    """The view target and the name of each generated declaration a build rejects, whatever the error, read from the failing lines."""
    run = subprocess.run(["swift", "build"], cwd=REPO, capture_output=True, text=True)
    # The compiler colours `error:` even with no terminal, and the escapes sit between the location and the word.
    log = ANSI.sub("", run.stdout + run.stderr)
    names: set[tuple[str, str]] = set()
    # A type error prints as `<path>:<line>:<column>: error:`, and a syntax error the build system reports as `error: <path>:<line>:<column> `.
    found = re.findall(r"^(/\S+/Generated/\w+\.swift):(\d+):\d+: error:", log, re.M)
    found += re.findall(r"^error: (/\S+/Generated/\w+\.swift):(\d+):\d+ ", log, re.M)
    for path, line in found:
        text = Path(path).read_text().splitlines()[int(line) - 1]
        m = re.search(r"public let (\w+)", text)
        if m:
            # Two view targets can spell one name, and the importer can take it in one and refuse it in the other.
            names.add((Path(path).parent.parent.name, m.group(1)))
    return names


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--no-probe", action="store_true", help="write once with every macro as an import, and skip the build that marks what Swift could not import")
    args = ap.parse_args()
    targets = [t for t, view in VIEW_OF.items() if (SOURCES / t / "include").exists() and (SOURCES / view).exists()]
    # A name climbs one rung per failed build: the import, the expression, the expression narrowed to Int32, a cast literal, then the marker.
    # The cast rung writes a marker at once for a body of any other form.
    # Each set holds pairs of a view target and a name.
    unimportable: set[tuple[str, str]] = set()
    narrowed: set[tuple[str, str]] = set()
    typed: set[tuple[str, str]] = set()
    unexpressible: set[tuple[str, str]] = set()
    # A failed build stops at the first module that fails, so each view target can take its own rounds.
    for _ in range(24):
        declared: dict[str, str] = {}
        for target in targets:
            # A target reads the names of the targets its umbrella reaches, and never the names of a sibling unit's target.
            reached = {VIEW_OF[d] for d in DEPS[target]}
            mine = [{name for view, name in rung if view == VIEW_OF[target]} for rung in (unimportable, narrowed, typed, unexpressible)]
            files = emit(target, *mine, {name: view for name, view in declared.items() if view in reached})
            count = write(target, files)
            for lines in files.values():
                for line in lines:
                    m = re.match(r"public (?:let|struct|typealias) (\w+)", line)
                    if m:
                        declared[m.group(1)] = VIEW_OF[target]
            print(f"{VIEW_OF[target]:12} {count:5} declarations from {target}")
        if args.no_probe:
            return 0
        found = probe()
        if not found:
            print(f"{len(unimportable)} macros spelled as Swift expressions, {len(narrowed)} of them narrowed to Int32, "
                  f"{len(typed - unexpressible)} reached the cast rung, {len(unexpressible)} marked TODO: Port")
            return 0
        unexpressible |= found & typed
        typed |= found & narrowed
        narrowed |= found & unimportable
        unimportable |= found
    print("reexport.py: the build still fails after 24 rounds", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
