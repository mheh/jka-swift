#!/usr/bin/env python3
"""traps.py: the typed trap functions, one per Raven trap_* in g_syscalls.c, per porting rule 11.

Reads the run's one parse and its one swept table, takes every function of g_syscalls.c whose body is one syscall(...) call,
and writes Sources/JKAMP_Game/Generated/g_syscalls.swift. The sweep walks the game unit and the cgame unit, so a parameter
is optional when a caller in either unit hands it NULL. Each trap keeps Raven's name, Raven's comment,
Raven's parameter names, and a body of one Syscall.call through the typed overload of the view target.

The parameter table is abi-stubs.md row 2:

  int, scalar typedef          Int32 or the re-exported typealias, bare
  qboolean                     Bool, bare
  float                        Float, bare, the word is PASSFLOAT's
  const char *                 String, withCString around the call
  char * with an int size      dropped, the trap returns String, a buffer of the size read after the call through String(nulTerminated:)
                               a trap in LIST_TRAPS fills a NUL-separated list, and it returns the whole buffer as a CharBuf
  const vec3_t, vec3_t         vec3_t by value when const, inout vec3_t when not, a pointer scoped around the call
  int *, float *, qboolean *   inout of the scalar, withUnsafeMutablePointer around the call
  int * with an int count      inout [Int32], an array the engine fills, withUnsafeMutableBufferPointer around the call
  pointer to a viewed struct   the view, bare
  void *                       OpaquePointer?, bare
  anything else                TODO: Port signature with Raven's C text, body portMissing

Usage:
  .venv/bin/python traps.py                  # writes the file and prints the counts
  .venv/bin/python traps.py --only trap_Trace   # prints one trap to stdout, writes nothing
"""

from __future__ import annotations

import argparse
import re
from collections import Counter
from pathlib import Path

import clang.cindex as ci
from clang.cindex import CursorKind, TypeKind

import closure as C
from reexport import GAME_TARGET, REPO, SOURCES
from rulings import LIST_TRAPS, NIL_OVERLOADS, NOT_PORTED
from table import Param, SourceFile, Table, swift_name

TARGET = GAME_TARGET
VIEW = "JKAMP_Game"
SOURCE = f"{C.GAME_DIR}/g_syscalls.c"
NOTE = "// Generated by tools/oracle-closure/traps.py from the oracle's g_syscalls.c. Do not edit. Rule 11 and rule 13."
NOT_TRAPS = {"PASSFLOAT", "dllEntry"}


class Traps:
    def __init__(self, parse: C.Parse) -> None:
        self.parse = parse
        self.tu = parse.game
        # The NULL sweep and the buffer sweep of docket row 7 read both units the port parses, because a caller of a trap stands in either one.
        self.table = Table(parse)
        self.table.sweep()
        self.path = C.ORACLE / SOURCE
        self.source = SourceFile(self.path)
        self.counts: Counter[str] = Counter()
        self.functions = [
            cur for cur in self.tu.cursor.get_children()
            if cur.kind == CursorKind.FUNCTION_DECL and cur.is_definition()
            and cur.location.file and Path(cur.location.file.name).resolve() == self.path.resolve()
            and cur.spelling not in NOT_TRAPS
        ]

    def syscalls(self, cur: ci.Cursor) -> list[ci.Cursor]:
        found: list[ci.Cursor] = []

        def walk(node: ci.Cursor) -> None:
            if node.kind == CursorKind.CALL_EXPR and node.spelling == "syscall":
                found.append(node)
            for child in node.get_children():
                walk(child)

        walk(cur)
        return found

    # MARK: - Emission

    def marker(self, cur: ci.Cursor, reason: str) -> list[str]:
        name = cur.spelling
        self.counts["TODO: Port signature"] += 1
        return [
            f"/// Source: oracle/{SOURCE}:{cur.location.line}",
            f"// TODO: Port signature",
            f"// Raven wrote: {self.source.c_signature(cur)}",
            f"// {reason}",
            f"public func {name}() -> Never {{",
            f"    // TODO: Port {name}",
            f'    portMissing("{name}", source: "oracle/{SOURCE}:{cur.location.line}")',
            "}",
        ]

    def trap(self, cur: ci.Cursor) -> list[str]:
        name = cur.spelling
        if name in NOT_PORTED:
            self.counts["not ported by ruling"] += 1
            return [
                f"/// Source: oracle/{SOURCE}:{cur.location.line}",
                f"// Raven wrote: {self.source.c_signature(cur)}",
                f"// Not ported: {NOT_PORTED[name]}.",
            ]
        calls = self.syscalls(cur)
        if len(calls) != 1:
            return self.marker(cur, f"The body holds {len(calls)} syscall calls, not one.")
        params = list(cur.get_arguments())
        mapped: dict[str, Param] = {}
        for i, p in enumerate(params):
            following = params[i + 1] if i + 1 < len(params) else None
            m = self.table.param(p, following, owner=name)
            if m is None:
                return self.marker(cur, self.table.marker_reason(p, name))
            mapped[p.spelling] = m
        result = self.table.result(cur)
        if result is None:
            return self.marker(cur, f"No table row for the return `{cur.result_type.spelling}`.")
        args = list(calls[0].get_arguments())
        command = self.source.slice(args[0].extent).strip()
        words: list[str] = []
        for arg in args[1:]:
            text = self.source.slice(arg.extent).strip()
            text = re.sub(r"^\(\s*[\w\s\*]+\)\s*", "", text)
            m = re.fullmatch(r"PASSFLOAT\s*\(\s*(\w+)\s*\)", text)
            if m:
                text = m.group(1)
            if re.fullmatch(r"-?\d+", text):
                words.append(text)
            elif text in mapped:
                words.append(mapped[text].word())
            else:
                return self.marker(cur, f"The syscall argument `{text}` is not a parameter.")
        for p in mapped.values():
            self.counts[p.kind] += 1
        self.counts["traps"] += 1
        signature = ", ".join(f"_ {p.name}: {p.swift}" for p in mapped.values() if p.swift)
        returns, mapping = result
        outs = [p for p in mapped.values() if p.kind == "out_string"]
        # The word is read only when Raven returned one. A filled buffer is read from the buffer.
        prefix = "    let word = " if returns else "    _ = "
        text_type = "JKAShared.CharBuf" if name in LIST_TRAPS else "String"
        text_read = f"JKAShared.CharBuf(bytes: {outs[0].name})" if outs and name in LIST_TRAPS else f"String(nulTerminated: {outs[0].name})" if outs else ""
        if outs and returns:
            # Raven filled the buffer and returned a count, so the trap returns both, per rule 7.
            returns = f"({returns}, {text_type})"
            mapping = f"({mapping}, {text_read})"
        elif outs:
            returns = text_type
            mapping = text_read
        # The engine never returns from G_ERROR, it longjmps to its main loop, ruling of 2026-09-09. Raven's C cannot say so.
        never = name == "trap_Error"
        head = f"public func {name}({signature})" + (" -> Never" if never else f" -> {returns}" if returns else "")
        if returns and not never:
            # Raven drops a trap's return at most call sites, and C never warned, so a body reads his line without `_ =`.
            head = "@discardableResult\n" + head
        call = f"Syscall.call({command}, {', '.join(words)})" if words else f"Syscall.call({command})"
        body: list[str] = []
        for p in outs:
            body.append(f"    var {p.name} = [CChar](repeating: 0, count: Int({p.size}))")
        for p in mapped.values():
            if p.kind == "vec3_array":
                # Raven's vec3_t is three floats of 12 bytes, and SIMD3<Float> strides 16, so the engine reads a flat copy.
                body.append(f"    let {p.name}Flat = {p.name}.flatMap {{ [$0.x, $0.y, $0.z] }}")
        # Every scoped pointer wraps the call in one closure, innermost last.
        layers: list[str] = []
        for p in mapped.values():
            if p.kind == "cstring":
                layers.append(f"{p.name}.withCString {{ {p.name} in")
            elif p.kind == "cstring_opt":
                layers.append(f"withCString({p.name}) {{ {p.name} in")
            elif p.kind == "vec3_const":
                layers.append(f"withUnsafePointer(to: {p.name}) {{ {p.name} in")
            elif p.kind == "vec3_mut":
                layers.append(f"withUnsafeMutablePointer(to: &{p.name}) {{ {p.name} in")
            elif p.kind == "vec3_array":
                layers.append(f"{p.name}Flat.withUnsafeBufferPointer {{ {p.name}Flat in")
            elif p.kind in ("out_string", "out_array"):
                layers.append(f"{p.name}.withUnsafeMutableBufferPointer {{ {p.name}Pointer in")
            elif p.kind in ("out_scalar", "out_opaque"):
                layers.append(f"withUnsafeMutablePointer(to: &{p.name}) {{ {p.name} in")
        if not returns:
            body += self.nest(layers, call, "    _ = ") if layers else [f"    {call}"]
        else:
            body += self.nest(layers, call, prefix) if layers else [f"{prefix.strip()} {call}"]
            body.append(f"    return {mapping}")
        lines = self.source.comment_above(cur)
        lines.append(f"/// Source: oracle/{SOURCE}:{cur.location.line}")
        lines.append(head + " {")
        lines += body
        if never:
            # A transport that returns is a test double, and the trap ends the process with Raven's text, as the engine would.
            lines.append(f'    fatalError("trap_Error returned: \\({mapped[params[0].spelling].name})")')
        lines.append("}")
        lines += self.nil_overload(cur, name, mapped, returns, body)
        lines += self.buffer_overload(cur, name, mapped, returns, never)
        lines += self.text_overload(cur, name, mapped, returns, never)
        return lines

    def nil_overload(self, cur: ci.Cursor, name: str, mapped: dict[str, Param], returns: str | None, body: list[str]) -> list[str]:
        """The second overload of a NIL_OVERLOADS ruling, the same body with the named view parameter optional.
        A nil view is the zero word, as Raven's NULL was, and a caller that holds a view still takes the first overload."""
        nil = [p for p in mapped.values() if (name, p.name) in NIL_OVERLOADS]
        if len(nil) != 1:
            return []
        self.counts["nil overloads"] += 1
        signature = ", ".join(f"_ {p.name}: " + (f"{p.swift}?" if p is nil[0] else p.swift) for p in mapped.values() if p.swift)
        head = f"public func {name}({signature})" + (f" -> {returns}" if returns else "")
        if returns:
            head = "@discardableResult\n" + head
        return [
            "",
            f"/// Source: oracle/{SOURCE}:{cur.location.line}",
            f"/// Raven hands `{nil[0].name}` a NULL from {NIL_OVERLOADS[(name, nil[0].name)]}.",
            "/// This overload takes that nil.",
            head + " {",
        ] + body + ["}"]

    def buffer_overload(self, cur: ci.Cursor, name: str, mapped: dict[str, Param], returns: str | None, never: bool) -> list[str]:
        """The second overload of docket row 7, for a `void *` parameter Raven's own callers fill with a `char buf[N]`.

        The buffer hands the engine its base inside one unsafe scope here, so a body passes the buffer bare and no `Unsafe`
        type reaches a logic target. The first overload stays for a caller that holds a raw allocation."""
        fills = [p for p in mapped.values() if p.swift == "OpaquePointer?" and self.table.fills_buffer(name, p.name)]
        if len(fills) != 1:
            return []
        buffer = fills[0]
        crossing = [p for p in mapped.values() if p.swift]
        signature = ", ".join(f"_ {p.name}: " + ("inout JKAShared.CharBuf" if p is buffer else p.swift) for p in crossing)
        words = []
        for p in crossing:
            if p is buffer:
                words.append("OpaquePointer(base)")
            elif (p.swift or "").startswith("inout "):
                words.append(f"&{p.name}")
            else:
                words.append(p.name)
        self.counts["buffer overloads"] += 1
        head = f"public func {name}({signature})" + (" -> Never" if never else f" -> {returns}" if returns else "")
        if returns and not never:
            head = "@discardableResult\n" + head
        keyword = "return " if returns or never else ""
        return [
            "",
            f"/// Source: oracle/{SOURCE}:{cur.location.line}",
            f"/// Raven's `{buffer.name}` takes a `char buf[N]` at his own call sites, and this overload hands the engine that buffer's base.",
            head + " {",
            f"    {keyword}{buffer.name}.withUnsafeMutableRawPointer {{ base in",
            f"        {name}({', '.join(words)})",
            "    }",
            "}",
        ]

    def text_overload(self, cur: ci.Cursor, name: str, mapped: dict[str, Param], returns: str | None, never: bool) -> list[str]:
        """The overload for a `const void *` parameter Raven's own callers hand a `char *` text, `trap_FS_Write(str, strlen(str), fh)`.

        The text hands the engine its bytes inside one unsafe scope here, so a body passes the String bare and no `Unsafe` type reaches a logic target."""
        reads = [p for p in mapped.values() if p.swift == "OpaquePointer?" and self.table.reads_text(name, p.name)]
        if len(reads) != 1:
            return []
        text = reads[0]
        crossing = [p for p in mapped.values() if p.swift]
        signature = ", ".join(f"_ {p.name}: " + ("String" if p is text else p.swift) for p in crossing)
        words = []
        for p in crossing:
            if p is text:
                words.append("OpaquePointer(base)")
            elif (p.swift or "").startswith("inout "):
                words.append(f"&{p.name}")
            else:
                words.append(p.name)
        self.counts["text overloads"] += 1
        head = f"public func {name}({signature})" + (" -> Never" if never else f" -> {returns}" if returns else "")
        if returns and not never:
            head = "@discardableResult\n" + head
        keyword = "return " if returns or never else ""
        return [
            "",
            f"/// Source: oracle/{SOURCE}:{cur.location.line}",
            f"/// Raven's `{text.name}` takes a `char *` text at his own call sites, and this overload hands the engine the text's bytes.",
            head + " {",
            f"    {keyword}{text.name}.withCString {{ base in",
            f"        {name}({', '.join(words)})",
            "    }",
            "}",
        ]

    def nest(self, layers: list[str], call: str, prefix: str) -> list[str]:
        out = [prefix + layers[0]]
        for depth, layer in enumerate(layers[1:], start=2):
            out.append("    " * depth + layer)
        out.append("    " * (len(layers) + 1) + call)
        for depth in range(len(layers), 0, -1):
            out.append("    " * depth + "}")
        return out

    def emit(self) -> list[str]:
        lines = [NOTE, "", "internal import CJKAMP_Game", "import JKAMP", "import JKAShared", ""]
        for cur in self.functions:
            lines += self.trap(cur)
            lines.append("")
        return lines


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rebuild", action="store_true", help="sweep every fact of the table again and write the store anew")
    ap.add_argument("--only", help="one trap name, printed to stdout, nothing written")
    args = ap.parse_args()
    import table

    table.REBUILD = args.rebuild
    gen = Traps(C.Parse())
    if args.only:
        for cur in gen.functions:
            if cur.spelling == args.only:
                print("\n".join(gen.trap(cur)))
                return
        raise SystemExit(f"traps.py: no trap named {args.only}")
    out = SOURCES / VIEW / "Generated" / "g_syscalls.swift"
    out.write_text("\n".join(gen.emit()).rstrip() + "\n")
    c = gen.counts
    print(f"traps.py: {c['traps']} traps, {c['TODO: Port signature']} TODO: Port signature markers, {out.relative_to(REPO)}")
    print(f"  {'buffer':12} {c['buffer overloads']} inout CharBuf overloads")
    print(f"  {'nil':12} {c['nil overloads']} overloads that take a nil view")
    print(f"  {'text':12} {c['text overloads']} String overloads")
    for kind in ("bare", "cstring", "out_string", "out_scalar", "out_array", "out_opaque", "vec3_const", "vec3_mut", "vec3_array", "slots", "view"):
        print(f"  {kind:12} {c[kind]}")


if __name__ == "__main__":
    main()
