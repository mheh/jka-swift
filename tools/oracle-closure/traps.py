#!/usr/bin/env python3
"""traps.py: the typed trap functions, one per Raven trap_* in g_syscalls.c, per porting rule 11.

Reads the mp-game unity parse, takes every function of g_syscalls.c whose body is one syscall(...) call,
and writes Sources/JKAMP_Game/Generated/g_syscalls.swift. Each trap keeps Raven's name, Raven's comment,
Raven's parameter names, and a body of one Syscall.call through the typed overload of the view target.

The parameter table is abi-stubs.md row 2:

  int, scalar typedef          Int32 or the re-exported typealias, bare
  qboolean                     Bool, bare
  float                        Float, bare, the word is PASSFLOAT's
  enum                         the re-exported struct, .rawValue
  const char *                 String, withCString around the call
  char * with an int size      dropped, the trap returns String, a buffer of the size read after the call
  const vec3_t, vec3_t         vec3_t, withUnsafePointer around the call, a var copy written back when not const
  pointer to a viewed struct   the view, bare
  void *                       OpaquePointer?, bare
  anything else                TODO: Port signature with Raven's C text, body portMissing

Usage:
  .venv/bin/python traps.py                  # writes the file and prints the counts
  .venv/bin/python traps.py --only trap_Trace   # prints one trap to stdout, writes nothing
"""

from __future__ import annotations

import argparse
import re
from collections import Counter
from pathlib import Path

import clang.cindex as ci
from clang.cindex import CursorKind, TypeKind

import closure as C
from reexport import REPO, SOURCES
from views import Generator

TARGET = "CJKAMP_Game"
VIEW = "JKAMP_Game"
SOURCE = "codemp/game/g_syscalls.c"
NOTE = "// Generated by tools/oracle-closure/traps.py from the oracle's g_syscalls.c. Do not edit. Rule 11 and rule 13."
NOT_TRAPS = {"PASSFLOAT", "dllEntry"}
INT_KINDS = {TypeKind.INT, TypeKind.UINT, TypeKind.LONG, TypeKind.ULONG, TypeKind.SHORT, TypeKind.USHORT}
# An int beside a char * is its size only when Raven named it so. trap_BotSetChatName's `client` is not a size.
SIZE_NAME = re.compile(r"size|len|max", re.I)
# A Raven parameter name that is a Swift keyword is written in backticks.
KEYWORDS = {"extension", "in", "func", "class", "struct", "enum", "protocol", "default", "operator", "repeat", "where",
            "import", "self", "init", "var", "let", "return", "case", "switch", "if", "else", "for", "while", "do", "is", "as",
            "true", "false", "nil", "super", "throws", "try", "catch", "inout", "static", "public", "private", "internal"}


def swift_name(name: str) -> str:
    return f"`{name}`" if name in KEYWORDS else name


class Param:
    """One parameter as the table maps it. `kind` picks the emission, `swift` is the type in the signature."""

    def __init__(self, name: str, swift: str | None, kind: str, size: str | None = None) -> None:
        self.name = swift_name(name)
        self.swift = swift
        self.kind = kind
        self.size = size

    def word(self) -> str:
        if self.kind == "enum":
            return f"{self.name}.rawValue"
        if self.kind == "out_string":
            return f"{self.name.strip('`')}Pointer.baseAddress!"
        return self.name


class Traps:
    def __init__(self) -> None:
        self.views = Generator(None)
        self.tu = C.parse_tu("mp-game", None, unity=True)
        self.path = C.ORACLE / SOURCE
        self.text = self.path.read_text()
        self.lines = self.text.splitlines()
        self.counts: Counter[str] = Counter()
        self.functions = [
            cur for cur in self.tu.cursor.get_children()
            if cur.kind == CursorKind.FUNCTION_DECL and cur.is_definition()
            and cur.location.file and Path(cur.location.file.name).resolve() == self.path.resolve()
            and cur.spelling not in NOT_TRAPS
        ]

    # MARK: - Reading Raven

    def slice(self, extent: ci.SourceRange) -> str:
        start, end = extent.start, extent.end
        if start.line == end.line:
            return self.lines[start.line - 1][start.column - 1:end.column - 1]
        parts = [self.lines[start.line - 1][start.column - 1:]]
        parts += self.lines[start.line:end.line - 1]
        parts.append(self.lines[end.line - 1][:end.column - 1])
        return "\n".join(parts)

    def comment_above(self, cur: ci.Cursor) -> list[str]:
        """Raven's comment lines directly above the function, verbatim, a block as /** */ and line comments as they are."""
        i = cur.extent.start.line - 2
        out: list[str] = []
        while i >= 0:
            line = self.lines[i].rstrip()
            stripped = line.strip()
            if not stripped:
                break
            if stripped.startswith("//"):
                out.insert(0, line)
                i -= 1
                continue
            if stripped.endswith("*/"):
                block = [line]
                while "/*" not in self.lines[i]:
                    i -= 1
                    block.insert(0, self.lines[i].rstrip())
                block[0] = block[0].replace("/*", "/**", 1)
                out = block + out
                i -= 1
                continue
            break
        return out

    def c_signature(self, cur: ci.Cursor) -> str:
        text = self.slice(cur.extent)
        return " ".join(text[:text.index("{")].split())

    def syscalls(self, cur: ci.Cursor) -> list[ci.Cursor]:
        found: list[ci.Cursor] = []

        def walk(node: ci.Cursor) -> None:
            if node.kind == CursorKind.CALL_EXPR and node.spelling == "syscall":
                found.append(node)
            for child in node.get_children():
                walk(child)

        walk(cur)
        return found

    # MARK: - The table

    def param(self, cur: ci.Cursor, following: ci.Cursor | None) -> Param | None:
        name = cur.spelling
        t = cur.type
        canonical = t.get_canonical()
        # A vec3_t parameter is the array type itself, and Clang keeps the typedef name on the parameter.
        if t.spelling.split()[-1] == "vec3_t":
            return Param(name, "JKAShared.vec3_t", "vec3_const" if "const" in t.spelling else "vec3_mut")
        if canonical.kind == TypeKind.POINTER:
            pointee = canonical.get_pointee()
            inner = pointee.get_canonical()
            if inner.kind == TypeKind.FUNCTIONPROTO or "vec3_t" in t.spelling:
                return None
            if inner.kind == TypeKind.CHAR_S:
                if pointee.is_const_qualified():
                    return Param(name, "String", "cstring")
                if following is not None and following.type.get_canonical().kind in INT_KINDS and SIZE_NAME.search(following.spelling):
                    return Param(name, None, "out_string", size=following.spelling)
                return None
            record = self.views.record_name(pointee)
            if record and record in self.views.views:
                return Param(name, self.views.qualified_view(record, TARGET), "view")
            if inner.kind == TypeKind.VOID:
                return Param(name, "OpaquePointer?", "bare")
            return None
        if canonical.kind in (TypeKind.RECORD, TypeKind.CONSTANTARRAY):
            return None
        swift = self.views.scalar(t, TARGET)
        if swift is None:
            return None
        if canonical.kind == TypeKind.ENUM and swift != "Bool":
            return Param(name, swift, "enum")
        return Param(name, swift, "bare")

    def result(self, cur: ci.Cursor) -> tuple[str | None, str] | None:
        """The Swift return type and the expression that maps the word into it, or None for an unmappable return."""
        t = cur.result_type
        canonical = t.get_canonical()
        if canonical.kind == TypeKind.VOID:
            return (None, "")
        if canonical.kind == TypeKind.FLOAT:
            return ("Float", "Float(bitPattern: UInt32(truncatingIfNeeded: word))")
        swift = self.views.scalar(t, TARGET)
        if swift is None:
            return None
        if swift == "Bool":
            return ("Bool", "word != 0")
        if canonical.kind == TypeKind.ENUM:
            return (swift, f"{swift}(rawValue: Int32(truncatingIfNeeded: word))")
        return (swift, f"{swift}(truncatingIfNeeded: word)")

    # MARK: - Emission

    def marker(self, cur: ci.Cursor, reason: str) -> list[str]:
        name = cur.spelling
        self.counts["TODO: Port signature"] += 1
        return [
            f"/// Source: oracle/{SOURCE}:{cur.location.line}",
            f"// TODO: Port signature",
            f"// Raven wrote: {self.c_signature(cur)}",
            f"// {reason}",
            f"public func {name}() -> Never {{",
            f"    // TODO: Port {name}",
            f'    portMissing("{name}", source: "oracle/{SOURCE}:{cur.location.line}")',
            "}",
        ]

    def trap(self, cur: ci.Cursor) -> list[str]:
        name = cur.spelling
        calls = self.syscalls(cur)
        if len(calls) != 1:
            return self.marker(cur, f"The body holds {len(calls)} syscall calls, not one.")
        params = list(cur.get_arguments())
        mapped: dict[str, Param] = {}
        for i, p in enumerate(params):
            following = params[i + 1] if i + 1 < len(params) else None
            m = self.param(p, following)
            if m is None:
                return self.marker(cur, f"No table row for `{' '.join(p.type.spelling.split())} {p.spelling}`.")
            mapped[p.spelling] = m
        result = self.result(cur)
        if result is None:
            return self.marker(cur, f"No table row for the return `{cur.result_type.spelling}`.")
        args = list(calls[0].get_arguments())
        command = self.slice(args[0].extent).strip()
        words: list[str] = []
        for arg in args[1:]:
            text = self.slice(arg.extent).strip()
            text = re.sub(r"^\(\s*[\w\s\*]+\)\s*", "", text)
            m = re.fullmatch(r"PASSFLOAT\s*\(\s*(\w+)\s*\)", text)
            if m:
                text = m.group(1)
            if re.fullmatch(r"-?\d+", text):
                words.append(text)
            elif text in mapped:
                words.append(mapped[text].word())
            else:
                return self.marker(cur, f"The syscall argument `{text}` is not a parameter.")
        for p in mapped.values():
            self.counts[p.kind] += 1
        self.counts["traps"] += 1
        signature = ", ".join(f"_ {p.name}: {p.swift}" for p in mapped.values() if p.swift)
        returns, mapping = result
        outs = [p for p in mapped.values() if p.kind == "out_string"]
        # The word is read only when Raven returned one. A filled buffer is read from the buffer.
        prefix = "    let word = " if returns else "    _ = "
        if outs and returns:
            # Raven filled the buffer and returned a count, so the trap returns both, per rule 7.
            returns = f"({returns}, String)"
            mapping = f"({mapping}, String(cString: {outs[0].name}))"
        elif outs:
            returns = "String"
            mapping = f"String(cString: {outs[0].name})"
        head = f"public func {name}({signature})" + (f" -> {returns}" if returns else "")
        call = f"Syscall.call(.{command}, {', '.join(words)})" if words else f"Syscall.call(.{command})"
        body: list[str] = []
        for p in outs:
            body.append(f"    var {p.name} = [CChar](repeating: 0, count: Int({p.size}))")
        for p in mapped.values():
            if p.kind == "vec3_mut":
                body.append(f"    var {p.name} = {p.name}")
        # Every scoped pointer wraps the call in one closure, innermost last.
        layers: list[str] = []
        for p in mapped.values():
            if p.kind == "cstring":
                layers.append(f"{p.name}.withCString {{ {p.name} in")
            elif p.kind == "vec3_const":
                layers.append(f"withUnsafePointer(to: {p.name}) {{ {p.name} in")
            elif p.kind == "vec3_mut":
                layers.append(f"withUnsafeMutablePointer(to: &{p.name}) {{ {p.name} in")
            elif p.kind == "out_string":
                layers.append(f"{p.name}.withUnsafeMutableBufferPointer {{ {p.name}Pointer in")
        if not returns:
            body += self.nest(layers, call, "    _ = ") if layers else [f"    {call}"]
        else:
            body += self.nest(layers, call, prefix) if layers else [f"{prefix.strip()} {call}"]
            body.append(f"    return {mapping}")
        lines = self.comment_above(cur)
        lines.append(f"/// Source: oracle/{SOURCE}:{cur.location.line}")
        lines.append(head + " {")
        lines += body
        lines.append("}")
        return lines

    def nest(self, layers: list[str], call: str, prefix: str) -> list[str]:
        out = [prefix + layers[0]]
        for depth, layer in enumerate(layers[1:], start=2):
            out.append("    " * depth + layer)
        out.append("    " * (len(layers) + 1) + call)
        for depth in range(len(layers), 0, -1):
            out.append("    " * depth + "}")
        return out

    def emit(self) -> list[str]:
        lines = [NOTE, "", "internal import CJKAMP_Game", "import JKAMP", "import JKAShared", ""]
        for cur in self.functions:
            lines += self.trap(cur)
            lines.append("")
        return lines


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", help="one trap name, printed to stdout, nothing written")
    args = ap.parse_args()
    gen = Traps()
    if args.only:
        for cur in gen.functions:
            if cur.spelling == args.only:
                print("\n".join(gen.trap(cur)))
                return
        raise SystemExit(f"traps.py: no trap named {args.only}")
    out = SOURCES / VIEW / "Generated" / "g_syscalls.swift"
    out.write_text("\n".join(gen.emit()).rstrip() + "\n")
    c = gen.counts
    print(f"traps.py: {c['traps']} traps, {c['TODO: Port signature']} TODO: Port signature markers, {out.relative_to(REPO)}")
    for kind in ("bare", "enum", "cstring", "out_string", "vec3_const", "vec3_mut", "view"):
        print(f"  {kind:12} {c[kind]}")


if __name__ == "__main__":
    main()
